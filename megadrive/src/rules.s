    .section .rodata
| EX_AX / EX_AZ: the 4 cells beside an explosion (W, E, N, S)
| EX_BX / EX_BZ: the 4 diagonal cells (SW, SE, NE, NW)
EX_AX:  .byte   -1, 1, 0, 0
EX_AZ:  .byte   0, 0, -1, 1
EX_BX:  .byte   -1, 1, 1, -1
EX_BZ:  .byte   1, 1, -1, -1
    .even
