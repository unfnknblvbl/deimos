| select_target: what the player would hit straight ahead -> d0.w = 1
| (Z clear) if it can be attacked: sel_kind, sel_idx; sel_locked = a
| door that is locked in the way
| (the original's target search for an attack.) A MASK_SHOT trace from
| the player toward the cell 8 ahead (clamped to the map); the first hit
| decides:
|   - a wall, the player, or a static prop: nothing;
|   - a line: a destructible one (line type ET_DESTRUCT) only with the axe
|     (T_LINE); a door (type 0) only if a monster stands in its cell
|     (that monster, T_ENT); a door that is locked sets sel_locked;
|   - an entity on the player's own cell is skipped;
|   - a person: nothing; a destructible: if bit (weapon) of its def parm
|     is set (the weapons that break it); fire (type 10): only with the
|     fire extinguisher (weapon 1); a monster: yes; anything else: nothing.
| clobbers d0, d1, a0, a1 (d2-d7 kept). Called by act_use_i.
select_target:
    movem.l d2-d7, -(sp)
    clr.b   sel_locked
    moveq   #0, d0
    move.b  S_FACING(a5), d0
    lea     DX, a0
    move.b  0(a0,d0.w), d2
    ext.w   d2
    lsl.w   #3, d2                      | x + 8 steps
    moveq   #0, d1
    move.b  S_PX(a5), d1
    add.w   d1, d2
    lea     DZ, a0
    move.b  0(a0,d0.w), d3
    ext.w   d3
    lsl.w   #3, d3                      | z + 8 steps
    move.b  S_PZ(a5), d1
    add.w   d1, d3
    tst.w   d2
    bpl.s   1f
    moveq   #0, d2
1:  cmpi.w  #31, d2
    ble.s   2f
    moveq   #31, d2
2:  tst.w   d3
    bpl.s   3f
    moveq   #0, d3
3:  cmpi.w  #31, d3
    ble.s   4f
    moveq   #31, d3
4:  move.b  S_PX(a5), d0
    move.b  S_PZ(a5), d1
    move.w  #MASK_SHOT, d4
    move.w  #NONE, d5
    bsr     trace                       | d0 = the number of hits
    move.w  d0, d7                      | n
    moveq   #0, d6                      | k
10: cmp.w   d7, d6
    bcc     st_no                       | no more hits: nothing
    lea     hit_kind, a0
    move.b  0(a0,d6.w), d0
    move.w  d6, d5
    add.w   d5, d5
    lea     hit_val, a0
    move.w  0(a0,d5.w), d5              | e
    cmpi.b  #H_WALL, d0
    beq     st_no
    cmpi.b  #H_PLAYER, d0
    beq     st_no
    cmpi.b  #H_STATIC, d0
    beq     st_no
    cmpi.b  #H_LINE, d0
    bne     20f
    movea.l line_etype, a0              | a line
    move.b  0(a0,d5.w), d0
    cmpi.b  #ET_DESTRUCT, d0
    bne.s   11f                         | not destructible
    tst.b   S_WEAPON(a5)
    bne     st_no                       | only the axe breaks it
    move.b  #T_LINE, sel_kind
    move.w  d5, sel_idx
    bra     st_yes
11: tst.b   d0
    bne     st_no                       | another kind of line: nothing
    lea     S_L_FLAGS(a5), a0
    btst    #1, 0(a0,d5.w)
    beq.s   12f                         | not locked
    move.b  #1, sel_locked
12: move.w  d6, d4                      | a monster in the doorway?
13: addq.w  #1, d4
    cmp.w   d7, d4
    bcc     st_no                       | nothing more behind
    lea     hit_kind, a0
    cmpi.b  #H_ENT, 0(a0,d4.w)
    bne.s   13b                         | not an entity
    move.w  d4, d3
    add.w   d3, d3
    lea     hit_val, a0
    move.w  0(a0,d3.w), d3
    move.w  d3, d0
    bsr     etype                       | d0 = its type
    cmpi.w  #ET_ENEMY, d0
    bne.s   13b                         | not a monster
    lea     S_E_X(a5), a0
    move.b  0(a0,d3.w), d0
    movea.l line_x, a0
    cmp.b   0(a0,d5.w), d0
    bne.s   13b                         | not in the door's cell
    lea     S_E_Z(a5), a0
    move.b  0(a0,d3.w), d0
    movea.l line_z, a0
    cmp.b   0(a0,d5.w), d0
    bne.s   13b                         | not in the door's cell
    move.b  #T_ENT, sel_kind
    move.w  d3, sel_idx
    bra     st_yes
20: lea     S_E_X(a5), a0               | an entity (not one under the player)
    move.b  0(a0,d5.w), d0
    cmp.b   S_PX(a5), d0
    bne.s   21f                         | not on the player's cell
    lea     S_E_Z(a5), a0
    move.b  0(a0,d5.w), d0
    cmp.b   S_PZ(a5), d0
    bne.s   21f
    addq.w  #1, d6
    bra     10b                         | skip it: the next hit
21: move.w  d5, d0
    bsr     etype                       | d0 = its type
    cmpi.w  #ET_HUMAN, d0
    beq.s   st_no                       | a person: nothing to attack
    move.b  #T_ENT, sel_kind
    move.w  d5, sel_idx
    cmpi.w  #ET_DESTRUCT, d0
    bne.s   22f
    lea     S_E_DEF(a5), a0
    moveq   #0, d0
    move.b  0(a0,d5.w), d0
    lsl.w   #2, d0
    movea.l def_parm, a0
    move.l  0(a0,d0.w), d1
    move.b  S_WEAPON(a5), d0
    btst    d0, d1                      | parm: a bit per weapon that can break it
    bne.s   st_yes
    bra.s   st_no
22: cmpi.w  #ET_FIRE, d0
    bne.s   23f
    cmpi.b  #1, S_WEAPON(a5)
    beq.s   st_yes                      | the fire extinguisher (weapon 1)
    bra.s   st_no
23: cmpi.w  #ET_ENEMY, d0
    beq.s   st_yes
| st_no / st_yes: the result, with the flags set from d0

st_no:
    moveq   #0, d0
    bra.s   1f
st_yes:
    moveq   #1, d0
1:  movem.l (sp)+, d2-d7
    tst.w   d0
    rts

| calc_hit_object: tiles d0.w -> d0.w = 1 if the shot breaks the object
| Hit roll against a door or thing: calc_hit with the player's accuracy
| and, as the "agility", 204/256 of it. If it hits, the result depends on
| the target: a destructible line only breaks under the axe, fire only
| under the extinguisher, anything else under any weapon but the
| extinguisher.
|   in:  d0.w = tiles to the target; sel_kind, sel_idx, S.weapon
|   out: d0.l = 1 broken (Z clear), 0 not
|   clobbers d1, a0, a1 (d2, d3 kept)
calc_hit_object:
    movem.l d2-d3, -(sp)
    move.w  d0, d3
    moveq   #0, d0
    move.b  S_ACCURACY(a5), d0
    move.w  d0, d2
    mulu.w  #204, d2                    | accuracy * 204 / 256
    lsr.w   #8, d2
    moveq   #0, d1
    move.b  S_WEAPON(a5), d1
    bsr     calc_hit                    | d0 = miss / hit / critical
    tst.w   d0
    beq.s   9f                          | a miss
    cmpi.b  #T_LINE, sel_kind
    bne.s   1f
    tst.b   S_WEAPON(a5)
    seq     d0                          | $FF if the axe
    bra.s   8f
1:  move.w  sel_idx, d0
    bsr     etype                       | d0 = its type
    cmpi.w  #ET_FIRE, d0
    bne.s   2f
    cmpi.b  #1, S_WEAPON(a5)
    seq     d0                          | $FF if the extinguisher
    bra.s   8f
2:  cmpi.b  #1, S_WEAPON(a5)
    sne     d0                          | $FF unless the extinguisher
8:  andi.w  #1, d0                      | $FF -> 1
9:  movem.l (sp)+, d2-d3
    tst.w   d0
    rts

| update_portal: Game_updateSpawnPortals - while the Reactor's portal is
| open, every few turns it brings one of the map's living monsters that
| are not yet fighting in front of it, and waits while that one lives
| (game_model.py's update_portal says what the port does differently)
| the message is TX_PORTAL_SPAWNS, the name, TX_PORTAL_END; portal_xs: the three cells
| in front of the portal tried in turn (x 16, 15, 17 at z PORTAL_SPAWN_Z)
    .section .rodata
portal_xs:  .byte   16, 15, 17
    .even
    .text
| Called at the start of every monster turn. While the monster it brought
| (S.portal_mon) is alive, nothing. S.portal_cnt counts the turns down;
| at 0: a random candidate (up_cand; rnd32 & 4095, modulo the count) is
| moved to the first free cell in front of the portal (not the player's)
| and becomes S.portal_mon; then portal_cnt = 1..4 (one rnd). With no
| candidates left the portal stops. The monster is not activated here:
| activate_visible does it when the player sees it.
| clobbers d0, d1, a0, a1 (d2-d4 kept)
update_portal:
    movem.l d2-d4, -(sp)
    tst.b   S_PORTAL(a5)
    beq     9f                          | the portal is closed
    move.w  S_PORTAL_MON(a5), d0
    cmpi.w  #NONE, d0
    beq.s   1f                          | no monster from it yet
    lea     S_E_FLAGS(a5), a0
    btst    #B_ALIVE, 0(a0,d0.w)
    bne     9f                          | its monster still lives: wait
1:  move.b  S_PORTAL_CNT(a5), d0
    subq.b  #1, S_PORTAL_CNT(a5)
    tst.b   d0
    bgt     9f                          | count > 0 before: not yet
    moveq   #0, d2                      | how many could come
    moveq   #0, d3
2:  cmp.w   n_map_ents, d2
    bcc.s   3f
    bsr     up_cand                     | Z set: a candidate
    bne.s   21f
    addq.w  #1, d3
21: addq.w  #1, d2
    bra.s   2b
3:  tst.w   d3
    bne.s   4f
    clr.b   S_PORTAL(a5)                | none left: the portal stops
    bra     9f
4:  bsr     rnd32                       | which one
    andi.l  #4095, d0
    divu.w  d3, d0                      | the remainder: which candidate (0..n-1)
    swap    d0
    move.w  d0, d4
    moveq   #-1, d2
5:  addq.w  #1, d2
    bsr     up_cand                     | Z set: a candidate
    bne.s   5b                          | not a candidate
    subq.w  #1, d4
    bpl.s   5b                          | count down to the picked one
    move.w  #NONE, S_PORTAL_MON(a5)
    moveq   #0, d4                      | the cells in front of it
6:  cmpi.w  #3, d4
    bcc.s   8f                          | every cell taken: nobody comes
    lea     portal_xs, a0
    moveq   #0, d3
    move.b  0(a0,d4.w), d3
    move.w  d3, d0
    moveq   #PORTAL_SPAWN_Z, d1
    bsr     cell_taken                  | Z clear: blocked
    bne.s   7f
    cmp.b   S_PX(a5), d3
    bne.s   61f
    cmpi.b  #PORTAL_SPAWN_Z, S_PZ(a5)
    beq.s   7f                          | the player stands there
61: move.w  d2, d0
    move.w  #PORTAL_SPAWN_Z << 8, d1
    move.b  d3, d1
