; Doom RPG for the SNES: the 3D view's pixels (view/view.h): the walls'
; columns through the compiled scalers (tools/snes_tables.py), the
; sprites' columns. The frame buffer is in bank $7F (view.h's order).
; Called from C (data bank $7E); 8-bit A/X/Y on entry and exit. ca65.
; Licence: GPL-2.0-or-later.
;
; Plain build only (the SuperFX build draws on the GSU). view/view.c works
; out, per screen column, the wall's height h and texture column (col_h,
; col_tex, col_t), then calls draw_walls; then, for each column of each
; visible sprite, it sets the ds_ variables and calls draw_spr.
;
; A "compiled scaler" is straight-line 65816 code generated by
; tools/snes_tables.py for one wall height h: it reads the texels and
; stores the pixels for every row of a column of that height, with no
; loop or arithmetic. They live in the ROM from bank $C2 on. Heights
; without a scaler (walls taller than N_SCALER, sprites taller than
; N_SPR_SCALER) are drawn by a loop here instead (the "DDA" routines:
; step a texture coordinate by a fixed amount per row).
;
; Texture coordinates are 8.8 fixed point: v's high byte is the texture
; row (0-63), dv the step per screen row (16384 / h).
;
; The scalers expect: A 8-bit with B (A's high byte) 0, X and Y 16-bit,
; X = the column's offset in the frame buffer, [DP_TEX] the texture
; column (long), (DP_RM) its colour remap in bank $7E, the data bank $7E.
; They use the direct page bytes $F0-$F6, which the linker keeps out of
; cc65's zero page (snes.cfg).

.p816
.include "banks.inc"
.include "view.inc"
.smart -
.export _draw_walls, _draw_spr, _fb_clear
.import _col_h, _col_tex, _col_t, _tex_rm, _spr_rm
.import _ds_x, _ds_top, _ds_len, _ds_s, _ds_h, _ds_data
.import _block_bank, _vc_sx0, _vc_sx1

FB       = $7F0000              ; the frame buffer (FB_BYTES, view/view.h's FB_OFF order)
TABLES   = $C20000              ; per h: first row, rows, v0, dv (8 bytes)
SCALERS  = $C28008              ; per h: the scaler's long address
                                ; (3 bytes per h at SCALERS + 3 h, h = 1..N_SCALER)
N_SCALER = 1024                 ; wall heights with a compiled scaler (1..1024)
DP_TEX   = $F0                  ; [$F0]: the texture column (long)
DP_RM    = $F3                  ; ($F3): the remap (bank $7E)
DP_END   = $F5                  ; a sprite column's end row (16 bits)
SPR_ENT  = $C30000              ; the sprite scalers' entry points (tools/snes_tables.py)
                                ; (per h at (h - 1) * 130: +2 the bank, +3 0, then
                                ; at +4 + 2 r the address to enter for top row r)
N_SPR_SCALER = 256              ; sprite heights with a compiled scaler (1..256)

.segment "LOWRAM"
scaler:   .res 3                ; jml [scaler]
cx:       .res 2                ; the screen column (0 .. VIEW_W - 1)
colbase:  .res 2                ; FB_OFF(cx, 0)
vv:       .res 2                ; the texture row, 8.8
dv:       .res 2                ; its step per screen row, 8.8
nrows:    .res 2                ; rows left to draw (draw_walls: first h)
yy:       .res 2                ; the screen row
toprow:   .res 2                ; draw_spr: the sprite column's first canvas row
endrow:   .res 2                ; draw_spr: its end (one past the last)

.segment "RODATA"
; FB_OFF(x, 0) and FB_OFF(0, y)
; (FB_OFF(x, y) = colofs[x] + rowofs[y]: an 8-pixel-wide strip is 3 x 256
; bytes; within 256 bytes, 32 rows of each of the 8 columns. Tiled
; (view.inc's FB_TILED): a strip is TILE_ROWS tiles of 64 bytes; within a
; tile, 8 rows of each of the 8 columns)
colofs:
.repeat VIEW_W, I
.if FB_TILED
    .word (I >> 3) * TILE_ROWS * 64 + (I & 7) * 8
.else
    .word (I >> 3) * 768 + (I & 7) * 32
.endif
.endrepeat
rowofs:
.repeat FB_ROWS, I
.if FB_TILED
    .word (I >> 3) * 64 + (I & 7)
.else
    .word (I >> 5) * 256 + (I & 31)
.endif
.endrepeat

.segment "CODE"

; void fb_clear(void): the frame buffer to 0 (DMA into work RAM, in
; pieces so a vblank is never kept waiting long)
; (The CPU, and so the NMI, waits while a DMA runs.) Four DMAs of
; FB_BYTES / 4 bytes (3072 at 128 wide) through the WRAM port ($2180)
; from a zero byte in the ROM.
; Clobbers A, X, Y; DMA channel 7. Called by draw_walls (exported, but C
; does not call it).
.a8
.i8
_fb_clear:
    php
    rep #$10
    .i16
    lda #0
    sta f:$002181
    sta f:$002182
    lda #1
    sta f:$002183               ; work RAM $7F0000
    lda #$08                    ; A -> B, fixed source
    sta f:$004370
    lda #$80                    ; $2180
    sta f:$004371
    ldx #.loword(zero)
    ldy #4                      ; 4 x FB_BYTES / 4 bytes
@part:
    rep #$20
    .a16
    txa
    sta f:$004372
    lda #FB_BYTES / 4
    sta f:$004375
    sep #$20
    .a8
    lda #CODE_BANK
    sta f:$004374
    lda #$80
    sta f:$00420B               ; run channel 7 (WMADD carries on from where it stopped)
    dey
    bne @part
    plp
    rts

zero:     .byte 0               ; (in the ROM: DMA can't copy work RAM to work RAM)

; fb_clear_cols: the frame buffer's columns vc_sx0 .. vc_sx1 - 1 colour 0
; (both multiples of 8: whole strips, which lie one after another in it,
; FB_ROWS bytes a column: bytes sx0 FB_ROWS .. sx1 FB_ROWS). One DMA from
; the zero byte, as _fb_clear. Clobbers A, X; DMA channel 7. (a16 i16 in
; and out.) Called by draw_walls.
.a16
.i16
fb_clear_cols:
    sep #$20
    .a8
    lda _vc_sx0                 ; sx0 x FB_ROWS (the multiplier: 8 x 8 bits)
    sta f:$004202
    lda #FB_ROWS
    sta f:$004203
    nop                         ; (8 cycles for the product)
    nop
    nop
    nop
    rep #$20
    .a16
    lda f:$004216
    sta f:$002181               ; work RAM $7F0000 + it
    sep #$20
    .a8
    lda #1
    sta f:$002183
    lda _vc_sx1                 ; (sx1 - sx0) x FB_ROWS bytes
    sec
    sbc _vc_sx0
    sta f:$004202
    lda #FB_ROWS
    sta f:$004203
    lda #$08                    ; A -> B, fixed source
    sta f:$004370
    lda #$80                    ; $2180
    sta f:$004371
    rep #$20
    .a16
    lda #.loword(zero)
    sta f:$004372
    lda f:$004216
    sta f:$004375
    sep #$20
    .a8
    lda #CODE_BANK
    sta f:$004374
    lda #$80
    sta f:$00420B               ; run channel 7
    rep #$20
    .a16
    rts

; jsl here: jml [scaler]
; (the 65816 has no indirect long call: the scaler's rtl returns to the jsl)
call_scaler:
    jml [scaler]

; set [DP_TEX] and X (the column's offset) for column cx (a16 i16)
; (more exactly: [DP_TEX] = the ROM address of col_tex[cx], a block offset,
; and colbase = FB_OFF(cx, 0); X is clobbered.) Called by draw_walls.
.a16
.i16
col_setup:
    lda cx
    asl
    asl
    tax                         ; col_tex: 4 bytes a column
    lda _col_tex,x
    sta DP_TEX
    sep #$20
    .a8
    lda _col_tex + 2,x
    clc
    adc _block_bank             ; block offset -> ROM bank
    sta DP_TEX + 2
    rep #$20
    .a16
    lda cx
    asl
    tax
    lda colofs,x
    sta colbase
    rts

; void draw_walls(void)
; Clears the frame buffer, then draws the wall column of each of the
; VIEW_W screen columns that has one (col_h[x] != 0); the floor and ceiling stay
; colour 0. In: col_h, col_tex, col_t, tex_rm (view/view.c).
; Clobbers A, X, Y, the direct page $F0-$F4. Called by view/view.c.
.a8
.i8
_draw_walls:
    php
    rep #$30
    .a16
    .i16
    lda _vc_sx0                 ; the whole view: everything colour 0
    bne :+
    lda _vc_sx1
    cmp #VIEW_W
    bne :+
    sep #$30
    .a8
    .i8
    jsr _fb_clear
    bra :++
:   jsr fb_clear_cols           ; (a strip: its columns colour 0)
:   rep #$30
    .a16
    .i16
    lda _vc_sx0
    sta cx
@col:                           ; per screen column:
    lda cx
    asl
    tax
    lda _col_h,x
    bne :+
    jmp @next                   ; no wall here
:   sta nrows                   ; (h, for now)
    jsr col_setup               ; the texture column, the frame buffer column
    ldx cx
    lda _col_t,x
    and #$00FF
    asl
    asl
    asl
    asl
    asl                         ; texture slot * 32: tex_rm's row
    clc
    adc #_tex_rm
    sta DP_RM
    lda nrows
    cmp #N_SCALER + 1
    bcs @generic                ; too tall for a compiled scaler
    sta yy                      ; scaler = SCALERS + 3 h
    asl
    adc yy
    tax
    lda f:SCALERS,x
    sta scaler
    sep #$20
    .a8
    lda f:SCALERS + 2,x
    sta scaler + 2
    lda #0                      ; B = 0 (tay in the scalers)
    xba
    lda #0
    ldx colbase
    jsl f:CODE_BANK * $10000 + call_scaler  ; draw the column
    rep #$20
    .a16
    bra @next
@generic:
    jsr column_dda              ; draw it row by row
@next:
    inc cx
    lda cx
    cmp _vc_sx1
    bcs :+
    jmp @col
:   plp
    rts

; the column's params from the table for h (in A): yy, nrows, vv, dv (a16 i16)
; (the table at TABLES + 8 h: u8 first screen row, u8 rows, u16 v at the
; first row, u16 dv.) Clobbers A, X. Called by column_dda and draw_spr.
.a16
.i16
col_params:
    asl
    asl
    asl
    tax
    lda f:TABLES,x
    and #$00FF
    sta yy
    lda f:TABLES + 1,x
    and #$00FF
    sta nrows
    lda f:TABLES + 2,x
    sta vv
    lda f:TABLES + 4,x
    sta dv
    rts

; a wall column of any height, row by row (h in nrows on entry) (a16 i16)
; In: nrows = h, [DP_TEX], (DP_RM), colbase. Out: the column in FB.
; Clobbers A, X, Y, yy, nrows, vv, dv. Called by draw_walls.
column_dda:
    lda nrows
    jsr col_params              ; yy, nrows, vv, dv for this h
    lda nrows
    bne :+
    rts                         ; no rows on screen
:
@row:                           ; per screen row:
    lda vv
    xba
    and #$00FF
    tay                         ; Y = the texture row (v's integer part)
    lda vv
    clc
    adc dv
    sta vv
    lda yy
    asl
    tax
    lda rowofs,x
    clc
    adc colbase
    tax                         ; X = FB_OFF(cx, yy)
    sep #$20
    .a8
    lda [DP_TEX],y              ; the texel (the texture's colour index)
    rep #$20
    .a16
    and #$00FF
    tay
    sep #$20
    .a8
    lda (DP_RM),y               ; -> the map's colour slot
    sta f:FB,x
    rep #$20
    .a16
    inc yy
    dec nrows
    bne @row
    rts

; void draw_spr(void): one sprite column (ds_*)
; In: ds_x (screen column), ds_top and ds_len (the canvas rows the column
; holds, of 64), ds_data (block offset of row ds_top's byte), ds_s (sprite
; slot: spr_rm's row), ds_h (the sprite's height on screen). The column's
; byte 255 is a hole (left as it is). Out: the column in FB over what is
; there (view.c calls it far to near). Clobbers A, X, Y, the direct page
; $F0-$F6. Called by view/view.c.
.a8
.i8
_draw_spr:
    php
    rep #$30
    .a16
    .i16
    lda _ds_x
    and #$00FF
    sta cx
    asl
    tax
    lda colofs,x
    sta colbase
    ; [DP_TEX] = the data of row 0 (ds_data - ds_top)
    lda _ds_top
    and #$00FF
    sta toprow
    lda _ds_len
    and #$00FF
    clc
    adc toprow
    sta endrow                  ; rows toprow..endrow-1
    lda _ds_data
    sec
    sbc toprow
    sta DP_TEX
    sep #$20
    .a8
    lda _ds_data + 2
    sbc #0
    clc
    adc _block_bank
    sta DP_TEX + 2
    rep #$20
    .a16
    lda _ds_s
    and #$00FF
    asl
    asl
    asl
    asl                         ; sprite slot * 16: spr_rm's row
    clc
    adc #_spr_rm
    sta DP_RM
    lda _ds_h
    cmp #N_SPR_SCALER + 1
    bcs @dda                    ; too tall for a compiled scaler
    ; the compiled scaler: entry for h, row top
    dec
    sta yy
    xba
    lsr                         ; (h - 1) * 128
    clc
    adc yy
    adc yy                      ; + (h - 1) * 2
    tax
    lda endrow
    sta DP_END
    sep #$20
    .a8
    lda f:SPR_ENT + 2,x
    sta scaler + 2
    rep #$20
    .a16
    txa
    clc
    adc toprow
    adc toprow
    tax
    lda f:SPR_ENT + 4,x
    sta scaler
    sep #$20
    .a8
    lda #0                      ; B = 0 (as for the walls)
    xba
    lda #0
    ldx colbase
    jsl f:CODE_BANK * $10000 + call_scaler  ; draw the column (from row top)
    plp
    rts
    .a16
@dda:                           ; row by row: A = h
    jsr col_params              ; yy, nrows, vv, dv for this h
    lda nrows
    beq @done
@row:
    lda vv
    xba
    and #$00FF
    cmp endrow
    bcs @done                   ; past the sprite's last row
    cmp toprow
    bcc @skip                   ; above its first
    tay
    sep #$20
    .a8
    lda [DP_TEX],y
    cmp #$FF
    beq @skip8                  ; a hole: leave the pixel
    rep #$20
    .a16
    and #$00FF
    tay
    lda yy
    asl
    tax
    lda rowofs,x
    clc
    adc colbase
    tax
    sep #$20
    .a8
    lda (DP_RM),y
    sta f:FB,x
@skip8:
    rep #$20
    .a16
@skip:
    lda vv
    clc
    adc dv
    sta vv
    inc yy
    dec nrows
    bne @row
@done:
    plp
    rts
