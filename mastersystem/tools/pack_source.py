"""
Packs the EDITABLE SOURCE of the level into the ROM, so the editor
(editor/) can open a ROM, change the map/art and rebuild it without any of
this project's other tools.

The container is described in tools/source_container.py (shared with the
Mega Drive port). It is written to whole banks after the sprite
banks, and the ROM directory in bank 1 ($7FC0) says where everything is.

Usage: python3 pack_source.py analysis/level01.json analysis/gamedata.json <jar_dir> <gfx_dir>
       python3 pack_source.py --dir-only <gfx_dir>   (no source, directory only)

Run by build.sh (step 3) after the sprite banks are built. Outputs, all in
gfx_dir: source_bank_NNN.bin (the container cut into 16 KB banks),
source_banks.inc (the WLA-DX .BANK/.incbin lines that place them) and
rom_dir.inc (the 16-byte ROM directory as a .db line).

ROM directory layout ("DRPGDIR1" then 8 bytes, then a u32):
  version (3: views drawn live; 2: no source), first level data bank (9),
  number of level data banks, first sprite bank, number of sprite banks,
  first source bank, number of source banks, 0; u32 container size.
The "level data banks" are the data_N.bin files tools/live_data.py wrote.
"""
import json
import struct
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from view_render import LevelTextures
from sprite_art import SpriteArt
from source_container import make_project, art_rgba, container, locked_container

BANK = 0x4000                   # one Sega-mapper bank: 16 KB


def dir_only(gfx):
    """No editor source in the ROM, just the directory.

    gfx is the build/gfx Path. Writes a version-2 directory (no level data
    banks recorded, no source banks) to rom_dir.inc, an empty
    source_banks.inc, and deletes any old source_bank_*.bin files.
    """
    sprites = sorted(int(p.stem.split("_")[-1]) for p in gfx.glob("sprite_bank_*.bin"))
    d = b"DRPGDIR1" + bytes([2, 0, 0, sprites[0], len(sprites), 0, 0, 0]) + struct.pack("<I", 0)
    (gfx / "source_banks.inc").write_text("; no editor source in this ROM\n")
    for old in gfx.glob("source_bank_*.bin"):
        old.unlink()
    with open(gfx / "rom_dir.inc", "w") as fp:
        fp.write("; generated by tools/pack_source.py\n.db " + ", ".join(f"${b:02X}" for b in d) + "\n")
    print("source: not included")


def main():
    """Build the editor-source container and place it in banks after the sprites.

    make_project (source_container.py) turns the level and game data into
    the editor's project plus its packed drawings; before writing, every
    texture and sprite is redrawn from that project and compared with
    the art the build used. Asserts if anything differs or if the source
    does not fit below bank 256.
    """
    if "--dir-only" in sys.argv:
        return dir_only(Path(sys.argv[sys.argv.index("--dir-only") + 1]))
    level_json, gamedata, jar_dir, gfx = map(Path, sys.argv[1:5])
    level = json.loads(level_json.read_text())
    g = json.loads(gamedata.read_text())
    proj, shapes = make_project(level, g, jar_dir)
    # check: the shared drawings + palettes give exactly the art the build used
    tex = LevelTextures(jar_dir)
    art = SpriteArt(jar_dir)
    for t, a in proj["textures"].items():
        assert (art_rgba(proj, shapes, a)[..., :3] == tex.texture_rgb(int(t))).all(), f"texture {t}"
    for t, a in proj["sprites"].items():
        assert (art_rgba(proj, shapes, a) == art.canvas(int(t))).all(), f"sprite {t}"
    # The Master System and Game Gear ROMs are made locked (the editor makes
    # them new and doesn't open them): a locked container in place of the
    # level's editable copy, as the editor's locked ROMs have. (The project
    # above is still made and checked against the build's art.)
    out = bytearray(locked_container())
    # statistics for the summary line only: the art references (textures,
    # sprites, one extra, weapons) and how many drawings they share
    n_refs = len(proj["textures"]) + len(proj["sprites"]) + 1 + len(proj["weapons"])
    raw_total = sum(len(v) for v in shapes.values())
    entries = [0] * (1 + len(shapes))
    n_shared = n_refs - len(shapes)
    # the first bank after the last sprite bank
    first = 1 + max(int(p.stem.split("_")[-1]) for p in gfx.glob("sprite_bank_*.bin"))
    n = (len(out) + BANK - 1) // BANK      # banks needed, rounded up
    # 256 banks: the most the Sega mapper's bank register can select (4 MB)
    assert first + n <= 256, "no room left in the 4 MB ROM for the editor source"
    data = bytes(out).ljust(n * BANK, b"\0")
    for old in gfx.glob("source_bank_*.bin"):
        old.unlink()
    with open(gfx / "source_banks.inc", "w") as fp:
        for i in range(n):
            (gfx / f"source_bank_{first + i:03d}.bin").write_bytes(data[i * BANK:(i + 1) * BANK])
            fp.write(f".BANK {first + i} SLOT 2\n.ORGA $8000\n.incbin \"build/gfx/source_bank_{first + i:03d}.bin\"\n\n")
    # ROM directory (bank 1, $7FC0): where the generated parts are
    # version 3: no pre-drawn views; the level's data banks are 3 and
    # 9 .. (data banks), then the sprite sets (large and small view)
    sprites = sorted(int(p.stem.split("_")[-1]) for p in gfx.glob("sprite_bank_*.bin"))
    data = sorted(int(p.stem.split("_")[-1]) for p in (gfx / "live").glob("data_*.bin"))
    d = b"DRPGDIR1" + bytes([3, 9, data[-1] - 8, sprites[0], len(sprites), first, n, 0]) + \
        struct.pack("<I", len(out))
    with open(gfx / "rom_dir.inc", "w") as fp:
        fp.write("; generated by tools/pack_source.py\n.db " + ", ".join(f"${b:02X}" for b in d) + "\n")
    print(f"source: {len(entries)} entries ({n_shared} drawings shared between palettes), "
          f"{raw_total // 1024} KB -> {len(out) // 1024} KB in banks {first}..{first + n - 1}")


if __name__ == "__main__":
    main()
