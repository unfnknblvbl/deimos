| kill_on_tile: the first two things at (d0.b, d1.b) that a kill shows on die
| (the original's SHOW command clears the cell first: of the first two
| entities in the cell's list, those whose type is in MASK_SHOW_KILL -
| monsters and destructibles - die or are destroyed.)
|   in:  d0.b, d1.b = the cell
|   clobbers d0, d1, a0, a1 (d2-d5 kept). Called by ec_7.
kill_on_tile:
