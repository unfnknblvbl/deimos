| spawn_drop: a dead monster d0.w may leave something (random)
| (the original's drop table). rnd32 is always drawn. Nothing drops
| when the monster dropped before (F_DROPPED), for classes 1 (dogs), 12
| (Cyberdemon) and 13 (Kronos), or when the first byte < 51. Otherwise the
| other three bytes (n = rnd >> 8) choose a DD_* kind: odd n gives health,
| armour or credits (n5 = (n >> 1) & $FF), even n depends on the class.
| The thing goes into the next of the N_DROPS (8) drop slots after the map
| entities, in turn (S.drop_index): the oldest drop there is replaced.
|   in:  d0.w = the dead monster's entity
