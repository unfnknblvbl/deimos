1:  move.w  d6, d0
    bsr     destroy                     | destroyed
9:  move.l  (sp)+, d6
    rts

| exec_cmd: run command d0.w -> d0.w = 1 (Z clear) if it counts as run
| Runs one event command (opcode 0..41; others do nothing). The handlers
| below share these registers: d3 = op, d4 = a1, d5 = a1 bits 0..7
| ("lo": usually x, a line or a string id), d6 = a1 bits 8..15 ("hi":
| usually z). They may set suspend (SUSP_*), dialog_str, pw_want and
| skip_turn. Every handler ends at ec_ret1 or ec_ret0.
|   in:  d0.w = command index (into cmd_op, cmd_a1, cmd_a2)
|   out: d0.l = 1 (Z clear) it ran, 0 (Z set) it did nothing
|   clobbers d0, d1, a0, a1 (d2-d7 kept)
| Called by run_event.
exec_cmd:
    movem.l d2-d7, -(sp)
    move.w  d0, d7                      | c
    movea.l cmd_op, a0
    moveq   #0, d3
    move.b  0(a0,d7.w), d3              | op
    move.w  d7, d0
    lsl.w   #2, d0
    movea.l cmd_a1, a0
    move.l  0(a0,d0.w), d4              | a1
    moveq   #0, d5
    move.b  d4, d5                      | lo
    move.w  d4, d6
    lsr.w   #8, d6                      | hi
    cmpi.w  #41, d3
    bhi     ec_ret1                     | an unknown opcode: counts as run
    move.w  d3, d0
    add.w   d0, d0
    lea     ec_tab, a0
    move.w  0(a0,d0.w), d0
    jmp     0(a0,d0.w)                  | to the handler (offsets from ec_tab)
| ec_tab: the handler of each opcode, as word offsets from ec_tab. The
| opcodes that do nothing here go to ec_ret1: 0, 25, 27 SAVEGAME,
| 28, 29, 35 PARTICLES, 36 REFRESHVIEW, 37 WAIT (no real-time pause).
ec_tab:
    .word   ec_ret1-ec_tab, ec_1-ec_tab, ec_2-ec_tab, ec_3-ec_tab             | 0-3
    .word   ec_4-ec_tab, ec_5-ec_tab, ec_door-ec_tab, ec_7-ec_tab             | 4-7
    .word   ec_8-ec_tab, ec_9-ec_tab, ec_10-ec_tab, ec_state-ec_tab           | 8-11
    .word   ec_12-ec_tab, ec_13-ec_tab, ec_14-ec_tab, ec_door-ec_tab          | 12-15
    .word   ec_door-ec_tab, ec_door-ec_tab, ec_18-ec_tab, ec_state-ec_tab     | 16-19
    .word   ec_state-ec_tab, ec_stat-ec_tab, ec_stat-ec_tab, ec_23-ec_tab     | 20-23
    .word   ec_24-ec_tab, ec_ret1-ec_tab, ec_8-ec_tab, ec_ret1-ec_tab         | 24-27
    .word   ec_ret1-ec_tab, ec_ret1-ec_tab, ec_30-ec_tab, ec_31-ec_tab        | 28-31
    .word   ec_32-ec_tab, ec_33-ec_tab, ec_34-ec_tab, ec_ret1-ec_tab          | 32-35
    .word   ec_ret1-ec_tab, ec_ret1-ec_tab, ec_38-ec_tab, ec_39-ec_tab        | 36-39
    .word   ec_40-ec_tab, ec_41-ec_tab                                        | 40-41

