"""
The level's data pack: everything that depends on the level, in one block
at the end of the ROM, so the editor can replace the level (map, art,
text) without a compiler. The code finds the pack through the ROM
directory in the cartridge header's notes field ($1C8):

  $1C8  "MDRPGDIR"  u32 pack address  u32 end of the space the pack may use

Pack (big-endian, starts on a 64 KB boundary):
  0   "MDPK", u16 version (1), u16 number of entries (N_ENTRIES)
  8   u16 n_walls, n_tex, n_spr, n_scenery, floor colour, ceiling colour
  32  per entry: u32 offset (from the pack start), u32 size
  then the entries, each 4-aligned, in ENTRIES order.
The last entry is the editable level (tools/source_container.py).

Usage: md_pack.py analysis/level01.json analysis/gamedata.json <jar dir> build/gen
Writes build/gen/pack.bin and build/gen/pack.s.
Licence: GPL-2.0-or-later.
"""
import json
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from source_container import make_project, container

VERSION = 1  # the pack format's version, written in its header
# the pack's entries, in order (the ROM looks them up by index)
ENTRIES = ["walls", "tex", "tex_pal", "tex_hist", "spr_cols", "spr_off", "spr_data", "spr_coff",
           "pvs_index", "pvs", "spr_pal", "spr_hist", "scenery", "def_spr", "vis_index", "vis",
           "level", "strings", "wp_frames", "wp_sprites", "wp_pal", "wp_tiles", "source"]
HEAD = 32 + 8 * len(ENTRIES)  # header size: 32 fixed bytes plus the directory
PACK_LIMIT = 0x200000          # battery RAM is mapped from $200000


def build(blobs, counts):
    """Assembles the pack from `blobs` (entry name -> bytes; every entry of
    ENTRIES must be there) and `counts` (the n_walls, n_tex, n_spr,
    n_scenery, floor and ceiling numbers, and optionally "swaps").
    Header bytes 20..31: byte 20 the number of texture swaps, then two
    bytes (from, to) per swap (at most 5 fit). Returns the pack's bytes.
    """
    out = bytearray(HEAD)
    out[0:8] = b"MDPK" + struct.pack(">HH", VERSION, len(ENTRIES))
    out[8:20] = struct.pack(">6H", counts["n_walls"], counts["n_tex"], counts["n_spr"], counts["n_scenery"],
                            counts["floor"], counts["ceiling"])
    sw = counts.get("swaps", [])            # the portal's texture swaps (tools/md_campaign.py)
    out[20] = len(sw)
    for k, (a, b) in enumerate(sw):
        out[21 + 2 * k], out[22 + 2 * k] = a, b
    for i, name in enumerate(ENTRIES):
        out += bytes(-len(out) % 4)  # pad to a multiple of 4
        struct.pack_into(">II", out, 32 + 8 * i, len(out), len(blobs[name]))
        out += blobs[name]
    out += bytes(-len(out) % 4)
    return bytes(out)


def main():
    """md_pack.py <level json> <gamedata json> <jar dir> <gen dir>: reads the
    renderer tables from <gen>/pack/ (build_render_data.py), the rules'
    level.bin and strings.bin from <gen>, builds the editable level
    (source_container), and writes <gen>/pack.bin plus pack.s, which puts
    it into the ROM's .pack section. (This is the single-level form, from
    before the campaign: build.sh no longer runs it; tools/md_campaign.py
    builds the campaign block instead.)
    """
    level_json, gamedata, jar_dir, gen = map(Path, sys.argv[1:5])
    pk = gen / "pack"
    counts = json.loads((pk / "counts.json").read_text())
    blobs = {n: (pk / f"{n}.bin").read_bytes() for n in ENTRIES if (pk / f"{n}.bin").exists()}
    blobs["level"] = (gen / "level.bin").read_bytes()
    blobs["strings"] = (gen / "strings.bin").read_bytes()
    proj, shapes = make_project(json.loads(level_json.read_text()), json.loads(gamedata.read_text()), jar_dir)
    blobs["source"] = container(proj, shapes)
    data = build(blobs, counts)
    (gen / "pack.bin").write_bytes(data)
    (gen / "pack.s").write_text("| generated by tools/md_pack.py: the level's data pack\n"
                                "    .section .pack, \"a\"\n    .global md_pack\nmd_pack:\n"
                                "    .incbin \"build/gen/pack.bin\"\n")
    print(f"data pack: {len(data) // 1024} KB (editable level {len(blobs['source']) // 1024} KB)")


if __name__ == "__main__":
    main()
