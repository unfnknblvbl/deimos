| berserk_tick: Player_updateBerserkerTics
| (S.berserk counts the turns left; called at the end of every turn.)
| clobbers d0, d1, a0, a1 (C call when it runs out)
berserk_tick:
    tst.b   S_BERSERK(a5)
    beq.s   9f
    subq.b  #1, S_BERSERK(a5)
    bne.s   9f                          | still going
    SAYT    TX_BERSERK_OFF
9:  rts

| use_item_i: the Berserker (d0.b = 3) or the collar (4) -> d0.w = 1 if used
| (the C entry point use_item; the ITEMS menu of ui.c.)
| 3: the Berserker: x 3 damage for 31 more turns; takes a turn.
| 4: the collar: the first entity or line in the next cell (a
|    MASK_SHOT trace) must be a dog (class 1). It leaves the map and
|    becomes a weapon: 9, 10 or 11 by its variant (parm 294, 467, other),
|    with "ammo" 5 = its health x 5 (low byte, at most 99). A dialog
|    (TX_CAPTURED, the name, TX_CAPTURED_END, DLG_CAPTURED with captured_def) opens; the
|    turn passes when it closes (monsters_pending).
|   in:  d0.b = inventory slot (3 or 4)
|   out: d0.l = 1 used, 0 not
|   clobbers d0, d1, a0, a1 (d2-d7 kept)
use_item_i:
    movem.l d2-d7, -(sp)
    andi.w  #0xFF, d0
    move.w  d0, d7
    lea     S_INVENTORY(a5), a0
    tst.b   0(a0,d7.w)                  | any left?
    bne.s   1f
    SAY     s_none                      | "YOU HAVE NONE"
    bra     90f
1:  cmpi.w  #3, d7
    bne.s   2f
    SAYT    TX_BERSERK_ON                   | the Berserker: x3 damage for 31 turns
    addi.b  #31, S_BERSERK(a5)
    subq.b  #1, S_INVENTORY+3(a5)       | one fewer
    bsr     end_player_turn             | the monsters' turn
    bra     91f
2:  cmpi.w  #4, d7
    bne     90f                         | another slot: nothing
    moveq   #0, d0                      | the collar: the first thing ahead
    move.b  S_FACING(a5), d0
    lea     DX, a0
    move.b  S_PX(a5), d2
    add.b   0(a0,d0.w), d2
    lea     DZ, a0
    move.b  S_PZ(a5), d3
    add.b   0(a0,d0.w), d3
    move.b  S_PX(a5), d0
    move.b  S_PZ(a5), d1
    move.w  #MASK_SHOT, d4
    move.w  #NONE, d5
    bsr     trace                       | what is in the cell ahead
    moveq   #0, d6
    lea     hit_kind, a1
3:  cmp.b   hit_n, d6                   | every hit looked at: nothing
    bcc.s   4f
    move.b  0(a1,d6.w), d0
    cmpi.b  #H_ENT, d0
    beq.s   5f                          | an entity
    cmpi.b  #H_LINE, d0
    beq.s   6f                          | a door or wall line
    addq.w  #1, d6
    bra.s   3b                          | (others: skip)
4:  SAYT    TX_NO_DOG
    bra     90f
6:  SAYT    TX_BAD_TARGET
    bra     90f
5:  move.w  d6, d0
    add.w   d0, d0
    lea     hit_val, a0
    move.w  0(a0,d0.w), d6              | j
    move.w  d6, d0
    bsr     etype                       | d0 = its type
    cmpi.w  #ET_ENEMY, d0
    bne.s   6b                          | not a monster: a bad target
    move.w  d6, d0
    bsr     esub                        | d0 = its class
    cmpi.w  #1, d0
    beq.s   7f                          | 1: a dog
    move.w  d6, d0
    bsr     ent_name                    | a0 = its name
    movea.l a0, a1
    TXT     TX_WONT_FIT, a0
    bsr     say2_a                      | TX_WONT_FIT <name>
    bra     90f
7:  subq.b  #1, S_INVENTORY+4(a5)       | the dog leaves the map and fights for you
    move.w  d6, d0
    bsr     deactivate                  | off the active list
    move.w  d6, d0
    bsr     ent_unlink                  | off the map
    lea     S_E_DEF(a5), a0
    moveq   #0, d0
    move.b  0(a0,d6.w), d0
    move.b  d0, captured_def            | (the dialog names it)
    lsl.w   #2, d0
    movea.l def_parm, a0
    move.l  0(a0,d0.w), d0
    moveq   #9, d1                      | Hell Hound (parm 294)
    cmpi.l  #294, d0
    beq.s   71f
    moveq   #10, d1                     | Cerberus (parm 467)
    cmpi.l  #467, d0
    beq.s   71f
    moveq   #11, d1                     | the third dog (any other parm)
71: move.b  d1, S_WEAPON(a5)            | the dog in hand
    move.w  S_WEAPONS(a5), d0
    bset    d1, d0
    move.w  d0, S_WEAPONS(a5)           | carried
    move.w  d6, d0
    bsr     mon_slot                    | d0 = its monster slot
    lea     S_M_HP(a5), a0
    moveq   #0, d1
    move.b  0(a0,d0.w), d1
    mulu.w  #5, d1
    andi.w  #0xFF, d1                   | (the low byte, as the original)
    cmpi.w  #99, d1
    bls.s   72f
    moveq   #99, d1
72: move.b  d1, S_AMMO+5(a5)            | the dog's health
    move.b  #DLG_CAPTURED, dialog_str   | TX_CAPTURED, the name, TX_CAPTURED_END
    clr.b   pend_valid                  | (no event to resume)
    move.b  #1, skip_turn
    move.b  #1, monsters_pending        | the turn passes when it closes
    bsr     berserk_tick                | the Berserker counts this turn too
    bra.s   91f
90: moveq   #0, d0
    bra.s   99f
91: moveq   #1, d0
99: movem.l (sp)+, d2-d7
    rts

| store_buy_i: buy line d0.w of the open vendor's list (STORE_LINES) ->
| d0.w = 0 bought, 1 too few credits, 2 has too many already
| (the C entry point store_buy; ui.c's vendor menu.) S.store picks the
| vendor's 32 bytes in STORE_LINES; the tag picks the 2 bytes of
| STORE_ITEMS: kind 1 an inventory item (what = its subtype 25..29), 2
| ammunition (what = ammo type; 10 rounds, 3 rockets), 3 a stat point
| (what 1..4 = defence, agility, strength, accuracy, through STAT_OFF).
| Refused when the price is above the credits, or the thing is at 99.
|   in:  d0.w = the line
|   clobbers d0, d1, a0, a1 (d2-d4 kept)
store_buy_i:
    movem.l d2-d4, -(sp)
    moveq   #0, d1
    move.b  S_STORE(a5), d1
    lsl.w   #5, d1                      | 16 lines of (tag, price) per vendor
    lea     STORE_LINES, a0
    adda.w  d1, a0
    add.w   d0, d0
    moveq   #0, d2
    move.b  0(a0,d0.w), d2              | tag
    moveq   #0, d3
    move.b  1(a0,d0.w), d3              | price
    lea     STORE_ITEMS, a0
    add.w   d2, d2
    moveq   #0, d4
    move.b  0(a0,d2.w), d4              | kind: 1 item, 2 ammo, 3 stat
    move.b  1(a0,d2.w), d2              | what
    andi.w  #0xFF, d2
    cmpi.w  #1, d4                      | have
    bne.s   1f
    lea     S_INVENTORY-25(a5), a1
    adda.w  d2, a1
    bra.s   3f                          | a1 = S.inventory[what - 25]
1:  cmpi.w  #2, d4
    bne.s   2f
    lea     S_AMMO(a5), a1
    adda.w  d2, a1
    bra.s   3f                          | a1 = S.ammo[what]
2:  lea     STAT_OFF-1, a0
    moveq   #0, d0
    move.b  0(a0,d2.w), d0
    lea     0(a5,d0.w), a1              | a1 = the stat's byte in S
3:  moveq   #1, d0
    cmp.w   S_CREDITS(a5), d3
    bhi.s   9f                          | price > credits
    moveq   #2, d0
    cmpi.b  #99, (a1)
    beq.s   9f                          | already 99
    sub.w   d3, S_CREDITS(a5)           | pay
    cmpi.w  #2, d4
    beq.s   4f
    addq.b  #1, (a1)                    | (an item, or a stat point)
    bra.s   8f
4:  move.w  d2, d0                      | ammo: 10 (3 rockets)
    moveq   #10, d1
    cmpi.w  #3, d2
    bne.s   41f
    moveq   #3, d1
41: bsr     add_ammo                    | (at most 99)
8:  moveq   #0, d0
9:  movem.l (sp)+, d2-d4
    rts

| store_close_i: the vendor's menu closes: the turn goes on
| (the C entry point store_close.) S.store = $FF ends the modal state; the
| monsters' turn that was owed now runs (settle_i).
| clobbers d0, d1, a0, a1
store_close_i:
    clr.b   S_SECRET_TURN(a5)
    move.b  #NONE_B, S_STORE(a5)
    bra     settle_i                    | (tail call)

