/*
 * The Mega Drive game - the game rules' interface to C.
 *
 * The rules (moving, fighting, doors, events, vendors, map changes) are a
 * re-implementation of the original game's rules. They started as C shared
 * with the Master System port and are now 68000 assembler in src/rules.s;
 * this header declares what C (src/ui.c, src/save.c, src/sound.c) may use:
 * the game state S, the rules' entry points, the flags they leave for the
 * user interface, and the constants of the state's fields.
 *
 * The rules were written from tools/game_model.py (the executable spec),
 * which was itself written from reading the J2ME original and the GPL
 * DoomRPG-RE project. The ROM's state is compared byte for byte against
 * that model after every move by the "lockstep" tests
 * (tools/md_lockstep.py, tools/md_campaign_lockstep.py: the ROM runs in an
 * emulator, the model in Python, both get the same inputs), so keep the
 * two in step when changing rules.
 *
 * Licence: GPL-2.0-or-later (see LICENSE).
 */
#ifndef GAME_H
#define GAME_H

#include "md.h"
#include "state.h"      /* struct state (generated by tools/gen_cdata.py) */
#include "sfx.h"        /* SFX_* sound effect ids (tools/build_sfx.py) */
#include "texts.h"      /* TX_* the game's texts' indices (../tools/game_text.py) */

/* All rule state lives in one struct; the test harness finds it in the
   link map and reads it straight out of RAM. The saved game is this struct
   as it is (src/save.c). */
extern struct state S;

/* entity types (def_etype): what kind of thing an entity definition is */
#define ET_LINE 0           /* the def is a door or other line, not a thing */
#define ET_ENEMY 1          /* a monster */
#define ET_HUMAN 2          /* a person to talk to */
#define ET_PICKUP 3         /* used at once (health, armour, credits) */
#define ET_INV 4            /* an inventory item (medkits, Berserker, collar) */
#define ET_WEAPON 5
#define ET_AMMO 6
#define ET_FIRE 10          /* fire hazards (hurt whoever stands in them) */
#define ET_FIRE2 11
#define ET_DESTRUCT 12      /* a destructible prop (barrel, crate, coupling) */
#define ET_AMMO2 16         /* ammunition dropped by a monster or crate */

/* entity flag bits (S.e_flags) */
#define F_ALIVE 0x01        /* on the map and able to act / be hit */
#define F_HIDDEN 0x02       /* hidden until an event shows it */
#define F_LINKED 0x04       /* in its cell's entity list (ui.c draws only these) */
#define F_ACTIVE 0x08       /* on the active list (S.active: takes monster turns) */
#define F_ATK2 0x10         /* a monster that uses its second attack this turn */
#define F_DROPPED 0x20      /* a dropped thing in one of the slots after the map's */
#define F_CORPSE 0x40       /* a dead monster's body */
#define F_RAISING 0x80      /* being raised from the dead (by an Arch-Vile) */

/* line flag bits (S.l_flags) */
#define L_OPEN 1            /* open: does not block, its wall is not drawn */
#define L_LOCKED 2          /* locked: needs a key or a code */
#define L_ALIVE 4           /* not yet destroyed (a destructible line) */

#define NO_DEF 0xFF         /* an entity slot with no definition (unused) */

/* trace masks (bit n = entity type n blocks; bit 8 = the player): what
   stops a line traced across the map for a move, a monster's move, a shot
   and so on. Bits 14 and 15 are the two kinds of invisible thin wall. */
#define MASK_PLAYER_MOVE 0xF287
#define MASK_MONSTER_MOVE 0xFF87
#define MASK_SHOT 0x5687
#define MASK_SHOW_KILL 4098         /* $1002: monsters and destructibles */
#define MASK_RAISE_FREE 16263       /* $3F87 */

/* event trigger bits: a command of an event runs only if its a2 shares a
   bit with the trigger */
#define EVF_USE 0x100UL     /* the player used the cell (A) */
#define EVF_MODIFY 0x200UL  /* (in a command's a2: a one-shot command) */
#define EVF_MOVE 0x400UL    /* the player stepped into the cell */

/* trace hit kinds (hit_kind[]) */
#define H_WALL 0            /* a wall cell */
#define H_PLAYER 1          /* the player */
#define H_LINE 2            /* a closed line */
#define H_STATIC 3          /* a static prop or thin wall */
#define H_ENT 4             /* an entity */

/* why an event stopped (suspend) */
#define SUSP_NONE 0
#define SUSP_DIALOG 1       /* it opened a dialog: resume() when it closes */
#define SUSP_PASSWORD 2     /* it asks for a door code: resume(code) */
#define SUSP_STOP 3

/* attack target kinds */
#define T_PLAYER 0          /* the player */
#define T_ENT 1             /* an entity (monster, dog, barrel...) */
#define T_RAISE 2           /* a corpse being raised */
#define T_LINE 3            /* a destructible line */

/* rules.s (the C entry points; the rest uses its own register conventions) */
extern u8 hit_n, hit_kind[8];      /* the last trace: how many things it met, and their kinds */
extern u8 captured_def;            /* the dog the collar caught (DLG_CAPTURED) */
extern u8 map_id;                  /* the original game's id of the map in play */
extern const u8 STORE_LINES[];     /* per vendor 16 x (name tag, price), tag 0 ends */
#define DLG_CAPTURED 0xFE          /* dialog_str: TX_CAPTURED, the name, TX_CAPTURED_END */
/* what the last action left for the user interface (0xFF: nothing):
   dialog_str  a level string to show in a dialog box (or DLG_CAPTURED);
   pw_want     a door code is wanted; pw_prompt the string asking for it;
   suspend     why the running event stopped (SUSP_*);
   skip_turn   the event opened a dialog: the monsters' turn waits;
   monsters_pending  the monsters still have their turn to take */
extern u8 dialog_str, pw_want, pw_prompt, suspend, skip_turn, monsters_pending;
/* the event waiting to go on (pend_valid 1): its index, its command, why */
extern u8 pend_valid, pend_ev, pend_k, pend_why;
extern u32 pend_flags;
extern char status_msg[33];        /* a message the rules made up for the message line */
extern u8 status_new;              /* 1: status_msg is new (ui.c queues it, clears this) */
extern u8 player_hurt;             /* 1: the player took damage (ui.c: red flash, face) */
extern u8 player_fired;            /* 1: the player fired (ui.c: the weapon's firing frame) */

/* the actions (one turn each, the monsters move after), all in rules.s */
void game_init(void);              /* a fresh game: the first map, a new player */
void game_restore(void);           /* S was just loaded: rebuild the map's tables */
void act_turn(s8 delta);           /* turn right (+1) or left (-1) */
u8 act_move(u8 back);              /* step forward (0) or back (1) -> 1 if moved */
void act_use(void);                /* use or attack what is ahead */
void act_pass(void);               /* wait a turn */
void act_cycle_weapon(s8 step);    /* the next usable weapon, +1 or -1 */
u8 act_health_item(void);          /* use the smallest medkit -> 1 if one was used */
void resume(const char *password); /* a dialog closed (0) or a code was entered */
void settle(void);                 /* after a dialog: the monsters' turn, if due */
u8 modal(void);                    /* 1 while a dialog, code entry or vendor is open */
u8 use_item(u8 k);                 /* 3 the Berserker, 4 the collar -> 1 used */
u8 store_buy(u8 line);             /* -> 0 bought, 1 too few credits, 2 too many */
void store_close(void);            /* the vendor's menu closed: the turn goes on */
void map_change(u8 map);           /* through the exit (S.exit) to map `map` */

/* messages (ui.c): queued for the message line above the view, shown one
   at a time (the parts are joined, 31 characters at most) */
void say(const char *s);
void say2(const char *a, const char *b);
void say3(const char *a, const char *b, const char *c);
void say_num(const char *a, u16 n, const char *b);
void sfx(u8 id);          /* queue a sound effect (SFX_*; sound.c) */

/* strings bank: the map's string id -> its text (ui.c) */
const char *level_string(u8 id);
/* the game's text id (TX_*), read from DoomRPG.jar by the build: in the
   campaign block's texts table (pack.c); the pointer stays valid */
const char *gtext(u8 id);

#endif
