"""
The Virtual Boy's sound tables (obj/snd_tab.c, for src/sound.c), made
from the Mega Drive game's FM instruments (megadrive/build/gen/
music_data.s: the port's own, no part of the original game; the music and
the effects themselves are read from the SNES image's spc_streams at run
time):

  snd_wave[5][32]   the VSU's five waves (6-bit samples): each instrument's
                    steady tone (snes_sound.py's render_period: one period
                    of its FM sound, two when an operator runs at half
                    speed), band-limited to 32 samples; the instruments
                    grouped into five by likeness (the VSU holds five
                    waves), each group's wave its middle one's
  snd_inst[n][4]    per instrument: its wave (0..4), 1 if the wave holds
                    two periods (played an octave lower), the envelope's
                    step time (0 steady, 1..7 falling: the Game Boy
                    Color's gb_sound.py pace) and its base attenuation
                    (0.75 dB steps)
  snd_drum[9][3]    the noise drums (the Mega Drive game's 8, then the
                    kick and toms): the envelope (EV0), the frequency's
                    register value / 8, the tap (0..7)
  snd_per[96]       the period (156250 / Hz: a 32-sample wave's frequency
                    register is 2048 - period) of MIDI notes 48..59 in
                    1/8 semitones (an octave down: twice)
  snd_vol[128]      attenuation -> the channel's volume 0..15

Usage: vb_sound.py <megadrive build/gen dir> OUT.c
Licence: GPL-2.0-or-later.
"""
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "gbc" / "tools"))
import snes_sound as SS  # noqa: E402
import gb_sound as GB  # noqa: E402

N_WAVES = 5
# the noise drums from the Game Boy Color's (gb_sound.py's NR42 / NR43
# pairs): NR42's start volume and pace become EV0; NR43's clock the
# frequency; its 7-bit width a short tap
def drum(nr42, nr43):
    """A Game Boy noise preset -> (EV0, frequency register / 8, tap)."""
    vol, down, pace = nr42 >> 4, not (nr42 & 8), nr42 & 7
    ev0 = (vol << 4) | (0 if down else 8) | max(0, pace - 1)
    s, wide, r = nr43 >> 4, not (nr43 & 8), nr43 & 7
    hz = 524288 / (r if r else 0.5) / 2 ** (s + 1)       # (the Game Boy's noise clock)
    f = max(0, min(2047, round(2048 - 500000 / hz)))      # (the VSU's: 500 kHz / (2048 - f))
    return ev0, f >> 3, 0 if wide else 4


def wave_of(patch):
    """An instrument's 32-sample wave (zero mean, -1..1) and its periods (1 or 2)."""
    out, periods = SS.render_period(patch, 512)
    w = SS.band_limit(out, 32, 10 * periods)
    m = np.abs(w).max()
    return (w / m if m else w), periods


def main():
    """Write OUT.c with the tables."""
    gen, out = Path(sys.argv[1]), Path(sys.argv[2])
    patches = SS.patches_of((gen / "music_data.s").read_text())
    waves = [wave_of(p) for p in patches]
    # group the waves: the five most different first (farthest from those chosen), then each to the nearest
    dist = np.array([[np.sum((a[0] - b[0]) ** 2) + (0 if a[1] == b[1] else 100) for b in waves] for a in waves])
    chosen = [0]
    while len(chosen) < min(N_WAVES, len(waves)):
        chosen.append(int(np.argmax(dist[:, chosen].min(1))))
    group = [int(np.argmin([dist[i, c] for c in chosen])) for i in range(len(waves))]
    samples = []
    for c in chosen:
        w = waves[c][0]
        samples.append([max(0, min(63, round(31.5 + 31.5 * v))) for v in w])
    while len(samples) < N_WAVES:
        samples.append([32] * 32)
    inst = []
    for i, p in enumerate(patches):
        _duty, pace, att = GB.instrument(p)
        inst.append((group[i], 1 if waves[i][1] == 2 else 0, pace, att))
    per = [round(156250 / (440 * 2 ** ((48 + i / 8 - 69) / 12))) for i in range(96)]
    vol = [max(0, min(15, round(15 * 10 ** (-0.75 * a / 20)))) for a in range(128)]
    c = ["/* generated by vb/tools/vb_sound.py: do not edit */", '#include "../../core/types.h"',
         "const u8 snd_wave[5][32] = {%s};" % ", ".join("{%s}" % ", ".join(map(str, s)) for s in samples),
         "const u8 snd_n_inst = %d;" % len(inst),
         "const u8 snd_inst[%d][4] = {%s};" % (len(inst), ", ".join("{%d, %d, %d, %d}" % t for t in inst)),
         "const u8 snd_drum[9][3] = {%s};" % ", ".join("{0x%02X, %d, %d}" % drum(*d) for d in GB.DRUMS),
         "const u16 snd_per[96] = {%s};" % ", ".join(map(str, per)),
         "const u8 snd_vol[128] = {%s};" % ", ".join(map(str, vol))]
    out.write_text("\n".join(c) + "\n")


if __name__ == "__main__":
    main()
