    SFX     SFX_BUMP                    | blocked: the bump sound
    moveq   #0, d0
    bra.s   9f
2:  SFX     SFX_STEP                    | the footstep sound
    lea     LEAVE_FLAG, a0
    moveq   #0, d2
    move.b  0(a0,d7.w), d2              | leaving in direction d
    ori.w   #EVF_MOVE, d2
    move.b  S_PX(a5), d0
    move.b  S_PZ(a5), d1
    bsr     run_tile                    | the old cell's event
    move.b  d6, S_PX(a5)                | the player is now on the new cell
    move.b  d5, S_PZ(a5)
    lea     ARRIVE_FLAG, a0
    moveq   #0, d2
    move.b  0(a0,d7.w), d2              | arriving in direction d
    ori.w   #EVF_MOVE, d2
    moveq   #0, d0
    move.b  S_FACING(a5), d0
    lsl.w   #2, d0
    lea     FACING_FLAG, a0
    or.l    0(a0,d0.w), d2              | and the facing bit
    move.b  d6, d0
    move.b  d5, d1
    bsr     run_tile                    | the new cell's event
    moveq   #1, d0
    bsr     touch_tile                  | pick up everything there (or get burnt)
    bsr     end_player_turn             | the monsters' turn
    moveq   #1, d0
9:  movem.l (sp)+, d2-d7
    rts

| act_use_i: use or attack what is ahead
| (the C entry point act_use; button A.) First the event of the cell in
| front runs with trigger $500 (EVF_USE + EVF_MOVE): that is how doors,
| switches, terminals and people work. If no command ran, the weapon is
| used on what select_target finds; with nothing to attack: TX_NOTHING
| (or "THE DOOR IS LOCKED"), and no turn passes. A dialog opened by
| the event (skip_turn) also holds the turn until it closes.
| clobbers d0, d1, a0, a1 (d2 kept)
act_use_i:
    move.l  d2, -(sp)
    clr.b   skip_turn
    moveq   #0, d0
    move.b  S_FACING(a5), d0
    lea     DX, a0
    move.b  0(a0,d0.w), d1
    lea     DZ, a0
    move.b  0(a0,d0.w), d2
    move.b  S_PX(a5), d0
    add.b   d1, d0
    move.b  S_PZ(a5), d1
    add.b   d2, d1                      | (d0, d1) = the cell in front
    move.l  #0x500, d2
    bsr     run_tile                    | its event, as used
    beq.s   2f                          | nothing ran: attack instead
    tst.b   skip_turn
    bne.s   9f                          | a dialog is open: the turn waits
    bra.s   5f
2:  bsr     select_target               | Z clear: something to attack
    bne.s   4f                          | something to attack
    TXT     TX_NOTHING, a0
    moveq   #SFX_BLIP, d2
    tst.b   sel_locked
    beq.s   3f
    lea     s_locked, a0
    moveq   #SFX_DENIED, d2
3:  bsr     say_a                       | to the message line
    move.w  d2, d0
    bsr     sfx_d0                      | blip, or the refusal buzz
    bra.s   9f
4:  bsr     player_attack               | Z set: no ammunition, no turn
    beq.s   9f
5:  moveq   #0, d0
    bsr     touch_tile                  | standing in fire burns
    bsr     end_player_turn             | the monsters' turn
9:  move.l  (sp)+, d2
    rts

| act_pass_i: wait a turn
| (the C entry point act_pass; button B.) clobbers d0, d1, a0, a1
act_pass_i:
    SAYT    TX_TURN_PASSED
    moveq   #0, d0
    bsr     touch_tile                  | standing in fire burns
    bra     end_player_turn             | the monsters' turn (tail call)

| act_cycle_weapon_i: the next usable weapon in direction d0.b (+1 / -1)
| (the C entry point act_cycle_weapon.) Tries the weapons cur + step,
| cur + 2 step... (11 at most, wrapping around 0..11) and takes the first
| that is carried and has ammunition (or needs none). Takes no turn.
| clobbers d0, d1, a0, a1 (d2-d4 kept)
act_cycle_weapon_i:
    movem.l d2-d4, -(sp)
    ext.w   d0
    move.w  d0, d4                      | step
    moveq   #1, d3                      | k
1:  move.w  d4, d2
    muls.w  d3, d2
    moveq   #0, d0
    move.b  S_WEAPON(a5), d0
    add.w   d0, d2                      | w
2:  tst.w   d2
    bpl.s   3f
    addi.w  #12, d2
    bra.s   2b                          | below 0: wrap
3:  cmpi.w  #12, d2
    blt.s   4f
    subi.w  #12, d2
    bra.s   3b                          | 12 or more: wrap
4:  move.w  S_WEAPONS(a5), d0
    btst    d2, d0
    beq.s   6f                          | not carried
    lea     wpn_use, a0
    tst.b   0(a0,d2.w)
    beq.s   5f                          | needs no ammunition
    lea     wpn_ammo, a0
    moveq   #0, d0
    move.b  0(a0,d2.w), d0
    lea     S_AMMO(a5), a0
    tst.b   0(a0,d0.w)
    beq.s   6f                          | no ammunition left
5:  move.b  d2, S_WEAPON(a5)
    SFX     SFX_SWITCH                  | the switch sound
    bra.s   9f
6:  addq.w  #1, d3
    cmpi.w  #12, d3
    bcs.s   1b                          | the next one
9:  movem.l (sp)+, d2-d4
    rts

| act_health_item_i: use the first health item -> d0.w = 1 if one was used
| (the C entry point act_health_item; button C.) Inventory slots 0 small
| medkit, 1 large medkit, 2 soulsphere: the first one held is used. A
| medkit gives the health of the map's medkit def (its parm, found through
| drop_def_tab); the soulsphere 200 health and 200 armour (both capped at
| the maximums). Using one takes a turn.
|   out: d0.l = 1 used, 0 none held
|   clobbers d0, d1, a0, a1 (d2 kept)
act_health_item_i:
    move.l  d2, -(sp)
    moveq   #0, d2
1:  lea     S_INVENTORY(a5), a0
    tst.b   0(a0,d2.w)
    bne.s   2f
    addq.w  #1, d2
    cmpi.w  #3, d2
    bcs.s   1b                          | slots 0..2
    SAY     s_nohealth                  | "NO HEALTH ITEMS"
    SFX     SFX_DENIED                  | the refusal buzz
    moveq   #0, d0
    bra.s   9f
2:  cmpi.w  #2, d2
    bne.s   3f                          | not the soulsphere
    move.w  #200, d0
    bsr     add_health                  | up to max health
    move.w  #200, d0
    bsr     add_armor                   | up to max armour
    bra.s   4f
3:  moveq   #DD_SMMED, d0
    tst.w   d2
    beq.s   31f
    moveq   #DD_LGMED, d0
| (If the map has no def of that medkit, drop_def_tab holds $FF and the
| parm read below comes from past the end of def_parm.)
31: movea.l drop_def_tab, a0
    moveq   #0, d1
    move.b  0(a0,d0.w), d1              | d1 = the medkit's def
    lsl.w   #2, d1
    movea.l def_parm, a0
    move.l  0(a0,d1.w), d0              | d0 = its parm: the health it gives
    bsr     add_health                  | says "GAINED <n> HEALTH"
4:  lea     S_INVENTORY(a5), a0
    subq.b  #1, 0(a0,d2.w)              | one fewer
    SFX     SFX_HEAL                    | the healing sound
    bsr     end_player_turn             | the monsters' turn
    moveq   #1, d0
9:  move.l  (sp)+, d2
    rts

