| clear_lists: no entity on any cell
| cell_head is 2048 bytes (1024 words), ent_next MAX_ENTS words; both are
| cleared a long at a time. clobbers d0, a0
clear_lists:
    lea     cell_head, a0
    move.w  #2048/4-1, d0
1:  clr.l   (a0)+
    dbra    d0, 1b
    lea     ent_next, a0
    move.w  #MAX_ENTS/2-1, d0
2:  clr.l   (a0)+
    dbra    d0, 2b
    rts

| turn_reset: no dialog, code entry, pending turn, attack or explosion
| (also clears suspend.) Called at map start and after a restore.
turn_reset:
    move.b  #NONE_B, dialog_str
    move.b  #NONE_B, pw_want
    clr.b   pend_valid
    clr.b   monsters_pending
    clr.b   att_n
    clr.b   n_pend_expl
    clr.b   suspend
    rts

| game_restore_i: S was loaded from a saved game: the map's data and the
| per-cell lists (sorted, so rebuilding them gives the same lists)
| (the C entry point game_restore, called by save.c after it copied the
| saved S back.) Only S is saved; the level pointers and the per-cell
| lists are rebuilt: each entity marked F_LINKED is linked again, in index
| order, so the lists come out sorted as before.
| clobbers d0, d1, a0, a1 (d2 kept)
game_restore_i:
    move.l  d2, -(sp)
    moveq   #0, d0
    move.b  S_MAP(a5), d0
    bsr     map_data                    | point the tables at the saved map
    bsr     level_load                  | the pointers and counts
    bsr.s   clear_lists                 | empty every cell's list
    moveq   #0, d2
1:  cmp.w   n_ents, d2
    bcc.s   2f
    lea     S_E_FLAGS(a5), a0
    bclr    #B_LINKED, 0(a0,d2.w)       | not on the map
    beq.s   11f
    move.w  d2, d0
    bsr     ent_link                    | sets F_LINKED again and inserts it
11: addq.w  #1, d2
    bra.s   1b
2:  bsr.s   turn_reset                  | no dialog, no pending turn...
    move.l  (sp)+, d2
    rts

| map_data: the C side finds map d0.w's tables (src/pack.c)
| pack.c's pack_init(map) finds that map in the campaign block and sets
| level_blob, strings_blob and the renderer's tables.
| clobbers d0, d1, a0, a1 (C call)
map_data:
    move.l  d0, -(sp)
    jsr     pack_init                   | pack.c
    addq.l  #4, sp
    rts

| game_init_i: a fresh game: the campaign's first map, the player of
| Player_reset (the pistol and 8 bullets)
| (the C entry point game_init, called by ui.c for a fresh game.) S is cleared
| and the random generator starts at $1234 (the model's seed); then map 0.
| clobbers d0, d1, a0, a1
game_init_i:
    movea.l a5, a0
    move.w  #S_SIZE-1, d0
1:  clr.b   (a0)+
    dbra    d0, 1b
    move.w  #0x1234, S_RNG(a5)          | the same seed as the model
    move.b  #30, S_HP(a5)
    move.b  #30, S_MAXHP(a5)
    move.b  #20, S_MAXARMOR(a5)
    move.b  #16, S_DEFENSE(a5)
    move.b  #12, S_STRENGTH(a5)
    move.b  #14, S_AGILITY(a5)
    move.b  #16, S_ACCURACY(a5)
    move.b  #1, S_LEVEL(a5)
    move.w  #80, S_NEXTXP(a5)           | level 1 needs 80 XP
    move.w  #4, S_WEAPONS(a5)           | bit 2: the pistol
    move.b  #2, S_WEAPON(a5)            | in hand
    move.b  #8, S_AMMO+1(a5)            | 8 bullets (ammo type 1)
    moveq   #0, d0
    moveq   #0, d1
    bra     map_start                   | (tail call: map 0, its own spawn point)

| map_change_i: through the exit (S.exit) to map d0.w: Game_changeMap
| (the sector completed, Player_addLevelStats) then the map's start
| (the C entry point map_change; ui.c calls it once S.exit_set is seen.)
| S.exit (CHANGEMAP's a1): bit 31 = a sector exit, so the map left counts
| as completed (S.completed bit map_id - 1), except from the Junction (the
| original's map id 2); bits 8..30 = the spawnParam for the next map.
|   in:  d0.w = the new map's index in the campaign
|   clobbers d0, d1, a0, a1 (d2 kept)
map_change_i:
    move.l  d2, -(sp)
    move.w  d0, d2
    move.l  S_EXIT(a5), d1
    bpl.s   1f                          | (bit 31: a completed sector, unless the Junction)
    moveq   #0, d0
    move.b  map_id, d0
    cmpi.b  #2, d0
    beq.s   1f
    subq.w  #1, d0                      | map id 1 -> bit 0...
    bmi.s   1f                          | map id 0: nothing to mark
    move.w  S_COMPLETED(a5), d1
    bset    d0, d1                      | the sector is done
    move.w  d1, S_COMPLETED(a5)
1:  move.l  S_EXIT(a5), d1              | spawnParam = (param << 1) >> 9
    add.l   d1, d1                      | (drops bit 31)
    asr.l   #8, d1
    asr.l   #1, d1                      | d1 = bits 8..30 of S.exit
    move.w  d2, d0
    move.l  (sp)+, d2
    bra     map_start                   | (tail call)

| map_start: map d0.w with the player in S; d1.l = spawnParam (0: the
| map's own spawn; else x | z << 5 | angle << 10): the world of the map
| (Game_loadMapEntities, random numbers as the model draws them), then the
| player (Player_setup), then the spawn cell's event
| Called by game_init_i and map_change_i. The player's own fields (stats,
| weapons, inventory, keys, completed...) carry over; everything from
| S.n_active to the end of S (the map's entities, monsters, lines, event
| states, props, the notebook, the portal) is cleared and set up again
| from the level blob. Random numbers are drawn in the model's order:
| per monster, setup_enemy's five then one for its first attack.
|   in:  d0.w = map index, d1.l = spawnParam
|   clobbers d0, d1, a0, a1 (d2-d4 kept)
map_start:
    movem.l d2-d4, -(sp)
    move.b  d0, S_MAP(a5)
    move.l  d1, d4
    bsr     map_data                    | pack.c: point at the map's data
    bsr     level_load                  | the counts and table pointers
    lea     S_N_ACTIVE(a5), a0          | the map's part of S
    move.w  #S_SIZE-S_N_ACTIVE-1, d0
1:  clr.b   (a0)+                       | (the map's part, byte by byte)
    dbra    d0, 1b
    clr.b   S_DEAD(a5)
    clr.b   S_MAP_GIVEN(a5)
    clr.b   S_DROP_INDEX(a5)
    clr.b   S_BERSERK(a5)
    move.b  #NONE_B, S_STORE(a5)
    clr.b   S_SECRET_TURN(a5)
    clr.w   S_CHG_SET(a5)               | (and exit_set)
    clr.l   S_CHG(a5)
    clr.l   S_EXIT(a5)
    move.w  #NONE, S_PORTAL_MON(a5)
    clr.b   S_PORTAL(a5)
    clr.b   S_PORTAL_CNT(a5)
    clr.b   S_COUPLINGS(a5)             | (the per-map player state is reset above)
    movea.l level_blob, a0              | the colours of floor and ceiling
    lea     18(a0), a0                  | header bytes 18..20 floor, 21..23 ceiling (rgb888)
    lea     S_FLOOR_RGB(a5), a1
    moveq   #5, d0
2:  move.b  (a0)+, (a1)+                | six bytes into S.floor_rgb, S.ceil_rgb
    dbra    d0, 2b
    move.b  spawn_x, S_PX(a5)           | where the player stands
    move.b  spawn_z, S_PZ(a5)
    move.b  spawn_f, S_FACING(a5)
    tst.l   d4
    beq.s   3f                          | spawnParam 0: the map's own spawn
    move.b  d4, d0
    andi.b  #31, d0                     | x = bits 0..4
    move.b  d0, S_PX(a5)
    move.l  d4, d0
    lsr.l   #5, d0
    andi.b  #31, d0                     | z = bits 5..9
    move.b  d0, S_PZ(a5)
    move.l  d4, d0
    lsr.l   #8, d0
    lsr.l   #2, d0                      | angle = bits 10..17
    lea     ANGLE_FACING, a0
    moveq   #3, d1
21: cmp.b   (a0)+, d0
    dbeq    d1, 21b                     | the facing of that angle
    bne.s   22f                         | not one of the four
    moveq   #3, d0
    sub.w   d1, d0
    bra.s   23f
22: moveq   #0, d0                      | north
23: move.b  d0, S_FACING(a5)
3:  bsr     clear_lists                 | empty every cell's list
    bsr     turn_reset                  | no dialog, no attack, no explosion waiting
    moveq   #0, d2                      | the entities
4:  cmp.w   n_ents, d2
    bcc.s   6f                          | every entity done
    lea     S_E_DEF(a5), a1
    cmp.w   n_map_ents, d2
    bcs.s   41f                         | a map entity
    move.b  #NONE_B, 0(a1,d2.w)         | a drop slot: empty ($FF), not linked
    bra.s   5f
41: movea.l ent_def0, a0
    move.b  0(a0,d2.w), 0(a1,d2.w)
    movea.l ent_x0, a0
    lea     S_E_X(a5), a1
    move.b  0(a0,d2.w), 0(a1,d2.w)
    movea.l ent_z0, a0
    lea     S_E_Z(a5), a1
    move.b  0(a0,d2.w), 0(a1,d2.w)
    movea.l ent_hidden0, a0
    tst.b   0(a0,d2.w)
    bne.s   5f                          | hidden at start: off the map
    move.w  d2, d0
    bsr     ent_link                    | onto the map (F_LINKED)
5:  addq.w  #1, d2
    bra.s   4b
6:  moveq   #0, d2                      | the lines
61: cmp.b   n_lines, d2
    bcc.s   7f
    moveq   #0, d0
    movea.l line_locked0, a0
    tst.b   0(a0,d2.w)
    beq.s   62f                         | not locked at start
    moveq   #L_LOCKED, d0
62: movea.l line_etype, a0
    cmpi.b  #ET_DESTRUCT, 0(a0,d2.w)
    bne.s   63f                         | not destructible
    ori.b   #L_ALIVE, d0                | a destructible line stands
63: lea     S_L_FLAGS(a5), a0
    move.b  d0, 0(a0,d2.w)
    addq.w  #1, d2
    bra.s   61b
7:  moveq   #0, d2                      | the events
71: cmp.b   n_events, d2
    bcc.s   8f
    movea.l ev_state0, a0
    lea     S_EV_STATE(a5), a1
    move.b  0(a0,d2.w), 0(a1,d2.w)
    addq.w  #1, d2
    bra.s   71b                         | (S.ev_state = ev_state0)
8:  moveq   #0, d2                      | the monsters, fires, barrels
81: cmp.w   n_map_ents, d2
    bcc     9f                          | every map entity done
    move.w  d2, d0
    bsr     etype                       | d0 = its type
    cmpi.w  #ET_ENEMY, d0
    bne     85f                         | not a monster
    move.w  d2, d0
    bsr     mon_slot                    | d0 = its monster slot
    move.w  d0, d3                      | m
    move.w  d2, d0
    bsr     esub                        | d0 = its class
| mon_base: 6 bytes per class (health, armour, defence, strength,
| agility, accuracy), capped at 255 by the build
    mulu.w  #6, d0
    lea     mon_base, a0
    adda.w  d0, a0
    move.b  (a0)+, d0
    lea     S_M_MAXHP(a5), a1
    move.b  d0, 0(a1,d3.w)
    lea     S_M_HP(a5), a1
    move.b  d0, 0(a1,d3.w)
    move.b  (a0)+, d0
    lea     S_M_MAXARMOR(a5), a1
    move.b  d0, 0(a1,d3.w)
    lea     S_M_ARMOR(a5), a1
    move.b  d0, 0(a1,d3.w)
    lea     S_M_DEF(a5), a1
    move.b  (a0)+, 0(a1,d3.w)           | defence
    lea     S_M_STR(a5), a1
    move.b  (a0)+, 0(a1,d3.w)           | strength
    lea     S_M_AGI(a5), a1
    move.b  (a0)+, 0(a1,d3.w)           | agility
    lea     S_M_ACC(a5), a1
    move.b  (a0)+, 0(a1,d3.w)           | accuracy
    lea     S_E_DEF(a5), a0
    moveq   #0, d1
    move.b  0(a0,d2.w), d1
    lsl.w   #2, d1
    movea.l def_parm, a0
    move.l  0(a0,d1.w), d1              | d1 = its def's parm
    move.w  d3, d0
    bsr     setup_enemy                 | scale the stats (five rnd)
    bsr     rnd                         | one rnd: which attack it starts with
    lea     S_E_FLAGS(a5), a0
    btst    #0, d0
    beq.s   82f                         | even: its first attack
    bset    #B_ATK2, 0(a0,d2.w)         | odd: its second
82: bset    #B_ALIVE, 0(a0,d2.w)        | alive
    bra.s   89f
85: cmpi.w  #ET_FIRE, d0
    beq.s   86f                         | fire (type 10; ET_FIRE2 is not set alive)
    cmpi.w  #ET_DESTRUCT, d0
    bne.s   89f                         | not a destructible
    move.w  d2, d0                      | (power couplings: once the portal opens)
    bsr     esub                        | d0 = its subtype
    cmpi.w  #4, d0
    beq.s   89f
86: lea     S_E_FLAGS(a5), a0
    bset    #B_ALIVE, 0(a0,d2.w)        | alive: can be hit
89: addq.w  #1, d2
    bra     81b
9:  tst.w   S_DISABLED_WEAPONS(a5)      | Player_setup: weapons put away come back
    beq.s   91f
    bsr     restore_weapons             | the weapons come back
91: moveq   #0, d0
    move.b  S_FACING(a5), d0
    lsl.w   #2, d0
    lea     FACING_FLAG, a0
    move.l  0(a0,d0.w), d2
| EVF_MOVE + every arriving bit ($40F) and the facing bit: the spawn
| cell's event runs as if the player had just walked in
    ori.w   #0x40F, d2
    move.b  S_PX(a5), d0
    move.b  S_PZ(a5), d1
    bsr     run_tile                    | the spawn cell's event
    bsr     activate_visible            | monsters in view start to think
    movem.l (sp)+, d2-d4
    rts

