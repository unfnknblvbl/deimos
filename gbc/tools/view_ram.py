"""
view/view.c (preprocessed, sdcc -E) made into the Game Boy's: its
functions __banked (bankify.py's way), and its variables, too many for
the work RAM, moved into the cartridge RAM's bank 3: one struct at
$A000 (view_ram.h: struct view_ram and VR; the file's uses of them become
VR.name), bank 3
being in place whenever the view runs (gfx.c). view_ram_init() gives them
their first values (the cartridge RAM keeps whatever it had).

  view_ram.py view_pp.c view/view.c OUT.c OUT_ram.h

It also writes view_api.h next to OUT_ram.h: the banked prototypes of
view_render and view_map_load, for gfx.c and the other banked callers.
The original view/view.c is read only for the names of the structs it
defines itself (they go into view_ram.h, before struct view_ram). Every
non-constant variable (static or not) becomes a field; initialisers become
assignments in view_ram_init, which first clears the whole struct (the
work RAM's zero-fill does not reach the cartridge RAM). Constant tables
stay in ROM. Environment: PROF_STATIC=1 makes the static functions
non-static (their names then show in the link map).
Licence: GPL-2.0-or-later.
"""
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from split_core import items_of, func_name, add_banked, split_top  # noqa: E402

RAM_AT = 0xA000                     # the cartridge RAM's window (bank 3 mapped)
RAM_SIZE = 8192                     # a bank: the struct must fit (checked by the compiler)


def declarators(t):
    """'static s16 a, *b[4] = x;' -> (base type, [(name, declarator, init)])"""
    body = re.sub(r"^static\s+", "", t.rstrip(";").strip())
    segs = split_top(body, ",")
    out, base = [], None
    for k, seg in enumerate(segs):
        parts = split_top(seg, "=")
        decl, init = parts[0].strip(), ("=".join(parts[1:]).strip() if len(parts) > 1 else None)
        core = re.sub(r"\[[^\]]*\]", "", decl)
        name = re.findall(r"[A-Za-z_]\w*", core)[-1]
        if k == 0:
            m = re.search(r"(\**\s*)" + name + r"\b", decl)
            base = decl[:m.start()].strip()
            d = decl[m.start():].strip()
        else:
            d = decl
        out.append((name, d, init))
    return base, out


def main():
    """Write OUT.c, OUT_ram.h and view_api.h."""
    pp = Path(sys.argv[1]).read_text()
    local_structs = set(re.findall(r"^struct\s+(\w+)\s*\{", Path(sys.argv[2]).read_text(), re.M))
    items = items_of(pp)
    defined = {func_name(t[:t.index("{")]) for t, k in items if k == "func"}
    # head: the declarations kept as they are; structs: view.c's own; funcs:
    # the functions; fields / inits / names: the variables moved to VR
    head, structs, funcs, fields, inits, names = [], [], [], [], [], []
    for t, k in items:
        if k == "func":
            hdr, body = t[:t.index("{")].strip(), t[t.index("{"):]
            if os.environ.get("PROF_STATIC") and hdr.startswith("static"):   # (profiling: the names seen)
                hdr = hdr[len("static"):].strip()
            funcs.append((hdr if hdr.startswith("static") else add_banked(hdr)) + "\n" + body)
            continue
        m = re.match(r"struct\s+(\w+)\s*\{", t)
        if m and m.group(1) in local_structs:
            structs.append(t)
            continue
        first = split_top(t, "=")[0]
        # (a prototype, not a function-pointer variable)
        is_proto = "(" in first and re.search(r"\w+\s*\([^;{=]*\)\s*;$", t) and \
            not re.search(r"\(\s*\*", first)
        if t.startswith(("typedef", "extern")) or re.match(r"(struct|enum|union)\s+\w*\s*\{", t) or is_proto:
            if is_proto and func_name(t) in defined and not t.startswith("static"):
                t = add_banked(t[:-1]) + ";"
            head.append(t)
            continue
        if re.match(r"(static\s+)?const\b", t):              # constant tables: stay in ROM
            head.append(t)
            continue
        base, ds = declarators(t)
        for name, d, init in ds:
            fields.append(f"    {base} {d};")
            names.append(name)
            if init is not None:
                inits.append(f"    {name} = {init};")
    ram_h = ["/* generated by gbc/tools/view_ram.py: do not edit */", "#ifndef VIEW_RAM_H", "#define VIEW_RAM_H"]
    ram_h += structs
    ram_h += ["struct view_ram {"] + fields + ["};",
              f"#define VR (*(struct view_ram *)0x{RAM_AT:04X})",
              f"typedef char view_ram_fits[sizeof(struct view_ram) <= {RAM_SIZE} ? 1 : -1];"]   # (a compile-time size check)
    ram_h += ["void view_ram_init(void) __banked;", "#endif"]
    out = ["/* generated by gbc/tools/view_ram.py from view/view.c: do not edit */", "#pragma bank 255"]
    out += head
    out.append(f'#include "{Path(sys.argv[4]).name}"')
    out.append("void view_ram_init(void) __banked\n{\n    unsigned char *p = (unsigned char *)&VR;\n"
               "    unsigned int n = sizeof(struct view_ram);\n    while (n--) *p++ = 0;\n" + "\n".join(inits) + "\n}")
    def ram(text):
        """every use of a moved variable (not after '.', '->' or a word character) -> VR.name"""
        for n in names:
            text = re.sub(r"(?<![\.\w>])" + n + r"\b", "VR." + n, text)
        return text
    out[-1] = ram(out[-1])
    out += [ram(f) for f in funcs]
    Path(sys.argv[3]).write_text("\n".join(out) + "\n")
    Path(sys.argv[4]).write_text("\n".join(ram_h) + "\n")
    # the view's functions as other banks call them (view.h's prototypes are not banked)
    api = ["/* generated by gbc/tools/view_ram.py: do not edit */", "#ifndef VIEW_API_H", "#define VIEW_API_H"]
    api += [f[:f.index("{")].strip() + ";" for f in funcs if not f.startswith("static")
            and func_name(f[:f.index("(") + 1]) in ("view_render", "view_map_load")]
    api += ["#endif"]
    Path(sys.argv[4]).with_name("view_api.h").write_text("\n".join(api) + "\n")
    print(f"{sys.argv[3]}: {len(funcs)} functions, {len(names)} variables in the cartridge RAM")


if __name__ == "__main__":
    main()
