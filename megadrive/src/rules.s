| The Mega Drive game - the game rules, in 68000 assembler: combat, monsters,
| items, doors, scripted events. Re-implemented from tools/game_model.py
| (the executable spec, written from the original game) and kept in step
| with it by tools/md_lockstep.py, which compares the whole game state S
| with the model's after every action: every random number must be drawn
| in the same order. Routine names match the model's methods.
|
| Conventions inside the rules:
|   a5 = S (the game state, tools/gen_cdata.py's layout: S_* offsets)
|   arguments and results in d0/d1 (as documented per routine); a routine
|   may change d0, d1, a0 and a1 and keeps every other register - the same
|   registers C may change, so the C routines it calls (say, sfx, ...) fit.
| Entity, line and event indices are words in registers and in memory
| (entities number up to MAX_ENTS); NONE ($FFFF) = none. Byte tables of
| the level use $FF for none.
| The C entry points (act_*, game_init, ...) take their arguments from the
| stack, set a5 and save what C expects.
|
| Licence: GPL-2.0-or-later.
|
| Where it fits:
|   - ui.c calls the C entry points at the end of this file (act_turn,
|     act_move, act_use, act_pass, act_cycle_weapon, act_health_item,
|     use_item, resume, store_buy, store_close, settle, game_init,
|     map_change, modal); save.c calls game_restore after loading a save.
|     Each entry point is made by the CENTRY macro: it saves the registers
|     C needs kept, points a5 at S and calls the inner routine (name_i).
|   - A few helpers are .global (wall_at, ent_at, line_at, trace, rnd)
|     but nothing outside this file calls them now; they use the register
|     conventions below, not C's, so C cannot call them directly.
|   - This file calls back into C only for messages (say, say2, say_num in
|     ui.c), sound effects (sfx in sound.c) and level strings.
|
| Jargon used in this file:
|   - "lockstep": the test (tools/md_lockstep.py, md_campaign_lockstep.py)
|     that runs the ROM in an emulator next to the Python model and compares
|     S byte for byte after every player action.
|   - "level blob": one map's rule data (tools/gen_cdata.py level_blob,
|     big-endian). A 24-byte header (counts, spawn point, map id, floor and
|     ceiling colours) is followed by a table of u16 offsets, one per table
|     (LT_* indices); level_load turns them into the pointers in .bss below.
|     pack.c sets level_blob when a map is chosen, from the "campaign
|     block" (all maps' data, at the end of the ROM).
|   - "def": an entity definition (def_etype, def_esub, def_parm,
|     def_name); every entity on the map is an instance of a def.
|   - "entity": a thing on the map (monster, person, item, prop). Indices
|     0..n_map_ents-1 come from the map; the N_DROPS slots after them are
|     reused for things monsters and crates drop.
|   - "monster slot": the index into the S.m_* arrays (hp, armour, stats)
|     of an entity whose type is ET_ENEMY (table ent_mon, $FF for others).
|   - "line": a door or other wall-like thing that sits in one cell
|     (line_x, line_z); it blocks while closed (L_OPEN clear).
|   - "event": a script attached to one cell (ev_x, ev_z); its commands
|     (cmd_op, cmd_a1, cmd_a2) run when something triggers the cell (the
|     player uses it, steps into it...): see run_event.
|   - "active list": S.active, the entities that take part in monster turns.
|   - "trace": a walk along a row or a column of cells, collecting what
|     is in the way (Game_trace in the original).
|   - "cell": one square of the 32 x 32 map; cell number = z * 32 + x.
|   - "text": the messages are the game's own words, not written here:
|     TX_* (texts.inc) names each one in the campaign block's texts table,
|     which the build makes from DoomRPG.jar (../tools/game_text.py); the
|     TXT and SAYT macros below find it.
|
| Memory: everything here is in .bss (68000 work RAM). S is the state that
| is saved and compared; the pointers after it are the level blob's tables
| (set by level_load, all in ROM); the rest is scratch that is rebuilt from
| S (the per-cell entity lists, the last trace's results, this turn's
| attacks) or carries results to C (dialog_str, pw_want, status_msg...).

| generated by the build: state.inc has the S_* field offsets, the MAX_*
| limits and the LT_* and DD_* numbers (tools/gen_cdata.py); sfx.inc the
| SFX_* sound effect ids (tools/build_sfx.py); texts.inc the TX_* indices
| of the game's texts (../tools/game_text.py)
