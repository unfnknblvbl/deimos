| modal: 1 while something needs the player's answer before the game goes
| on: a dialog, a door code or a vendor's menu. (C function: d0 = result;
| reads only.)
    .global modal
modal:
    moveq   #0, d0
    cmpi.b  #NONE_B, dialog_str
    bne.s   1f                          | a dialog is open
    cmpi.b  #NONE_B, pw_want
    bne.s   1f                          | a door code is asked for
    lea     S, a0
    cmpi.b  #NONE_B, S_STORE(a0)
    beq.s   2f                          | no vendor's menu either: 0
1:  moveq   #1, d0
2:  rts
