| a1: x bits 0..7, z 8..15, angle 16..23 (64 north, 0 east, 192 south,
| 128 west); another angle leaves the facing as it was.
    move.b  d5, S_PX(a5)
    move.b  d6, S_PZ(a5)
    move.l  d4, d0
