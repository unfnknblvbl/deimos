| add_health: hp += d0.w (signed), kept within 0..maxhp
| Says "GAINED n HEALTH" when health went up.
| clobbers d0, d1, a0, a1 (d2 kept)
add_health:
    movem.l d2, -(sp)
    moveq   #0, d2
    move.b  S_HP(a5), d2                | before
    add.w   d2, d0
    moveq   #0, d1
    move.b  S_MAXHP(a5), d1
    cmp.w   d1, d0
    ble.s   1f
    move.w  d1, d0
1:  tst.w   d0                          | below 0: 0
    bpl.s   2f
    moveq   #0, d0
2:  move.b  d0, S_HP(a5)
    sub.w   d2, d0
    ble.s   3f                          | no gain: no message
    TXT     TX_GAINED, a0
    TXT     TX_HEALTH_GAINED, a1
    bsr     say_num_a                   | "GAINED <n> HEALTH"
3:  movem.l (sp)+, d2
    rts

| add_armor: armor += d0.w, at most maxarmor
| (d0 >= 0.) Says "GAINED n ARMOR" when it went up.
| clobbers d0, d1, a0, a1 (d2 kept)
add_armor:
    movem.l d2, -(sp)
    moveq   #0, d2
    move.b  S_ARMOR(a5), d2
    add.w   d2, d0
    moveq   #0, d1
    move.b  S_MAXARMOR(a5), d1
    cmp.w   d1, d0
    ble.s   1f
    move.w  d1, d0
1:  move.b  d0, S_ARMOR(a5)
    andi.w  #0xFF, d0
    sub.w   d2, d0
    ble.s   3f
    TXT     TX_GAINED, a0
    TXT     TX_ARMOR_GAINED, a1
    bsr     say_num_a                   | "GAINED <n> ARMOR"
3:  movem.l (sp)+, d2
    rts

| add_ammo: type d0.w += d1.b -> Z set (beq) if already 99 (nothing taken)
| S.ammo: 6 bytes, one per ammo type (0 Halon, 1 bullets, 2 shells,
| 3 rockets, 4 cells, 5 dog); at most 99 of each.
|   in:  d0.w = ammo type, d1.b = amount
|   out: Z clear and d0.l = 1 if any was taken; clobbers d0, d1, a0
add_ammo:
    lea     S_AMMO(a5), a0
    adda.w  d0, a0
    cmpi.b  #99, (a0)
    beq.s   9f                          | full: nothing taken (Z set)
    andi.w  #0xFF, d1
    moveq   #0, d0
    move.b  (a0), d0
    add.w   d1, d0
    cmpi.w  #99, d0
    bls.s   1f
    moveq   #99, d0
1:  move.b  d0, (a0)
    moveq   #1, d0                      | (Z clear)
9:  rts

| stat_up: d0.b += d1.b, at most 99
|   in:  d0.b = the stat, d1.b = the gain
|   out: d0.w = the new stat (the gain is cut to reach 99 at most)
|   clobbers d1, a0
stat_up:
    andi.w  #0xFF, d0
    andi.w  #0xFF, d1
    move.w  d0, a0
    add.w   d1, a0
    cmpa.w  #99, a0
    bls.s   1f
    moveq   #99, d1
    sub.w   d0, d1
1:  add.w   d1, d0
    rts

| level_up: the next level and its rewards (random)
| levelling up: S.level + 1, the next level needs level * 20 + 60 XP; max
| health + 3..5 (and health filled), max armour + 3..5 (both at most 99),
| defence, strength, agility and accuracy + 1..2 each (at most 99).
| Six rnd draws, in that order. Says TX_LEVEL_UP n.
| Called by add_xp. clobbers d0, d1, a0, a1 (d2 kept)
level_up:
    move.l  d2, -(sp)
    addq.b  #1, S_LEVEL(a5)
    moveq   #0, d0
    move.b  S_LEVEL(a5), d0
    mulu.w  #20, d0
    addi.w  #60, d0
    move.w  d0, S_NEXTXP(a5)
    bsr     rnd                         | max health + 3..5, at most 99
    divu.w  #3, d0                      | remainder (0..2) in the high word
    swap    d0                          | d0.w = rnd % 3
    addq.w  #3, d0
    moveq   #0, d1
    move.b  S_MAXHP(a5), d1
    move.w  d1, d2
    add.w   d0, d2
    cmpi.w  #99, d2
    bls.s   1f
    moveq   #99, d0
    sub.w   d1, d0
1:  add.b   d0, S_MAXHP(a5)
    move.b  S_MAXHP(a5), S_HP(a5)       | health filled up
    bsr     rnd                         | max armour + 3..5
    divu.w  #3, d0                      | d0.w = rnd % 3
    swap    d0
    addq.w  #3, d0
    moveq   #0, d1
    move.b  S_MAXARMOR(a5), d1
    move.w  d1, d2
    add.w   d0, d2
