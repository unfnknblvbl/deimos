| run_explosions: each waiting explosion hurts the 4 cells beside it, and
| half that the 4 diagonal ones
| (expl_x / expl_z: a queue of at most 8, oldest first.) Takes the oldest,
| draws rnd32 and uses its low byte: damage = byte / 11 + 5 (5..28), to
| health and to armour alike. The explosion's own cell is not hurt. A
| barrel hit by it queues a new explosion (destroy), and this loop runs
| until the queue is empty (destroy calls back into run_explosions, so
| the queue can also be emptied by an inner call).
| clobbers d0, d1, a0, a1 (d2-d7 kept)
run_explosions:
    movem.l d2-d7, -(sp)
1:  tst.b   n_pend_expl
    beq     9f                          | none left
    moveq   #0, d6
    move.b  expl_x, d6                  | x
    moveq   #0, d7
    move.b  expl_z, d7                  | z
    lea     expl_x, a0                  | the rest move up
    lea     expl_z, a1
    moveq   #0, d0
    move.b  n_pend_expl, d0
    subq.w  #2, d0
    bmi.s   3f                          | it was the only one
2:  move.b  1(a0), (a0)+
    move.b  1(a1), (a1)+
    dbra    d0, 2b
3:  subq.b  #1, n_pend_expl
    bsr     rnd32                       | dmg = (u8)rnd32 / 11 + 5
    andi.l  #0xFF, d0
    divu.w  #11, d0                     | (rnd32's low byte, 0..255) / 11
    addq.w  #5, d0
    move.w  d0, d5
    moveq   #0, d4
4:  lea     EX_AX, a0
    move.b  0(a0,d4.w), d0
    ext.w   d0
    add.w   d6, d0
    lea     EX_AZ, a0
    move.b  0(a0,d4.w), d1
    ext.w   d1
    add.w   d7, d1
    move.w  d5, d2
    move.w  d5, d3
    bsr     hurt_at                     | hurt that cell (player or thing)
    addq.w  #1, d4
    cmpi.w  #4, d4
    bne.s   4b
    move.w  d5, d3
    lsr.w   #1, d3
    beq     1b                          | (half 0: not possible, damage >= 5)
    moveq   #0, d4
5:  lea     EX_BX, a0
    move.b  0(a0,d4.w), d0
    ext.w   d0
    add.w   d6, d0
    lea     EX_BZ, a0
    move.b  0(a0,d4.w), d1
    ext.w   d1
    add.w   d7, d1
    move.w  d5, d2
    lsr.w   #1, d2
    move.w  d2, d3
    bsr     hurt_at                     | hurt that cell with half the damage
    addq.w  #1, d4
    cmpi.w  #4, d4
    bne.s   5b
    bra     1b                          | the next explosion
9:  movem.l (sp)+, d2-d7
    rts

| push_explosion: at (d0.b, d1.b)
| (queued for run_explosions; the 9th and later are lost)
| clobbers a0 (d2 kept)
push_explosion:
    move.l  d2, -(sp)
    moveq   #0, d2
    move.b  n_pend_expl, d2
    cmpi.w  #8, d2
    bcc.s   9f                          | queue full
    lea     expl_x, a0
    move.b  d0, 0(a0,d2.w)
    lea     expl_z, a0
    move.b  d1, 0(a0,d2.w)
    addq.b  #1, n_pend_expl
9:  move.l  (sp)+, d2
    rts

| destroy: a barrel, crate or fire d0.w is destroyed
| Destroys a thing that was alive (does nothing otherwise): it leaves the
| map. Fire (ET_FIRE): TX_FIRE_CLEARED and 2 XP. Destructibles
| (ET_DESTRUCT) by subtype: 1 a barrel explodes (queued); 4 a
| coupling (the Reactor's portal closes when both are gone); 2 a crate
| breaks and may hold a trap (an explosion), credits, a medkit, armour or
| ammunition (one rnd, a second for the ammo kind): the crate's own
| entity becomes that pick-up on the same cell. Then the queued explosions
| go off (run_explosions).
|   in:  d0.w = entity
|   clobbers d0, d1, a0, a1 (d2-d6 kept)
| Called by hurt_at, monster_attack, player_attack and kot_one.
destroy:
    movem.l d2-d6, -(sp)
    move.w  d0, d6                      | j
    lea     S_E_FLAGS(a5), a0
    btst    #B_ALIVE, 0(a0,d6.w)
    beq     9f                          | already gone
    bsr     etype                       | d0 = its type
    move.w  d0, d4                      | et
    move.w  d6, d0
    bsr     esub                        | d0 = its subtype
    move.w  d0, d5                      | es
    lea     S_E_FLAGS(a5), a0
    bclr    #B_ALIVE, 0(a0,d6.w)
    move.w  d6, d0
    bsr     ent_unlink                  | off the map
    cmpi.w  #ET_FIRE, d4
    bne.s   1f                          | only type 10 (ET_FIRE2 is not cleared here)
    SAYT    TX_FIRE_CLEARED
    moveq   #2, d0
    bsr     add_xp                      | 2 XP for the fire
    bra     8f
1:  cmpi.w  #ET_DESTRUCT, d4
    bne     8f
    cmpi.w  #1, d5
    bne.s   2f                          | 1: a barrel
