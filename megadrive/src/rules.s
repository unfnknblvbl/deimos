    bra     ec_ret1
| CHECK_KEY: a1 & 3 = key 0 green, 1 yellow, 2 blue, 3 red (S.keys bits
| 0..3). With the key, nothing happens (counts as not run); without it,
| "NEED ... KEY" and the event stops.
ec_41:                                  | require a key
    move.w  d5, d0
    andi.w  #3, d0
    move.b  S_KEYS(a5), d1
    btst    d0, d1
    bne.s   ec_ret0                     | the player has it
    add.w   d0, d0                      | (a word per text)
    lea     md_campaign, a0
    adda.l  24(a0), a0                  | the texts table
    adda.w  2*TX_NEED_GREEN(a0,d0.w), a0    | a0 = "NEED <colour> KEY" (TX_NEED_GREEN + key)
    bsr     say_a                       | to the message line
    SFX     SFX_DENIED                  | the refusal buzz
    move.b  #SUSP_STOP, suspend         | the rest of the event does not run
| the handlers' common exit: d0 = 1 / 0 with the flags set from it
ec_ret1:
    moveq   #1, d0
    bra.s   1f
| ec_ret0: the command did nothing (d0 = 0, Z set)
ec_ret0:
    moveq   #0, d0
1:  movem.l (sp)+, d2-d7
    tst.w   d0
    rts

| run_event: event d0.w from command d1.w on, with flags d2.l -> d0.w = 1
| (Z clear) if some command ran
| (described at the top of this part). Commands k..n-1 are tried in
| order; d6 bit 16 records that one ran. When a command sets suspend, the
| place is saved (pend_valid, pend_ev, pend_k, pend_flags, pend_why) and
| the event stops; resume_i goes on from k + 1.
|   in:  d0.w = event, d1.w = first command (0 normally), d2.l = trigger
|   clobbers d0, d1, a0, a1 (d2-d7, a2 kept)
| Register use: d7 = event, d6 = k, d5 = trigger (with the key bit added),
| d4 = the state bit n7, d3 = the key bits n8, d2 = the command count,
| a2 = the command's global index.
run_event:
    movem.l d2-d7/a2, -(sp)
    move.w  d0, d7
    andi.w  #0xFF, d7                   | ev
    move.w  d1, d6
    andi.l  #0xFF, d6                   | k (bit 16: something ran)
    move.l  d2, d5                      | flags
    movea.l ev_flags, a0
    btst    #0, 0(a0,d7.w)
    beq.s   1f                          | ev_flags bit 0: the event ignores movement
    btst    #10, d5                     | (EVF_MOVE)
    bne     9f                          | a move trigger: not run
1:  lea     S_EV_STATE(a5), a0
    moveq   #0, d0
    move.b  0(a0,d7.w), d0
    moveq   #0, d4                      | n7
    tst.w   d0
    beq.s   2f                          | state 0: no state bit
    move.l  #0x10000, d4
    subq.w  #1, d0
    lsl.l   d0, d4                      | n7 = $10000 << (state - 1)
| the best key held as a trigger bit: red, else blue, else green, else
| yellow (S.keys: 1 green, 2 yellow, 4 blue, 8 red)
2:  move.b  S_KEYS(a5), d0
    btst    #3, d0                      | red keycard
    beq.s   21f
    ori.w   #0x8000, d5
    bra.s   3f
21: btst    #2, d0                      | blue keycard
    beq.s   22f
    ori.w   #0x4000, d5
    bra.s   3f
22: btst    #0, d0                      | green keycard
    beq.s   23f
    ori.w   #0x2000, d5
    bra.s   3f
23: btst    #1, d0                      | yellow keycard
    beq.s   3f
    ori.w   #0x1000, d5
3:  move.l  d5, d3
    andi.l  #0xF000, d3                 | n8
    movea.l ev_ncmd, a0
    moveq   #0, d2
    move.b  0(a0,d7.w), d2              | n
4:  cmp.w   d2, d6
    bcc     9f                          | all its commands tried
    movea.l ev_cmd0, a0
    move.w  d7, d0
    add.w   d0, d0
    move.w  0(a0,d0.w), d0              | d0 = the event's first command
    add.w   d6, d0                      | c
    movea.w d0, a2
    move.w  d0, d1                      | dead?
    lsr.w   #3, d1
    lea     S_CMD_DEAD(a5), a0
    btst    d0, 0(a0,d1.w)
    bne     8f                          | used up (S.cmd_dead bit): skip
    lsl.w   #2, d0
    movea.l cmd_a2, a0
    move.l  0(a0,d0.w), d1              | a2
    tst.l   d4
    beq.s   5f                          | state 0
    move.l  d1, d0
    and.l   d4, d0
    beq     8f                          | not for this state
    bra.s   6f
5:  move.l  d1, d0
    andi.l  #0x1FF0000, d0
    bne.s   8f                          | state 0: commands with state bits are skipped
6:  move.l  d1, d0
    andi.l  #0xF000, d0
    beq.s   7f                          | no key bits: any key
    cmp.l   d3, d0
    bne.s   8f                          | needs another key
7:  move.l  d1, d0
    and.l   d5, d0
    beq.s   8f                          | the trigger does not match
    clr.b   suspend                     | (set by the command if it stops the event)
    move.w  a2, d0
    bsr     exec_cmd                    | run it
    beq.s   71f                         | Z set: it did nothing
    bset    #16, d6                     | something ran
    move.w  a2, d0
    lsl.w   #2, d0
    movea.l cmd_a2, a0
    move.l  0(a0,d0.w), d1
    btst    #9, d1                      | (EVF_MODIFY): the command is used up
    beq.s   71f
    move.w  a2, d0
    move.w  d0, d1
    lsr.w   #3, d1
    lea     S_CMD_DEAD(a5), a0
    bset    d0, 0(a0,d1.w)              | used up from now on
71: tst.b   suspend
    beq.s   8f                          | not stopped: on
    move.b  #1, pend_valid
    move.b  d7, pend_ev
    move.b  d6, pend_k
    move.l  d5, pend_flags
    move.b  suspend, pend_why
    bra.s   9f                          | stop here
8:  addq.w  #1, d6
    bra     4b                          | the next command
9:  moveq   #0, d0
    btst    #16, d6
    beq.s   91f
    moveq   #1, d0
91: movem.l (sp)+, d2-d7/a2
    tst.w   d0
    rts

| run_tile: the event at (d0.b, d1.b), flags d2.l -> as run_event
| (from command 0.) Used for the player's actions, the map's start and
| the fixed events of the special deaths.
|   in:  d0.b, d1.b = cell; d2.l = trigger bits
|   out: d0.l = 1 (Z clear) if a command ran
|   clobbers d0, d1, a0, a1
run_tile:
    bsr     find_event                  | d0 = the event on that cell
    cmpi.w  #NONE, d0
    beq.s   9f                          | no event there: 0
    moveq   #0, d1
    bra     run_event                   | (tail call)
9:  moveq   #0, d0
    rts

| settle_i: after a dialog or code entry closed: the monsters' turn, if due
| (also the C entry point settle, and the end of every player action.)
| monsters_pending means a turn is owed; while a dialog, a code entry or a
| vendor's menu is open it waits, else visible monsters wake up and, if
| the player is alive, the monsters take their turn.
| clobbers d0, d1, a0, a1
settle_i:
    cmpi.b  #NONE_B, dialog_str
    bne.s   9f                          | a dialog is open
    cmpi.b  #NONE_B, pw_want
    bne.s   9f                          | a code is being asked for
    cmpi.b  #NONE_B, S_STORE(a5)
    bne.s   9f                          | a vendor's menu is open
    tst.b   monsters_pending
    beq.s   9f                          | no turn owed
    clr.b   monsters_pending
    bsr     activate_visible            | monsters now in view start to think
    tst.b   S_DEAD(a5)
    bne.s   9f                          | the player is dead: no turn
    bsr     monster_turn                | the monsters' turn
9:  rts

| end_player_turn: a player action that takes a turn is over: the
| Berserker counts down and the monsters are owed their turn (now, or
| when the open dialog closes). Called by the act_*_i routines and
| use_item_i. clobbers d0, d1, a0, a1
end_player_turn:
    bsr     berserk_tick                | one turn less of the Berserker
    move.b  #1, monsters_pending
    bra.s   settle_i                    | (tail call)

| resume_i: a dialog closed or a code was entered (a2 = the code or 0)
| (the C entry point resume; ui.c calls it when a dialog closes, with 0,
| or when a code was entered, with the typed string.)
| A dialog: the stopped event goes on from the next command. A code: if
| it matches the level string pw_want, TX_CODE_GOOD and the event goes
| on; if it is wrong, TX_CODE_BAD and the event is dropped; a
| cancelled entry (0 or "") is dropped silently. The monsters then get
| their turn (settle_i), except after a wrong or cancelled code.
|   in:  a2 = the code string or 0 (from the C argument)
|   clobbers d0, d1, a0, a1 (d2-d7 kept)
resume_i:
    movem.l d2-d7, -(sp)
    move.b  pend_valid, d3
    moveq   #0, d4
    move.b  pend_ev, d4
    moveq   #0, d5
    move.b  pend_k, d5
    addq.b  #1, d5                      | (k + 1 as a byte)
    move.b  pend_why, d6
    move.l  pend_flags, d2
    clr.b   pend_valid
    move.b  #NONE_B, dialog_str
    tst.b   d3
    beq   8f                            | no event was waiting
    cmpi.b  #SUSP_DIALOG, d6
    bne.s   1f                          | not a dialog
    move.w  d4, d0
    move.w  d5, d1
    bsr     run_event                   | on with the event
    bra.w   8f
1:  cmpi.b  #SUSP_PASSWORD, d6
    bne.w   8f                          | SUSP_STOP: nothing to resume
    moveq   #0, d0
    move.b  pw_want, d0
    move.b  #NONE_B, pw_want
    move.l  a2, d1
    beq.s   3f                          | no code given
    bsr     level_str                   | compare
    movea.l a2, a1
2:  move.b  (a1)+, d0
    beq.s   21f                         | the typed string ended
    cmp.b   (a0)+, d0
    beq.s   2b                          | the same so far
    bra.s   3f                          | different
21: tst.b   (a0)
    bne.s   3f                          | the code is longer: wrong
    SAYT    TX_CODE_GOOD
    SFX     SFX_SELECT
    move.w  d4, d0
    move.w  d5, d1
    bsr     run_event                   | on with the event
    bra.s   8f
3:  move.l  a2, d1                      | wrong (or none)
    beq.s   9f
    tst.b   (a2)
    beq.s   9f
    SAYT    TX_CODE_BAD
    SFX     SFX_DENIED                  | the refusal buzz
    bra.s   9f
8:  bsr     settle_i                    | the monsters' turn, if owed
9:  movem.l (sp)+, d2-d7
    rts

