"""
A C file of the other ports (view/view.c, snes/src/save.c), preprocessed
(sdcc -E), made into a Game Boy banked file: every function __banked, so
the game's code in any bank can call it; and its header with the same
functions __banked.

  bankify.py file_pp.c OUT.c [header.h OUT.h]

build.sh runs it on snes/src/save.c (its header save.h -> obj/save_api.h);
view/view.c goes through view_ram.py instead, which also moves its
variables. "Banked" (GBDK / SDCC __banked): the function is called through
a trampoline that maps its ROM bank first, so it may live in any of the
cartridge's switchable banks. The file parsing is split_core.py's.
Licence: GPL-2.0-or-later.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from split_core import items_of, func_name, add_banked  # noqa: E402


def main():
    """Write OUT.c (and OUT.h) as described above; print the count."""
    pp = Path(sys.argv[1]).read_text()
    items = items_of(pp)                    # the top-level items: functions and declarations
    defined = {func_name(t[:t.index("{")]) for t, k in items if k == "func"}
    # (#pragma bank 255: the linker's -autobank chooses the bank)
    out = ["/* generated by gbc/tools/bankify.py: do not edit */", "#pragma bank 255"]
    for t, k in items:
        if k == "func":
            hdr, body = t[:t.index("{")].strip(), t[t.index("{"):]
            # (a static function stays a plain call: only its own file calls it,
            # and the linker would leave its bank number unset)
            out.append((hdr if hdr.startswith("static") else add_banked(hdr)) + "\n" + body)
        # a prototype of one of the file's own functions: banked too
        elif "(" in t and re.search(r"\b(\w+)\s*\([^;{=]*\)\s*;$", t) and func_name(t) in defined \
                and not t.startswith("static"):
            out.append(add_banked(t[:-1]) + ";")
        else:
            out.append(t)
    Path(sys.argv[2]).write_text("\n".join(out) + "\n")
    if len(sys.argv) > 4:
        # the header: the prototypes of the functions defined here get __banked
        api = []
        for line in Path(sys.argv[3]).read_text().splitlines():
            m = re.match(r"^([a-zA-Z].*?\b(\w+)\s*\(.*\))\s*;(.*)$", line)
            if m and m.group(2) in defined:
                line = m.group(1) + " __banked;" + m.group(3)
            api.append(line)
        Path(sys.argv[4]).write_text("/* generated by gbc/tools/bankify.py: do not edit */\n" + "\n".join(api) + "\n")
    print(f"{sys.argv[2]}: {len(defined)} functions banked")


if __name__ == "__main__":
    main()
