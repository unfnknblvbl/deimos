| a fighter's numbers, as the formulas want them
| CB_*: offsets of a fighter's record (mcb for a monster; the player's
| fields are read from S directly). Each field is one byte; CB_CLASS is
| the monster class (def_esub), which picks its row of the damage tables.
    .equ    CB_HP, 0
    .equ    CB_MAXHP, 1
    .equ    CB_ARMOR, 2
    .equ    CB_MAXARMOR, 3
    .equ    CB_DEF, 4
    .equ    CB_STR, 5
    .equ    CB_AGI, 6
    .equ    CB_ACC, 7
    .equ    CB_CLASS, 8
    .bss
mcb:        .space  10                  | the monster in a fight (CB_* layout)
    .text

| mon_slot: d0.w = entity d0.w's monster slot (m_* arrays)
| (ent_mon: built by gen_cdata.py; $FF for an entity that is no monster)
| clobbers a0
mon_slot:
    movea.l ent_mon, a0
    move.b  0(a0,d0.w), d0
    andi.w  #0xFF, d0
    rts

| cb_monster: mcb = entity d0.w's numbers
| cb_monster: copy a monster's numbers into mcb for the combat formulas.
|   in:  d0.w = entity index (a monster)
|   out: mcb filled (hp, maxhp, armour, maxarmour, def, str, agi, acc from
|        S.m_*, class = its def_esub)
|   clobbers d0, d1, a0, a1 (d2 kept)
cb_monster:
    move.l  d2, -(sp)
    move.w  d0, d2
    bsr.s   mon_slot                    | d0 = its monster slot
    lea     mcb, a1
    lea     S_M_HP(a5), a0
    move.b  0(a0,d0.w), CB_HP(a1)
    lea     S_M_MAXHP(a5), a0
    move.b  0(a0,d0.w), CB_MAXHP(a1)
    lea     S_M_ARMOR(a5), a0
    move.b  0(a0,d0.w), CB_ARMOR(a1)
    lea     S_M_MAXARMOR(a5), a0
    move.b  0(a0,d0.w), CB_MAXARMOR(a1)
    lea     S_M_DEF(a5), a0
    move.b  0(a0,d0.w), CB_DEF(a1)
    lea     S_M_STR(a5), a0
    move.b  0(a0,d0.w), CB_STR(a1)
    lea     S_M_AGI(a5), a0
    move.b  0(a0,d0.w), CB_AGI(a1)
    lea     S_M_ACC(a5), a0
    move.b  0(a0,d0.w), CB_ACC(a1)
    move.w  d2, d0
    bsr     esub                        | d0 = its subtype: the monster class (0..13)
    lea     mcb, a1
    move.b  d0, CB_CLASS(a1)
    move.l  (sp)+, d2
    rts

| cb_exp: d0.w = the experience for killing entity d0.w:
| ((def + str) 5 + (agi + acc) 3 + (maxhp + maxarmor) 5 + 49) / 50
| (all the monster's current stats, from its monster slot). The + 49
| makes the division round up.
|   out: d0.l = 0..255; clobbers d1, a0 (d2, d3 kept)
cb_exp:
    movem.l d2-d3, -(sp)
    bsr   mon_slot                      | d0 = its monster slot
    move.w  d0, d3
    moveq   #0, d0
    moveq   #0, d1
    lea     S_M_DEF(a5), a0
    move.b  0(a0,d3.w), d0
    lea     S_M_STR(a5), a0
    move.b  0(a0,d3.w), d1
    add.w   d1, d0
    lea     S_M_MAXHP(a5), a0
    move.b  0(a0,d3.w), d1
    add.w   d1, d0
    lea     S_M_MAXARMOR(a5), a0
    move.b  0(a0,d3.w), d1
    add.w   d1, d0
    mulu.w  #5, d0
    moveq   #0, d2
    lea     S_M_AGI(a5), a0
    move.b  0(a0,d3.w), d2
    lea     S_M_ACC(a5), a0
    move.b  0(a0,d3.w), d1
    add.w   d1, d2
    mulu.w  #3, d2
    add.l   d2, d0
    addi.l  #49, d0
    divu.w  #50, d0
    andi.l  #0xFF, d0
    movem.l (sp)+, d2-d3
    rts

| range_excess: d0.w = tiles d0^2 - rmin d1^2 - 1 (signed)
| (> 0: that far beyond the weapon's minimum range; d0, d1 are small.)
| Used by calc_hit and calc_damage for the fall-off with distance.
| clobbers d1
range_excess:
    mulu.w  d0, d0
    mulu.w  d1, d1
    sub.w   d1, d0
    subq.w  #1, d0
    rts

| calc_hit: accuracy d0.w, weapon d1.w, the target's agility d2.w, tiles
| d3.w (0 = adjacent / the player) -> d0.w = HIT_MISS / HIT_HIT / HIT_CRIT
| The original's hit roll (CombatEntity hit chance). Tables wpn_* are the
| weapon table of tools/game_rules.py (data.c), indexed by weapon 0..18:
| the player's weapons, the dog's, then the monsters' attacks.
|   ch = ((acc * 256) / agi) / 2 + rangeMax * 32 / 25: the chance out of 256
|   (wpn_rmax is the original's "rangeMax", used here as a hit bonus).
|   Beyond the minimum range (ex = tiles^2 - rmin^2 - 1 > 0) a weapon with
|   rmin = 0 (melee) always misses; others lose 76/256 of ch for every
|   square number 1, 4, 9... below ex, except shell weapons (ammo type 2).
|   Then r = rnd: r < ch hits, and r < floor(ch / 20) is a critical.
| One rnd is drawn. clobbers d1, a0 (d2-d7 kept)
calc_hit:
    movem.l d2-d7, -(sp)
    move.w  d1, d7                      | weapon
    tst.b   d2                          | agility 0 counts as 1
    bne.s   1f
    moveq   #1, d2
1:  andi.l  #0xFF, d0                   | ch = ((acc << 8) / agi) >> 1 + rmax * 32 / 25
    lsl.l   #8, d0
    divu.w  d2, d0
    andi.l  #0xFFFF, d0
    lsr.w   #1, d0
    move.w  d0, d6
    lea     wpn_rmax, a0
    moveq   #0, d0
    move.b  0(a0,d7.w), d0
    lsl.w   #5, d0
    divu.w  #25, d0
    add.w   d0, d6                      | ch
    lea     wpn_rmin, a0
    moveq   #0, d5
    move.b  0(a0,d7.w), d5              | rmin
    moveq   #-1, d4                     | ex
    tst.b   d3                          | tiles 0: no distance fall-off
    beq.s   2f
    move.w  d3, d0
    andi.w  #0xFF, d0
    move.w  d5, d1
    bsr     range_excess                | d0 = tiles^2 - rmin^2 - 1
    move.w  d0, d4
2:  tst.w   d4                          | out of a melee weapon's reach: a miss
    ble.s   3f
    tst.b   d5
    beq.s   8f                          | rmin 0 (melee) and too far
    lea     wpn_ammo, a0                | shells (shotguns) don't fall off
    cmpi.b  #2, 0(a0,d7.w)
    beq.s   3f
    move.w  d6, d0                      | dec = (ch * 76) >> 8
    muls.w  #76, d0
    asr.l   #8, d0
    move.w  d0, d3
    moveq   #2, d2                      | k
    moveq   #1, d1                      | d
4:  cmp.w   d4, d1
    bge.s   3f                          | d (1, 4, 9...) >= ex: done
    sub.w   d3, d6                      | ch -= dec
    move.w  d2, d1
    mulu.w  d2, d1                      | d = k * k
    addq.w  #1, d2
    bra.s   4b
3:  bsr     rnd                         | d0 = r (0..255)
    cmp.w   d6, d0                      | r < ch
    bge.s   8f
    move.w  d0, d5
    move.w  d6, d0
    moveq   #20, d1
    bsr     fdiv                        | d0 = floor(ch / 20)
    cmp.w   d0, d5                      | r < ch / 20: a critical
    blt.s   5f
    moveq   #HIT_HIT, d0
    bra.s   9f
5:  moveq   #HIT_CRIT, d0
    bra.s   9f
8:  moveq   #HIT_MISS, d0
9:  movem.l (sp)+, d2-d7
    rts

| lmul: d0.l = d0.l * d1.l, the low 32 bits
| (32 x 32 bits with three 16-bit multiplies; the high product is not
| needed.) d1 is kept; clobbers nothing else.
lmul:
    movem.l d2-d3, -(sp)
    move.l  d0, d2
    swap    d2
    mulu.w  d1, d2                      | a_hi * b_lo
    move.l  d1, d3
    swap    d3
    mulu.w  d0, d3                      | a_lo * b_hi
    add.w   d3, d2
    swap    d2
    clr.w   d2
    mulu.w  d1, d0
    add.l   d2, d0
    movem.l (sp)+, d2-d3
    rts

| (cd_args is not used by any code: calc_damage takes its arguments in
| registers.)
    .bss
cd_args:    .space  8                   | calc_damage: str, weapon, def, class, mult (w), tiles
    .text

| calc_damage: the attacker's strength d0.b, weapon d1.b, the target's
| defence d2.b and class d3.b ($FF = the player), multiplier d4.w (256,
| 512 crit), tiles d5.b -> dmg_hp, dmg_arm
| The original's damage formula, in 8.8 fixed point (256 = 1 point):
|   ratio = (str * 256) / def (def 0 counts as 1)
|   a     = min * 256 + r * (max - min), r = rnd (0..255)
|   d     = (((a * ratio) >> 8) * mult >> 8) * class_mult >> 8
|           class_mult = dmg_mult[class * N_WEAPONS + weapon], 256 for the
|           player (class $FF)
|   then the same distance fall-off as calc_hit (76/256 of d per step),
|   d clamped to 256..255744 (1..999 points),
|   arm = d * wpn_armor / 256 (the armour's share), rounded to points:
|   dmg_hp = (d - arm + 128) >> 8, dmg_arm = (arm + 128) >> 8.
| dmg_hp and dmg_arm are bytes: a result over 255 keeps only its low byte.
| One rnd is drawn. clobbers d0, d1, a0 (d2-d7 kept)
calc_damage:
    movem.l d2-d7, -(sp)
    move.w  d1, d7                      | weapon
    andi.w  #0xFF, d7
    move.b  d0, d6                      | strength
    bsr     rnd                         | d0 = r (0..255), the one random draw
    move.w  d0, -(sp)                   | r
    tst.b   d2                          | defence 0 counts as 1
    bne.s   1f
    moveq   #1, d2
1:  moveq   #0, d0                      | ratio = (str << 8) / def
    move.b  d6, d0
    lsl.l   #8, d0
    andi.w  #0xFF, d2
    divu.w  d2, d0
    andi.l  #0xFFFF, d0
    move.l  d0, d6                      | ratio
    lea     wpn_min, a0                 | a = (min << 8) + r (max - min)
    moveq   #0, d1
    move.b  0(a0,d7.w), d1
    lea     wpn_max, a0
    moveq   #0, d0
    move.b  0(a0,d7.w), d0
    sub.w   d1, d0
    mulu.w  (sp)+, d0
    lsl.l   #8, d1
    add.l   d1, d0
    move.l  d6, d1                      | du = (a * ratio) >> 8 (32 bits)
    bsr.s   lmul                        | d0 = a * ratio
    lsr.l   #8, d0
    andi.l  #0xFFFF, d4                 | du = (du * mult) >> 8
    move.l  d4, d1
    bsr.s   lmul                        | d0 = du * mult
    lsr.l   #8, d0
    move.l  #256, d1                    | du = (du * class multiplier) >> 8
    cmpi.b  #0xFF, d3
    beq.s   2f                          | the player: x 1
    moveq   #0, d1
    move.b  d3, d1
    mulu.w  #N_WEAPONS, d1
    add.w   d7, d1
    add.w   d1, d1
    lea     dmg_mult, a0
    move.w  0(a0,d1.w), d1
    andi.l  #0xFFFF, d1
2:  bsr   lmul                          | d0 = du * class multiplier
    lsr.l   #8, d0
    move.l  d0, d6                      | d (signed from here)
    moveq   #-1, d4                     | ex
    tst.b   d5
    beq.s   3f                          | tiles 0: no fall-off
    moveq   #0, d0
    move.b  d5, d0
    lea     wpn_rmin, a0
    moveq   #0, d1
    move.b  0(a0,d7.w), d1
    bsr     range_excess                | d0 = tiles^2 - rmin^2 - 1
    move.w  d0, d4
3:  move.l  d6, d0                      | dec = (d * 76) >> 8
    moveq   #76, d1
    bsr   lmul                          | d0 = d * 76
    asr.l   #8, d0
    move.l  d0, d3
    moveq   #2, d2                      | k
    moveq   #1, d1                      | dist
4:  cmp.w   d4, d1
    bge.s   5f                          | step (1, 4, 9...) >= ex: done
    sub.l   d3, d6                      | d -= dec
    move.w  d2, d1
    mulu.w  d2, d1
    addq.w  #1, d2
    bra.s   4b
5:  cmpi.l  #255744, d6                 | at most 999 points
    ble.s   6f
    move.l  #255744, d6
6:  cmpi.l  #256, d6                    | at least 1 point
    bge.s   7f
    move.l  #256, d6
7:  lea     wpn_armor, a0               | arm = (d * armor share) >> 8
    moveq   #0, d0
    move.b  0(a0,d7.w), d0
    move.l  d6, d1
    bsr   lmul                          | d0 = d * share
    asr.l   #8, d0
    move.l  d6, d1                      | dmg_hp = (d - arm + 128) >> 8
    sub.l   d0, d1
    addi.l  #128, d1
    asr.l   #8, d1
    move.b  d1, dmg_hp
    addi.l  #128, d0                    | dmg_arm = (arm + 128) >> 8
    asr.l   #8, d0
    move.b  d0, dmg_arm
    movem.l (sp)+, d2-d7
    rts

| setup_enemy: monster slot d0.w, def parm d1.l: every stat scaled by a
| random factor in [0.75, 1.25) x parm / 256 (armour and defence share one)
| On entry the m_* arrays of slot m hold the class's base stats (spawn
| code); they are replaced by the scaled values (0..255). i2 = parm / 4,
| i3 = parm / 2, factor f = parm - i2 + (i3 * rnd) >> 8. Five rnd draws:
| health, armour + defence, strength, agility, accuracy.
|   in:  d0.w = monster slot, d1.l = the def's parm (8.8: 256 = x 1)
|   clobbers d0, d1, a0 (d2-d7 kept)
setup_enemy:
    movem.l d2-d7, -(sp)
    move.w  d0, d7                      | m
    move.l  d1, d6                      | parm
    move.l  d6, d5
    asr.l   #2, d5                      | i2 (as a word)
    move.w  d5, d4
    add.w   d4, d4                      | i3
    bsr.s   se_factor                   | d3 = factor for health
    lea     S_M_MAXHP(a5), a0
    bsr   se_scale                      | d0 = scaled max health
    lea     S_M_MAXHP(a5), a0
    move.b  d0, 0(a0,d7.w)
    lea     S_M_HP(a5), a0
    move.b  d0, 0(a0,d7.w)              | (full health)
    bsr.s   se_factor                   | d3 = factor for armour and defence
    lea     S_M_MAXARMOR(a5), a0
    bsr.s   se_scale                    | d0 = scaled max armour
    lea     S_M_MAXARMOR(a5), a0
    move.b  d0, 0(a0,d7.w)
    lea     S_M_ARMOR(a5), a0
    move.b  d0, 0(a0,d7.w)              | (full armour)
    lea     S_M_DEF(a5), a0
    bsr.s   se_scale                    | d0 = scaled defence (same factor)
    lea     S_M_DEF(a5), a0
    move.b  d0, 0(a0,d7.w)
    bsr.s   se_factor                   | d3 = factor for strength
    lea     S_M_STR(a5), a0
    bsr.s   se_scale                    | d0 = scaled strength
    lea     S_M_STR(a5), a0
    move.b  d0, 0(a0,d7.w)
    bsr.s   se_factor                   | d3 = factor for agility
    lea     S_M_AGI(a5), a0
    bsr.s   se_scale                    | d0 = scaled agility
    lea     S_M_AGI(a5), a0
    move.b  d0, 0(a0,d7.w)
    bsr.s   se_factor                   | d3 = factor for accuracy
    lea     S_M_ACC(a5), a0
    bsr.s   se_scale                    | d0 = scaled accuracy
    lea     S_M_ACC(a5), a0
    move.b  d0, 0(a0,d7.w)
    movem.l (sp)+, d2-d7
    rts
| d3.w = parm + ((i3 * rnd) >> 8) - i2
| se_factor: d4 = i3, d5 = i2, d6 = parm (setup_enemy's registers)
| clobbers d0, d1
se_factor:
    bsr     rnd                         | d0 = r (0..255)
    muls.w  d4, d0
    asr.l   #8, d0
    add.l   d6, d0
    move.w  d5, d1
    ext.l   d1
    sub.l   d1, d0
    move.w  d0, d3
    rts
| d0.w = clamp8((a0[m] * f) >> 8)
| se_scale: a0 = the stat array, d7 = the slot, d3 = the factor
| clobbers d0
se_scale:
    moveq   #0, d0
    move.b  0(a0,d7.w), d0
    muls.w  d3, d0
    asr.l   #8, d0
    bra     clamp8                      | (tail call: 0..255)

