| wall_at: Z clear (bne) if (d0.b, d1.b) is a wall (outside the map is)
| The map is 32 x 32 cells; wall_bits holds one bit per cell.
|   in:  d0.b = x, d1.b = z (unsigned: 32..255 is outside)
|   out: Z flag; clobbers d0, d1, a0
| Called by trace, the movement code, and the renderer.
    .global wall_at
wall_at:
    cmpi.b  #32, d0                     | x >= 32: outside, a wall
    bcc.s   9f
    cmpi.b  #32, d1
    bcc.s   9f
    andi.w  #31, d0
    andi.w  #31, d1
    lsl.w   #5, d1
    or.w    d0, d1                      | cell
    move.w  d1, d0
    lsr.w   #3, d0                      | byte = cell >> 3
    movea.l wall_bits, a0
    move.b  0(a0,d0.w), d0
    andi.w  #7, d1                      | bit = cell & 7
    btst    d1, d0
    rts
9:  moveq   #1, d0                      | (Z clear)
    rts

| cell_of: d0.w = the cell (z * 32 + x) of entity d0.w
| clobbers d1, a0
cell_of:
    lea     S_E_X(a5), a0
    moveq   #0, d1
    move.b  0(a0,d0.w), d1
    lea     S_E_Z(a5), a0
    move.b  0(a0,d0.w), d0
    andi.w  #0xFF, d0
    lsl.w   #5, d0
    or.w    d1, d0
    rts

| list_insert: entity d0.w into its cell's list (sorted): cell_head and
| ent_next hold index + 1 (words; 0 ends the list)
| Every linked entity is kept in the list of its cell, in index order, so
| that walking a cell gives the same order as the model's index loop.
| Walks the list until the next index is past i and links i in there.
| clobbers d0, d1, a0, a1 (d2, d3 kept)
list_insert:
    movem.l d2-d3, -(sp)
    move.w  d0, d2                      | i
    bsr.s   cell_of                     | d0 = its cell (from S.e_x / e_z)
    add.w   d0, d0
    lea     cell_head, a0
    adda.w  d0, a0                      | p = &cell_head[c]
    lea     ent_next, a1
1:  move.w  (a0), d1                    | *p
    beq.s   2f
    move.w  d1, d3
    subq.w  #1, d3
    cmp.w   d2, d3                      | *p - 1 < i: on
    bcc.s   2f
    add.w   d3, d3
    lea     0(a1,d3.w), a0              | p = &ent_next[*p - 1]
    bra.s   1b
2:  move.w  d2, d3
    add.w   d3, d3
    move.w  d1, 0(a1,d3.w)              | ent_next[i] = *p
    addq.w  #1, d2
    move.w  d2, (a0)                    | *p = i + 1
    movem.l (sp)+, d2-d3
    rts

| list_remove: entity d0.w out of its cell's list
| (unlinks it from the cell it is in now: call before changing e_x / e_z)
| clobbers d0, d1, a0, a1 (d2, d3 kept)
list_remove:
    movem.l d2-d3, -(sp)
    move.w  d0, d2
    bsr.s   cell_of                     | d0 = its cell
    add.w   d0, d0
    lea     cell_head, a0
    adda.w  d0, a0
    lea     ent_next, a1
1:  move.w  (a0), d1
    beq.s   9f                          | end of the list: not there
    move.w  d1, d3
    subq.w  #1, d3
    cmp.w   d2, d3
    bne.s   2f                          | not this one: on to its next
    add.w   d3, d3
    move.w  0(a1,d3.w), (a0)            | *p = ent_next[i]
    clr.w   0(a1,d3.w)                  | i is out: its next link cleared
    bra.s   9f
2:  add.w   d3, d3
    lea     0(a1,d3.w), a0
    bra.s   1b
9:  movem.l (sp)+, d2-d3
    rts

| ent_link / ent_unlink: entity d0.w onto / off the map
| Sets / clears F_LINKED and adds / removes the entity from its cell's
| list only when the flag changed. clobbers d0, d1, a0, a1
ent_link:
    lea     S_E_FLAGS(a5), a0
    bset    #B_LINKED, 0(a0,d0.w)
    beq   list_insert                   | it was not linked: link it now (tail call)
    rts
ent_unlink:
    lea     S_E_FLAGS(a5), a0
    bclr    #B_LINKED, 0(a0,d0.w)
    bne.s   list_remove                 | it was linked: unlink it (tail call)
    rts

| ent_move_to: entity d0.w to (d1.b x, d1 >> 8 z)
| Moves the entity between cell lists only if it is linked.
| clobbers d0, d1, a0, a1 (d2, d3 kept)
ent_move_to:
    movem.l d2-d3, -(sp)
    move.w  d0, d2
    move.w  d1, d3
    lea     S_E_FLAGS(a5), a0
    btst    #B_LINKED, 0(a0,d0.w)
    beq.s   1f
    bsr.s   list_remove                 | out of the old cell's list
1:  lea     S_E_X(a5), a0
    move.b  d3, 0(a0,d2.w)
    lsr.w   #8, d3
    lea     S_E_Z(a5), a0
    move.b  d3, 0(a0,d2.w)
    lea     S_E_FLAGS(a5), a0
    btst    #B_LINKED, 0(a0,d2.w)
    beq.s   2f
    move.w  d2, d0
    bsr     list_insert                 | into the new cell's list
2:  movem.l (sp)+, d2-d3
    rts

| ent_at: d0.w = the first linked entity with index >= d2.w at (d0.b,
| d1.b), or NONE
| (start at d2 = 0 for the first; call again with d2 = previous + 1 to walk
| the cell.) clobbers d1, a0; d2 kept. Called by trace and the renderer.
    .global ent_at
ent_at:
    cmpi.b  #32, d0
    bcc.s   8f                          | outside the map: nothing
    cmpi.b  #32, d1
    bcc.s   8f
    andi.w  #31, d0
    andi.w  #31, d1
    lsl.w   #5, d1
    or.w    d1, d0
    add.w   d0, d0
    lea     cell_head, a0
    move.w  0(a0,d0.w), d1              | d1 = first index + 1 (0: empty cell)
    lea     ent_next, a0
1:  tst.w   d1
    beq.s   8f
    move.w  d1, d0
    subq.w  #1, d0
    cmp.w   d2, d0
    bcc.s   9f                          | index >= d2: found
    add.w   d0, d0
    move.w  0(a0,d0.w), d1              | on to the next
    bra.s   1b
8:  move.w  #NONE, d0
9:  rts

| line_at: d0.w = the closed line at (d0.b, d1.b), or NONE
| line_cells gives a quick "is any line here" bit; then all lines are
| scanned for the one at this cell that is not open.
|   in:  d0.b = x, d1.b = z
| clobbers d1, a0 (d2-d4 kept)
    .global line_at
line_at:
    movem.l d2-d4, -(sp)
    cmpi.b  #32, d0
    bcc.s   8f
    cmpi.b  #32, d1
    bcc.s   8f
    move.b  d0, d2                      | x
    move.b  d1, d3                      | z
    andi.w  #31, d0
    andi.w  #31, d1
    lsl.w   #5, d1
    or.w    d0, d1
    move.w  d1, d0
    lsr.w   #3, d0
    movea.l line_cells, a0
    move.b  0(a0,d0.w), d0
    andi.w  #7, d1
    btst    d1, d0
    beq.s   8f                          | no line in this cell
    moveq   #0, d4                      | i
1:  cmp.b   n_lines, d4
    bcc.s   8f                          | every line checked
    movea.l line_x, a0
    cmp.b   0(a0,d4.w), d2
    bne.s   2f
    movea.l line_z, a0
    cmp.b   0(a0,d4.w), d3
    bne.s   2f
    lea     S_L_FLAGS(a5), a0
    btst    #0, 0(a0,d4.w)              | L_OPEN
    bne.s   2f
    move.w  d4, d0
    bra.s   9f
2:  addq.w  #1, d4
    bra.s   1b
8:  move.w  #NONE, d0
9:  movem.l (sp)+, d2-d4
    rts

| trace's working copies (only valid during one trace)
    .bss
tr_sx:  .space  1                       | the trace's start cell
tr_sz:  .space  1
tr_dx:  .space  1                       | the trace's end cell
tr_dz:  .space  1
tr_self: .space 2                       | the entity that does not count (the one tracing)
tr_mask: .space 2                       | the mask (bit 8 checked in the high byte)
tr_hid: .space  2                       | this cell's props are gone (S.static_hidden)
    .text

| trace: Game_trace along a row or a column from (d0.b, d1.b) to (d2.b,
| d3.b) with mask d4.w, ignoring entity d5.w: fills hit_kind / hit_val
| (at most 8) -> d0.w = hit_n (Z set: nothing in the way)
| The original's Game_trace, cell by cell: only straight lines (same x or
| same z) are traced; the start cell is included. A wall, the player (if the
| mask has bit 8) or a thin wall stops it; closed lines, static props and
| entities whose type is in the mask are recorded and the trace goes on.
| It also stops when 8 hits are recorded or the end cell is reached.
|   in:  d0.b, d1.b = start x, z; d2.b, d3.b = end x, z; d4.w = mask;
|        d5.w = entity to ignore (NONE for none)
|   out: hit_n, hit_kind[], hit_val[]; d0.w = hit_n with flags set from it
|   clobbers d0, d1, a0, a1 (d2-d7 kept)
| Called by the movement, sight and attack code (and the renderer).
| Register use: d4 / d5 = the x / z step (-1, 0, 1), d6 / d7 = the cell.
    .global trace
trace:
    movem.l d2-d7, -(sp)
    move.b  d0, d6                      | x
    move.b  d1, d7                      | z
    move.b  d0, tr_sx
    move.b  d1, tr_sz
    move.b  d2, tr_dx
    move.b  d3, tr_dz
    move.w  d4, tr_mask
    move.w  d5, tr_self
    clr.b   hit_n
    moveq   #0, d4                      | stx
    moveq   #0, d5                      | stz
    cmp.b   d2, d0                      | a column trace when x matches, else a row
    beq.s   1f
    moveq   #1, d4
    cmp.b   d0, d2
    bhi.s   2f
    moveq   #-1, d4                     | dx < sx: step west
    bra.s   2f
1:  cmp.b   d3, d1
    beq.s   2f
    moveq   #1, d5
    cmp.b   d1, d3
    bhi.s   2f
    moveq   #-1, d5                     | dz < sz: step north (dz > sz: south; same cell: no step)
2:  | one cell
| tr_cell: the loop over the cells of the trace
tr_cell:
    move.b  d6, d0
    move.b  d7, d1
    bsr     wall_at                     | Z clear: a wall here
    beq.s   3f
    moveq   #H_WALL, d1
    bsr     tr_add                      | record it and stop
    bra     tr_end
3:  btst    #0, tr_mask                 | (bit 8 of the mask: the player)
    beq.s   4f
    cmp.b   S_PX(a5), d6
    bne.s   4f
    cmp.b   S_PZ(a5), d7
    bne.s   4f
    moveq   #H_PLAYER, d1
    bsr     tr_add                      | record it and stop
    bra     tr_end
4:  move.b  d6, d0                      | a closed line
    move.b  d7, d1
    bsr     line_at                     | d0 = the closed line here, or NONE
    cmpi.w  #NONE, d0
    beq.s   5f
    move.w  d0, d2
    movea.l line_etype, a0
    moveq   #0, d0
    move.b  0(a0,d2.w), d0
    move.w  tr_mask, d1
    bsr     mask_has                    | does the mask stop this line's type?
    beq.s   5f
    cmpi.b  #8, hit_n                   | (room for 8 hits only)
    bcc.s   5f
    moveq   #H_LINE, d1
    move.w  d2, d0
    bsr     tr_add                      | record it, keep going
5:  moveq   #0, d0                      | a static blocker (unless taken away)
    move.b  d7, d0
    lsl.w   #5, d0
    or.b    d6, d0
    move.w  d0, d1
    lsr.w   #3, d1
    lea     S_STATIC_HIDDEN(a5), a0
    btst    d0, 0(a0,d1.w)              | bit cell & 7 of byte cell >> 3
    sne     tr_hid                      | tr_hid = $FF if this cell's props were taken away
    bne.s   6f
    movea.l static_block, a0
    moveq   #0, d2
    move.b  0(a0,d0.w), d2
    beq.s   6f                          | 0: no static prop here
    move.w  d2, d0
    move.w  tr_mask, d1
    bsr     mask_has                    | does the mask stop this prop?
    beq.s   6f
    cmpi.b  #8, hit_n
    bcc.s   6f
    moveq   #H_STATIC, d1
    move.w  d2, d0
    bsr     tr_add                      | record it, keep going
6:  moveq   #0, d2                      | the entities here
7:  move.b  d6, d0
    move.b  d7, d1
    bsr     ent_at                      | d0 = the next entity at index >= d2, or NONE
    cmpi.w  #NONE, d0
    beq.s   8f
    move.w  d0, d2
    cmp.w   tr_self, d0                 | the tracer itself: skip
    beq.s   71f
    bsr     etype                       | d0 = its type
    move.w  tr_mask, d1
    bsr     mask_has                    | does the mask stop this type?
    beq.s   71f
    cmpi.b  #8, hit_n
    bcc.s   71f
    moveq   #H_ENT, d1
    move.w  d2, d0
    bsr   tr_add                        | record it, keep going
71: addq.w  #1, d2                      | on to the entities after it
    bra.s   7b
8:  tst.b   tr_hid                      | invisible thin walls this trace crosses
    bne.s   81f
    bsr     tr_thin                     | Z clear: a thin wall stopped it
    bne.s   tr_end
81: cmpi.b  #8, hit_n                   | 8 hits: full
    bcc.s   tr_end
    tst.b   d4                          | a row trace (x steps)?
    beq.s   9f
    cmp.b   tr_dx, d6
    beq.s   tr_end                      | the last cell: done
    bra.s   10f
9:  cmp.b   tr_dz, d7
    beq.s   tr_end                      | the last cell: done
10: add.b   d4, d6
    add.b   d5, d7
    bra     tr_cell                     | the next cell
| tr_end: the trace is over
tr_end:
    moveq   #0, d0
    move.b  hit_n, d0
    movem.l (sp)+, d2-d7
    tst.w   d0                          | (flags for the caller: Z = nothing hit)
    rts

| tr_thin: the cell (d6, d7) of the trace (step d4, d5): its thin walls
| (Game_trace's eType 14 / 15 test: only those the trace crosses) -> Z
| clear (bne) if one stops it (added as a static hit)
| thin_bits per cell: bits 0..3 = the W, E, N, S edges of a type-14 thin
| wall, bits 4..7 the same for type 15. Only the edges the trace actually
| crosses count: not the entry edge of the start cell nor the exit edge of
| the end cell. Mask bits 14 / 15 say which type stops the trace.
|   out: d0.l = 1 (stopped, a static hit of type 14 or 15 added) or 0
| clobbers d0, d1, d2, a0
tr_thin:
    moveq   #0, d0
    move.b  d7, d0
    lsl.w   #5, d0
    or.b    d6, d0
    movea.l thin_bits, a0
    move.b  0(a0,d0.w), d2              | the walls on its edges
    beq   9f                            | 0: no thin walls in this cell
    moveq   #0, d1                      | the types the mask stops
    btst    #6, tr_mask                 | (bit 14: the mask word's high byte, bit 6)
    beq.s   1f
    moveq   #0x0F, d1                   | type 14 counts: the low nibble
1:  btst    #7, tr_mask
    beq.s   2f                          | bit 15
    ori.b   #0xF0, d1                   | type 15 counts: the high nibble
2:  and.b   d1, d2
    beq   9f                            | none of the right type
    moveq   #0, d1                      | the edges crossed
    tst.b   d4
    beq.s   5f                          | d4 = 0: a column trace
    bmi.s   3f                          | d4 < 0: going west
    cmp.b   tr_sx, d6                   | east: W if x > sx, E if x < dx
    bls.s   21f
    ori.b   #0x11, d1                   | W edge, both types
21: cmp.b   tr_dx, d6
    bcc.s   8f
    ori.b   #0x22, d1                   | E edge, both types
    bra.s   8f
3:  cmp.b   tr_sx, d6                   | west: E if x < sx, W if x > dx
    bcc.s   31f
    ori.b   #0x22, d1
31: cmp.b   tr_dx, d6
    bls.s   8f
    ori.b   #0x11, d1
    bra.s   8f
5:  tst.b   d5
    beq.s   9f                          | same cell: no edge crossed
    bmi.s   6f                          | d5 < 0: going north
    cmp.b   tr_sz, d7                   | south: N if z > sz, S if z < dz
    bls.s   51f
    ori.b   #0x44, d1                   | N edge, both types
51: cmp.b   tr_dz, d7
    bcc.s   8f
    ori.b   #0x88, d1                   | S edge, both types
    bra.s   8f
6:  cmp.b   tr_sz, d7                   | north: S if z < sz, N if z > dz
    bcc.s   61f
    ori.b   #0x88, d1
61: cmp.b   tr_dz, d7
    bls.s   8f
    ori.b   #0x44, d1
8:  and.b   d1, d2                      | a wall on an edge crossed?
    beq.s   9f
    moveq   #14, d0                     | its type: 14 if in the low nibble, else 15
    andi.b  #0x0F, d2
    bne.s   81f
    moveq   #15, d0
81: moveq   #H_STATIC, d1
    bsr.s   tr_add                      | record it (value = 14 / 15)
    moveq   #1, d0                      | Z clear: stopped
    rts
9:  moveq   #0, d0                      | Z set: not stopped
    rts

| tr_add: hit (kind d1, value d0)
| Appends one record to hit_kind / hit_val. The caller checks hit_n < 8
| first (except for the stopping hits, which come at most once).
|   in:  d1.b = kind (H_*), d0.w = value. clobbers a0 (d2 kept)
tr_add:
    move.w  d2, -(sp)
    moveq   #0, d2
    move.b  hit_n, d2
    lea     hit_kind, a0
    move.b  d1, 0(a0,d2.w)
    add.w   d2, d2
    lea     hit_val, a0
    move.w  d0, 0(a0,d2.w)
    addq.b  #1, hit_n
    move.w  (sp)+, d2
    rts

