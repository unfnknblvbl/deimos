| ltab: a0 = the address of blob table d0.w (header offsets at 24 + 2i)
| ltab: find one table of the level blob.
|   in:  d0.w = table index (LT_*)
|   out: a0 = its address (blob start + the u16 offset at 24 + 2 * index)
|   clobbers d0
ltab:
    movea.l level_blob, a0
    add.w   d0, d0
    move.w  24(a0,d0.w), d0
    adda.w  d0, a0
    rts

| level_load: the counts and every table's address
| Called by map_start and game_restore_i. Reads the header bytes
| at level_blob: 5 defs, 6 entities (w), 8 monsters, 9 lines, 10 events,
| 11 strings, 12 commands (w), 14..16 spawn x, z, facing, 17 map id.
|   in:  level_blob (set by pack.c)
|   out: the n_* counts, spawn_*, map_id and every table pointer
|   clobbers d0, d1, a0, a1 (d2, a2 kept)
    .global level_load
level_load:
    movem.l d2/a2, -(sp)
    movea.l level_blob, a0
    move.b  5(a0), n_defs
    move.w  6(a0), d0
    move.w  d0, n_map_ents
    addq.w  #N_DROPS, d0                | the drop slots follow the map's entities
    move.w  d0, n_ents
    move.b  8(a0), n_mons
    move.b  9(a0), n_lines
    move.b  10(a0), n_events
    move.b  11(a0), n_strings
    move.w  12(a0), n_cmds
    move.b  14(a0), spawn_x
    move.b  15(a0), spawn_z
    move.b  16(a0), spawn_f
    move.b  17(a0), map_id
    lea     lt_order, a2                | (table index, pointer) pairs
| walk lt_order until the -1 end mark
1:  move.w  (a2)+, d0
    bmi.s   2f
    movea.l (a2)+, a1
    bsr   ltab                          | a0 = that table's address
    move.l  a0, (a1)
    bra.s   1b
2:  movem.l (sp)+, d2/a2
    rts

| lt_order: (word table index, long address of its pointer) pairs, -1 ends
lt_order:
