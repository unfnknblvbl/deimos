"""
The Game Boy Color's sound tables (obj/snd_tab.c, for gbc/src/snd.c: the
driver's, made from the Mega Drive game's FM instruments, no part of the original
game; the streams themselves come with the resources, tools/gb_res.py):
  snd_inst[10][3]   per the Mega Drive game instrument: square wave duty (0..3),
                    envelope pace (0: steady, 1..7: falling), base
                    attenuation (0.75 dB steps)
  snd_drum[9][2]    NR42, NR43: the Mega Drive game's 8 noise drums, then the kick and
                    toms (voice 5)
  snd_per[96]       the square wave's period (131072 / Hz) for MIDI notes
                    36..47 in 1/8 semitones (an octave up: half)
  snd_vol[128]      attenuation -> volume 0..15

Usage: gb_sound.py <deimos gen dir> OUT.c
(snd_inst has one row per instrument in megadrive/tools/music_data.s; snd.c
reads at most 10.) The FM decoding helpers are snes_sound.py's.
Licence: GPL-2.0-or-later.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent / "tools"))
import snes_sound as SS  # noqa: E402

# the noise drums: (NR42 start volume / envelope, NR43 noise clock / width)
DRUMS = [(0x81, 0x52),     # 0 snare
         (0x41, 0x11),     # 1 closed hi-hat
         (0x42, 0x12),     # 2 open hi-hat
         (0x63, 0x33),     # 3 crash
         (0xF1, 0x44),     # 4 shot
         (0xF3, 0x67),     # 5 blast
         (0x95, 0x31),     # 6 hiss
         (0x41, 0x11),     # 7 tick
         (0xA1, 0x7C)]     # 8 the kick and toms: a short low thump


def instrument(patch):
    """A the Mega Drive game FM patch -> (duty, envelope pace, base attenuation): the
    loudest carrier's decay rate gives the pace, strong feedback (a
    brighter sound) the narrower duty."""
    ops, alg, fb = SS.ops_of(patch)
    car = [ops[k] for k in SS.CARRIERS[alg] if ops[k]["tl"] < 100]
    o = min(car, key=lambda c: c["tl"]) if car else ops[4]    # (the loudest audible carrier)
    pace = 0 if not o["d1r"] else max(1, min(7, 9 - o["d1r"] // 2))
    return (1 if fb >= 6 else 2, pace, min(127, SS.base_att(patch)))


def main():
    """Write OUT.c with the four tables."""
    gen, out = Path(sys.argv[1]), Path(sys.argv[2])
    patches = SS.patches_of((gen / "music_data.s").read_text())
    # the period of note 36 + i / 8 (MIDI note 69 is 440 Hz); the volume of
    # attenuation a (0.75 dB steps) on the 0..15 scale
    per = [min(2047, round(131072 / (440 * 2 ** ((36 + i / 8 - 69) / 12)))) for i in range(96)]
    vol = [max(0, min(15, round(15 * 10 ** (-0.75 * a / 20)))) for a in range(128)]
    c = ["/* generated by gbc/tools/gb_sound.py: do not edit */", '#include "../../core/types.h"',
         "const u8 snd_inst[%d][3] = {%s};" % (len(patches), ", ".join("{%d, %d, %d}" % instrument(p) for p in patches)),
         "const u8 snd_drum[9][2] = {%s};" % ", ".join("{0x%02X, 0x%02X}" % d for d in DRUMS),
         "const u16 snd_per[96] = {%s};" % ", ".join(str(v) for v in per),
         "const u8 snd_vol[128] = {%s};" % ", ".join(str(v) for v in vol)]
    out.write_text("\n".join(c) + "\n")


if __name__ == "__main__":
    main()
