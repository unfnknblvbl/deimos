    .equ    F_LINKED, 0x04              | in its cell's list (cell_head / ent_next)
    .equ    F_ACTIVE, 0x08              | on the active list (S.active)
    .equ    F_ATK2, 0x10                | a monster that uses its second attack this turn
    .equ    F_DROPPED, 0x20             | a monster that has already left its drop (spawn_drop)
    .equ    F_CORPSE, 0x40              | a dead monster's body (an arch-vile can raise it)
    .equ    F_RAISING, 0x80             | being raised from the dead
    .equ    B_ALIVE, 0                  | (bit numbers)
    .equ    B_HIDDEN, 1
    .equ    B_LINKED, 2
    .equ    B_ACTIVE, 3
    .equ    B_ATK2, 4
    .equ    B_DROPPED, 5
    .equ    B_CORPSE, 6
    .equ    B_RAISING, 7

| line flags (S.l_flags, one byte per line)
    .equ    L_OPEN, 1                   | open (does not block)
    .equ    L_LOCKED, 2                 | locked (needs a key or a code)
    .equ    L_ALIVE, 4                  | not yet destroyed (a destructible line)

| trace masks: bit n = entity type n blocks; bit 8 = the player.
| The masks are words: bits 0..15 = entity types 0..15 (type 16 and up
| never block, see mask_has). trace tests bit 8 (type 8 is not used by
| entities) to mean "the player stops the trace". Bits 14 and 15 are the
| two kinds of invisible thin walls (thin_bits).
    .equ    MASK_PLAYER_MOVE, 0xF287
    .equ    MASK_MONSTER_MOVE, 0xFF87
    .equ    MASK_SHOT, 0x5687
    .equ    MASK_SHOW_KILL, 4098        | 4098 = $1002: types 1 (monsters) and 12 (destructibles)
    .equ    MASK_RAISE_FREE, 16263      | 16263 = $3F87

| event trigger bits: run_event is given the trigger in a long (d2); a
| command runs only if its a2 has a bit in common with it. In a command's
| a2, bit 9 (EVF_MODIFY) means "run once" (it is then marked in S.cmd_dead).
| The other trigger bits are described with run_event.
    .equ    EVF_USE, 0x100              | the cell was used (A pressed at it), or run as if used
    .equ    EVF_MODIFY, 0x200           | (in a command's a2: a one-shot command)
    .equ    EVF_MOVE, 0x400             | the player moved: stepped in or out, turned, or arrived at map start

| trace hit kinds (hit_kind[]; hit_val[] holds the value)
    .equ    H_WALL, 0                   | a wall cell (value: unused)
    .equ    H_PLAYER, 1                 | the player (value: unused)
    .equ    H_LINE, 2                   | a closed line (value: the line index)
    .equ    H_STATIC, 3                 | a static prop or thin wall (value: its blocking type)
    .equ    H_ENT, 4                    | an entity (value: the entity index)

| why an event stopped (the byte suspend; pend_why keeps it for resume)
    .equ    SUSP_NONE, 0                | running, or finished
    .equ    SUSP_DIALOG, 1              | a dialog opened (dialog_str); resume goes on after it
    .equ    SUSP_PASSWORD, 2            | a door code is asked for (pw_want); resume checks it
    .equ    SUSP_STOP, 3                | refused (no key, a stat too low): the event ends here

| attack target kinds (att_kind[]: what each attack is aimed at; sel_kind)
    .equ    T_PLAYER, 0                 | the player
    .equ    T_ENT, 1                    | an entity (monster, dog, barrel...)
    .equ    T_RAISE, 2                  | a corpse being raised (arch-vile)
    .equ    T_LINE, 3                   | a line (destructible wall / door)

| the Reactor's portal (Game_updateSpawnPortals): fixed in the original's code
    .equ    PORTAL_X, 16                | its line's cell (the event that runs when it closes)
    .equ    PORTAL_Z, 14
    .equ    PORTAL_SPAWN_Z, 15          | where it sends monsters: x 16, 15, 17

    .equ    DLG_CAPTURED, 0xFE          | dialog_str: TX_CAPTURED <captured_def> TX_CAPTURED_END
    .equ    HIT_MISS, 0                 | calc_hit's results
    .equ    HIT_HIT, 1
    .equ    HIT_CRIT, 2

| ---- calling the C side (messages, sounds, strings) ----
| SAY label: queue the message at label (say in ui.c)
| SAYT id: queue the game's text id (TX_*, see TXT)
| SFX id: queue sound effect id (a constant, pushed as a long address
| operand: pea of a small number gives the number itself). These macros
| call C, so d0, d1, a0 and a1 are clobbered.
| TXT id, an: an = the address of the game's text id (TX_* of
| build/gen/texts.inc): the campaign block's texts table, at the offset in
| the block header's long at 24 (tools/game_text.py), starts with a word
| per text, its offset from the table. Changes no other register and no
| flag.
    .macro  TXT id, an
    lea     md_campaign, \an
    adda.l  24(\an), \an                | the texts table
    adda.w  2*\id(\an), \an            | the text (its offset in the table)
    .endm
    .macro  SAY txt
    pea     \txt
    jsr     say                         | ui.c: add the message to the status line queue
    addq.l  #4, sp                      | drop the argument
    .endm
    .macro  SAYT id
    TXT     \id, a0
    move.l  a0, -(sp)
    jsr     say                         | ui.c: add the message to the status line queue
    addq.l  #4, sp                      | drop the argument
    .endm
    .macro  SFX id
    pea     \id
    jsr     sfx                         | sound.c: queue the sound effect
    addq.l  #4, sp
    .endm

