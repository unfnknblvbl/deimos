| ======================================================================
| the C entry points (ui.c, save.c): C's registers kept, a5 = S; an
| action starts a new "secret found" count (S.secret_turn)
| ======================================================================

| C side: each wrapper is called as a C function (arguments on the stack,
| d0 the result, d2-d7 and a2-a6 kept). It saves every register the rules
| might touch, sets a5 = S, clears S.secret_turn when the call is a player
| action (action = 1: a new action may find a new secret), passes its
| first argument in d0 and in a2, calls the inner routine and returns its
| byte result in d0 (0..255).
| 48(sp): 11 saved registers (44 bytes) + the return address = the first
| argument (C passes even a char as a long).
    .macro  CENTRY name, inner, action
    .global \name
\name:
    movem.l d2-d7/a2-a6, -(sp)          | save C's d2-d7 / a2-a6 (11 registers)
    lea     S, a5                       | a5 = S for the rules
    .if \action
    clr.b   S_SECRET_TURN(a5)           | a player action: no secret found yet
    .endif
    move.l  48(sp), d0                  | (the first argument, if any)
    movea.l d0, a2                      | a2 = the argument as a pointer (resume's code string)
    bsr     \inner                      | the rules routine
    andi.l  #0xFF, d0                   | a byte result (C reads u8)
    movem.l (sp)+, d2-d7/a2-a6
    rts
    .endm

