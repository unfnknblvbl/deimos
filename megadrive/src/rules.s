| monster_turn: every active monster thinks (in list order); those that
| moved get further steps; then the attacks, newest first
| The original's update loop for the monsters, run once after each player
| action that takes a turn (called by settle_i):
|   1. the Reactor's portal may bring a monster (update_portal);
|   2. each monster on a snapshot of the active list thinks (ai_think);
|   3. while some moved, the ones that moved (walked in the order of the
|      active list as it is now) take their further steps (ai_after_step);
|   4. the queued attacks are carried out from the front of att_ent (the
|      newest first) until the player is dead;
|   5. monsters now in view become active (activate_visible).
| mt_snap, mt_movers, mt_again: word lists of entity indices.
| clobbers d0, d1, a0, a1 (d2-d7 kept)
monster_turn:
    movem.l d2-d7, -(sp)
    bsr     update_portal               | the portal's turn
    clr.b   att_n                       | no attacks yet
    move.w  S_N_ACTIVE(a5), d6          | n
    lea     S_ACTIVE(a5), a0            | a snapshot of the list
    lea     mt_snap, a1
    move.w  d6, d0
    bra.s   2f
1:  move.w  (a0)+, (a1)+
2:  dbra    d0, 1b                      | copy n words
    moveq   #0, d5                      | nm (movers)
    moveq   #0, d4                      | k
3:  cmp.w   d6, d4
    bcc.s   4f
    lea     mt_snap, a0
    move.w  d4, d0
    add.w   d0, d0
    move.w  0(a0,d0.w), d7
    move.w  d7, d0
    bsr     ai_think                    | Z clear: it moved
    beq.s   31f
    lea     mt_movers, a0
    move.w  d5, d0
    add.w   d0, d0
    move.w  d7, 0(a0,d0.w)
    addq.w  #1, d5                      | it is a mover
31: addq.w  #1, d4
    bra.s   3b
4:  tst.w   d5                          | while some moved: their next steps
    beq.s   7f
    moveq   #0, d3                      | na
    moveq   #0, d4                      | k
5:  cmp.w   S_N_ACTIVE(a5), d4
    bcc.s   6f                          | every active entity looked at
    lea     S_ACTIVE(a5), a0
    move.w  d4, d0
    add.w   d0, d0
    move.w  0(a0,d0.w), d7              | i
    lea     mt_movers, a0               | in the movers?
    move.w  d5, d0
    bra.s   52f
51: cmp.w   (a0)+, d7
    beq.s   53f
52: dbra    d0, 51b                     | search the movers
    bra.s   54f                         | not a mover
53: move.w  d7, d0
    bsr     ai_after_step               | Z clear: it moved again
    beq.s   54f
    lea     mt_again, a0
    move.w  d3, d0
    add.w   d0, d0
    move.w  d7, 0(a0,d0.w)
    addq.w  #1, d3                      | it moves on next round
54: addq.w  #1, d4
    bra.s   5b
6:  lea     mt_again, a0
    lea     mt_movers, a1
    move.w  d3, d5
    move.w  d3, d0
    bra.s   62f
61: move.w  (a0)+, (a1)+
62: dbra    d0, 61b                     | movers = those that moved again
    bra.s   4b                          | another round
7:  moveq   #0, d6                      | the attacks
    move.b  att_n, d6
    moveq   #0, d4
8:  cmp.w   d6, d4
    bcc.s   9f                          | all done
    tst.b   S_DEAD(a5)
    bne.s   9f                          | the player is dead: no more
    lea     att_kind, a0
    move.b  0(a0,d4.w), d1
    move.w  d4, d0
    add.w   d0, d0
    lea     att_tgt, a0
    move.w  0(a0,d0.w), d2
    lea     att_ent, a0
    move.w  0(a0,d0.w), d0
    bsr     monster_attack              | carry it out
    addq.w  #1, d4
    bra.s   8b
9:  clr.b   att_n
    bsr     activate_visible            | monsters now in view start to think
    movem.l (sp)+, d2-d7
    rts

| ======================================================================
| scripted events
| ======================================================================
| How events work (the original's tile events, tools/game_model.py
| run_event and exec_cmd). Each event belongs to one cell and has a list
| of commands; each command has an opcode (cmd_op) and two longs: a1, the
| argument (often packed: cell x in bits 0..7 and z in 8..15, or a string
| id), and a2, its conditions. An event is run with a long of trigger
| bits (d2 in run_event); a command runs only if:
|   - it is not used up (S.cmd_dead, one bit per command);
|   - its state bits (a2 bits 16..24) match the event's state (S.ev_state:
|     state s > 0 needs bit 16 + s - 1; state 0 needs none of them);
|   - its key bits (a2 bits 12..15), if any, equal the best key the player
|     holds (red $8000, blue $4000, green $2000, yellow $1000);
|   - a2 shares at least one bit with the trigger: bits 0..3 entering the
|     cell (ARRIVE_FLAG, by the step's direction), 4..7 leaving it
|     (LEAVE_FLAG), $100 used, $400 moved, 28..31 the player's facing
|     (FACING_FLAG).
| Bit 9 of a2 (EVF_MODIFY) makes the command one-shot. A command that
| opens a dialog, asks for a code or refuses (suspend) stops the event;
| where it stopped is kept in pend_* so resume can go on after it.

