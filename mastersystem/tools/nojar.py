"""
The Master System and Game Gear build without DoomRPG.jar (build.sh with
DEIMOS_NOJAR=1): every file the assembler reads, with the parts that come
from the jar or the map left as zeros. The ROM it gives is no game (no
map, no pictures, no texts) but has the engine's code and tables exactly
where the full build has them, so tools/make_engine.py makes the same
engine from it.

What is written:
  game/gen/            defs.inc, tables.inc, texts.inc, layout.json - the
                       full build's (gen_cdata.write_includes: the rules,
                       limits and text indices, none of them from the jar)
  build/gfx/           the UI pictures (hud_palette, font_index, hud_tiles,
                       hud_static, title_tiles, title_map, dlg_font and the
                       Game Gear's _gg ones) as zeros, each the size the
                       engine's region for it has (../editor/engines/
                       sg8.eng and sg8hh.eng: the sizes the jar's pictures
                       give; code after them is placed by those sizes);
                       the texts, the level blob, the strings and the
                       sprite directories as zeros (blanked in the engine)
  build/gfx/live/      c2p.bin, table_large.bin, table_small.bin,
                       unroll.inc, state.inc (the renderer's own tables and
                       code, as tools/live_data.py makes them), and the
                       level's data banks as zeros (bank 3 and bank 9)
  build/gfx/           sprite_banks_large.inc, sprite_banks_small.inc (one
                       zero bank each, 10 and 11) and rom_dir.inc (zeros:
                       the editor writes the directory)

Usage: nojar.py <engines dir>     (run from mastersystem/)
Licence: GPL-2.0-or-later.
"""
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parents[1] / "tools"))
from engine_file import regions          # noqa: E402  (../../tools/engine_file.py)

BANK = 0x4000
GG_FILES = {"hud_tiles", "font_index", "hud_static", "title_tiles", "title_map"}   # (as make_engine.py)
UI = ["hud_palette", "font_index", "hud_tiles", "hud_static", "title_tiles", "title_map", "dlg_font"]


def main():
    """Write the stand-ins (see the module docstring)."""
    engines = Path(sys.argv[1])
    root = HERE.parent
    gen, gfx = root / "game" / "gen", root / "build" / "gfx"
    live = gfx / "live"
    for d in (gen, gfx, live):
        d.mkdir(parents=True, exist_ok=True)
    # the rules' includes (gen_cdata.py) - before live_data is imported,
    # which reads game/gen/layout.json
    import gen_cdata
    gen_cdata.write_includes(gen)
    # the UI pictures: zeros of the engines' region sizes
    sms, gg = regions(engines / "sg8.eng"), regions(engines / "sg8hh.eng")
    for name in UI:
        (gfx / f"{name}.bin").write_bytes(bytes(sms[name][1]))
        if name in GG_FILES:
            (gfx / f"{name}_gg.bin").write_bytes(bytes(gg[name][1]))
        elif gg[name][1] != sms[name][1]:
            raise SystemExit(f"{name}: the two engines disagree on its size")
    # the level's parts (blanked in the engine; any size up to their room)
    for name in ("texts", "texts_gg", "level", "strings", "strings_gg"):
        (gfx / f"{name}.bin").write_bytes(bytes(16))
    (gfx / "sprite_dir_small.bin").write_bytes(bytes(1024))
    (gfx / "sprite_dir_large.bin").write_bytes(bytes(64 * 4 * 4 + 64 * 16))
    # the renderer's tables and code (tools/live_data.py)
    import live_data as L
    L.check_layout_inc()
    for name, (W, H) in L.SIZES.items():
        (live / f"table_{name}.bin").write_bytes(L.size_table(W, H)[0])
    (live / "c2p.bin").write_bytes(L.c2p_tables())
    (live / "unroll.inc").write_text(L.unrolled_fill())
    (live / "state.inc").write_text(f"; generated by tools/live_data.py from game/gen/layout.json\n"
                                    f".define L_FLAGS          ${L.LAYOUT['fields']['l_flags'][0] + 0xC400:04X}\n")
    for p in live.glob("data_*.bin"):
        p.unlink()
    with open(live / "data_banks.inc", "w") as fp:
        fp.write("; written by tools/nojar.py: the level's data banks, empty\n")
        for bank in (3, L.FIRST_DATA_BANK):
            (live / f"data_{bank}.bin").write_bytes(bytes(BANK))
            fp.write(f".BANK {bank} SLOT 2\n.ORGA $8000\n.incbin \"build/gfx/live/data_{bank}.bin\"\n")
    # the sprites' banks, one empty bank per view size
    for p in gfx.glob("sprite_bank_*.bin"):
        p.unlink()
    for i, size in enumerate(("large", "small")):
        bank = L.FIRST_DATA_BANK + 1 + i
        fn = f"sprite_bank_{bank}.bin"
        (gfx / fn).write_bytes(bytes(BANK))
        (gfx / f"sprite_banks_{size}.inc").write_text(
            f"; written by tools/nojar.py\n.BANK {bank} SLOT 2\n.ORGA $8000\n.incbin \"build/gfx/{fn}\"\n")
    (gfx / "rom_dir.inc").write_text("; written by tools/nojar.py (the editor writes the directory)\n"
                                     ".db " + ", ".join(["$00"] * 16) + "\n")
    print("no-jar stand-ins written (game/gen, build/gfx)")


if __name__ == "__main__":
    main()
