    cmpi.w  #2, (sp)
    bne     2b                          | a second step
    addq.l  #2, sp
    moveq   #0, d0                      | 2 + ex^2 + ez^2
    move.b  d4, d0
    moveq   #0, d1
    move.b  d2, d1
    sub.w   d1, d0
    muls.w  d0, d0
    moveq   #0, d1
    move.b  d5, d1
    moveq   #0, d6
    move.b  d3, d6
    sub.w   d6, d1
    muls.w  d1, d1
    add.w   d1, d0
    addq.w  #2, d0
9:  movem.l (sp)+, d2-d7
    rts

| ai_move: entity d0.w steps toward (d1.b, d1 >> 8) by a two-step greedy
| look-ahead, ties broken at random -> Z clear (bne) if it moved
| For each direction (east, west, south, north) the monster can step into,
| calc_path rates the cell; those with the lowest cost are kept in
| order[], and one of them is picked at random (one rnd, only if any).
| Stack: n (word), order[4] (bytes), the target word; a2 = order.
|   in:  d0.w = entity, d1.w = target (x low byte, z high byte)
|   out: d0.l = 1 moved, 0 not; flags from it
|   clobbers d0, d1, a0, a1 (d2-d7, a2 kept)
| Called by the monsters' turn.
ai_move:
    movem.l d2-d7/a2, -(sp)
    move.w  d0, d7                      | i
    move.w  d1, -(sp)                   | target (x low byte, z high byte)
    bsr     monster_mask                | d0 = what it may not cross
    move.w  d0, cp_mask
    move.w  d7, cp_ent
    lea     S_E_X(a5), a0
    move.b  0(a0,d7.w), d4              | sx
    lea     S_E_Z(a5), a0
    move.b  0(a0,d7.w), d5              | sz
    move.w  #9999, d6                   | best
    subq.l  #4, sp                      | order[4]
    movea.l sp, a2
    clr.w   -(sp)                       | n
    moveq   #0, d2                      | d
1:  movem.l d2-d3, -(sp)
    move.w  d2, d1                      | (d)
    lea     OX, a0
    move.b  d4, d2
    add.b   0(a0,d1.w), d2
    lea     OZ, a0
    move.b  d5, d3
    add.b   0(a0,d1.w), d3
    move.b  d4, d0
    move.b  d5, d1
    bsr     can_step                    | Z set: it can step that way
    bne.s   5f                          | can't step that way
    move.b  d2, d0                      | pd = calc_path(the cell, target)
    move.b  d3, d1
    move.w  14(sp), d2                  | (the target word: 8 regs + n + order)
    move.w  d2, d3
    lsr.w   #8, d3
    bsr     calc_path                   | d0 = the cost from that cell
    move.l  (sp), d2                    | d
| (East is the first direction tried, so best is still 9999 here and the
| east branch does the same as the general one below.)
    lea     CODE, a0
    cmpi.b  #2, 0(a0,d2.w)
    bne.s   3f
    cmpi.w  #9999, d0                   | east (code 2): first in order
    bcc.s   2f
    move.w  d0, d6
    clr.w   8(sp)
    bra.s   4f
2:  bne.s   5f                          | (pd > 9999: no)
    bra.s   4f
3:  cmp.w   d6, d0                      | a lower cost: the list starts again
    bcc.s   31f
    move.w  d0, d6
    clr.w   8(sp)
    bra.s   4f
31: bne.s   5f                          | higher: not kept
4:  move.w  8(sp), d0                   | order[n++] = d
    move.b  d2, 0(a2,d0.w)
    addq.w  #1, 8(sp)
5:  movem.l (sp)+, d2-d3
    addq.w  #1, d2                      | the next direction
    cmpi.w  #4, d2
    bne.s   1b
    move.w  (sp)+, d3                   | n
    beq.s   8f                          | nowhere to go
    bsr     rnd                         | pick = order[(rnd & 3) % n]
    andi.w  #3, d0
    divu.w  d3, d0
    swap    d0                          | the remainder (0..n-1)
    moveq   #0, d1
    move.b  0(a2,d0.w), d1              | d1 = the direction picked
    lea     OX, a0
    move.b  d4, d0
    add.b   0(a0,d1.w), d0
    lea     OZ, a0
    move.b  d5, d2
    add.b   0(a0,d1.w), d2
    lsl.w   #8, d2
    move.b  d0, d2                      | d2 = new x low byte, new z high byte
    move.w  d2, d1
    move.w  d7, d0
    bsr     ent_move_to                 | move it to that cell
    moveq   #1, d0
    bra.s   9f
8:  moveq   #0, d0
9:  addq.l  #6, sp                      | order, target
    movem.l (sp)+, d2-d7/a2
    tst.w   d0
    rts

| queue_attack: entity d0.w will attack (kind d1.b, target d2.b) this
| turn, newest first, once
| The attacks found during a monster turn are carried out afterwards in
| the list's order: att_ent (who), att_kind (T_*), att_tgt (whom), att_n
| entries, at most MAX_ACTIVE. An entity already in the list is not added
| again. A new entry goes to the front (the rest shifts down).
|   in:  d0.w = attacker, d1.b = target kind (T_*), d2.w = target
|   clobbers a0, a1 (d0-d2 kept; d3, d4, a2 saved)
queue_attack:
    movem.l d3-d4/a2, -(sp)
    moveq   #0, d3
    move.b  att_n, d3
    lea     att_ent, a0
    move.w  d3, d4
    bra.s   2f
1:  cmp.w   (a0)+, d0
    beq.s   9f                          | queued already
2:  dbra    d4, 1b                      | search the n entries
    cmpi.w  #MAX_ACTIVE, d3
    bcc.s   9f                          | full
    lea     att_ent, a0                 | make room at the front
    lea     att_kind, a1
    lea     att_tgt, a2
    move.w  d3, d4
    bra.s   4f
3:  move.b  -1(a1,d4.w), 0(a1,d4.w)
    add.w   d4, d4
    move.w  -2(a0,d4.w), 0(a0,d4.w)
    move.w  -2(a2,d4.w), 0(a2,d4.w)
    lsr.w   #1, d4
    subq.w  #1, d4
4:  tst.w   d4
    bne.s   3b                          | (d4 counts down from n to 1)
    move.w  d0, (a0)
    move.b  d1, (a1)
    move.w  d2, (a2)
    addq.b  #1, att_n                   | one more
9:  movem.l (sp)+, d3-d4/a2
    rts

| attack_weapon: d0.w = the weapon entity d0.w attacks with
| mon_atk holds two attacks (weapon numbers) per monster class; the
| second is used while the entity has F_ATK2.
| clobbers d1, a0 (d2 kept)
attack_weapon:
    move.l  d2, -(sp)
    move.w  d0, d2
    bsr     esub                        | d0 = its class
    add.w   d0, d0                      | two bytes per class
    lea     S_E_FLAGS(a5), a0
    btst    #B_ATK2, 0(a0,d2.w)
    beq.s   1f
    addq.w  #1, d0                      | F_ATK2: its second attack
1:  lea     mon_atk, a0
    move.b  0(a0,d0.w), d0
    andi.w  #0xFF, d0
    move.l  (sp)+, d2
    rts

| dist2: d0.w = (d0.b - d2.b)^2 + (d1.b - d3.b)^2
| (all bytes unsigned: cell coordinates.) d2 is kept, d3 is read only.
| clobbers d1
dist2:
    andi.w  #0xFF, d0
    andi.w  #0xFF, d1
    move.l  d2, -(sp)
    andi.w  #0xFF, d2
    sub.w   d2, d0
    muls.w  d0, d0
    move.w  d3, d2
    andi.w  #0xFF, d2
    sub.w   d2, d1
    muls.w  d1, d1
    add.w   d1, d0
    move.l  (sp)+, d2
    rts

| ai_think: entity d0.w decides: move, attack or (Archvile) raise a corpse
| -> Z clear (bne) if it moved
| (one monster's part of monster_turn; the original's AI think step)
| An Arch-vile (class 10) first, with chance 84/256, looks for a corpse
| among the map entities at squared distance 1..4 that is not being
| raised and has nothing standing on it; it queues a T_RAISE on the first
| one and stops there. Otherwise an Arch-vile switches its attack (F_ATK2).
| Then every monster: reach = its attack's rmin + 1. It can hit (th_hit)
| when it is in the player's row or column, within reach, and a shot
| (MASK_SHOT trace) is clear; a barrel or crate first in the way becomes
| the target instead. It attacks if it can hit, except that with half the
| reach > 0 it still moves with chance 39/256. Moving goes toward the cell
| in front of the player (ai_move); close and aligned (within half the
| reach), with chance 38/256 that target is shifted one cell toward the
| monster's side. A monster that cannot move attacks if it can hit.
| Up to three rnd draws, each one only when the branch needs it.
|   in:  d0.w = entity
|   out: d0.l = 1 (Z clear) moved, 0 not; S.e_move = 0 when it moved
|   clobbers d0, d1, a0, a1 (d2-d7 kept)
ai_think:
    movem.l d2-d7, -(sp)
    move.w  d0, d7                      | i
    bsr     esub                        | d0 = its class
    cmpi.w  #10, d0                     | 10: Infernis / Arch-vile / Apollyon
    bne     3f
    | an Archvile: sometimes raises a corpse within reach
    bsr     rnd
    cmpi.w  #84, d0
    bcc   2f                            | (84/256: look for a corpse)
    moveq   #0, d6                      | j
1:  cmp.w   n_map_ents, d6
    bcc   2f                            | no corpse near: an attack instead
    lea     S_E_FLAGS(a5), a0
    btst    #B_CORPSE, 0(a0,d6.w)
    beq.s   11f                         | not a corpse
    lea     S_E_X(a5), a0
    move.b  0(a0,d6.w), d0
    move.b  0(a0,d7.w), d2
    lea     S_E_Z(a5), a0
    move.b  0(a0,d6.w), d1
    move.b  0(a0,d7.w), d3
    bsr     dist2                       | d0 = squared distance to the corpse
    tst.w   d0
    beq.s   11f                         | (its own cell: no)
    cmpi.w  #4, d0
    bhi.s   11f                         | farther than 2 cells (squared distance > 4)
    lea     S_E_FLAGS(a5), a0
    btst    #B_RAISING, 0(a0,d6.w)
    bne.s   11f                         | already being raised
    lea     S_E_X(a5), a0               | something already standing on it?
    move.b  0(a0,d6.w), d0
    move.b  d0, d2
    lea     S_E_Z(a5), a0
    move.b  0(a0,d6.w), d1
    move.b  d1, d3
    move.w  #MASK_RAISE_FREE, d4        | what would stop the body standing up
    move.w  #NONE, d5
    bsr     trace                       | a trace on the corpse's own cell
    bne.s   11f                         | something is there
    lea     S_E_FLAGS(a5), a0
    bset    #B_RAISING, 0(a0,d6.w)      | (no other Arch-vile takes it)
    move.w  d7, d0
    moveq   #T_RAISE, d1
    move.w  d6, d2
    bsr     queue_attack                | raise it when the attacks are carried out
    moveq   #0, d0                      | (did not move)
    bra     9f
11: addq.w  #1, d6
    bra   1b                            | the next entity
2:  lea     S_E_FLAGS(a5), a0
    bchg    #B_ATK2, 0(a0,d7.w)         | alternate between its two attacks
3:  move.w  d7, d0
    bsr     attack_weapon               | d0 = its weapon now
    lea     wpn_rmin, a0
    moveq   #0, d6
    move.b  0(a0,d0.w), d6
    addq.w  #1, d6                      | reach
    lea     S_E_X(a5), a0
    move.b  0(a0,d7.w), d0
    lea     S_E_Z(a5), a0
    move.b  0(a0,d7.w), d1
    move.b  S_PX(a5), d2
    move.b  S_PZ(a5), d3
    bsr     dist2                       | d0 = squared distance to the player
    move.w  d0, d5                      | d2 (squared distance)
    moveq   #0, d4                      | aligned
    lea     S_E_X(a5), a0
    move.b  0(a0,d7.w), d0
    cmp.b   S_PX(a5), d0
    beq.s   4f                          | same column
    lea     S_E_Z(a5), a0
    move.b  0(a0,d7.w), d0
    cmp.b   S_PZ(a5), d0
    bne.s   5f                          | not in a line with the player
4:  moveq   #1, d4
5:  clr.b   th_hit                      | can_hit, kind, target
    move.b  #T_PLAYER, th_kind
    clr.w   th_tgt
    tst.b   d4
    beq.s   7f                          | not aligned: cannot hit
    move.w  d6, d0
    mulu.w  d6, d0
    cmp.w   d0, d5
    bhi.s   7f                          | out of reach
    movem.l d4-d5, -(sp)
    lea     S_E_X(a5), a0
    move.b  0(a0,d7.w), d0
    lea     S_E_Z(a5), a0
    move.b  0(a0,d7.w), d1
    move.b  S_PX(a5), d2
    move.b  S_PZ(a5), d3
    move.w  #MASK_SHOT, d4
    move.w  d7, d5
    bsr     trace                       | Z set: nothing in the way
    movem.l (sp)+, d4-d5
    beq.s   6f                          | a clear shot
    cmpi.b  #H_ENT, hit_kind            | a barrel or crate in the way: hit that
    bne.s   7f
    move.w  hit_val, d0
    bsr     etype                       | d0 = its type
    cmpi.w  #ET_DESTRUCT, d0
    bne.s   7f                          | a wall, door or someone else: cannot hit
    move.b  #T_ENT, th_kind
    move.w  hit_val, th_tgt
6:  st      th_hit
7:  move.w  d6, d3
    lsr.w   #1, d3                      | half
    tst.b   th_hit                      | !can_hit || (half && rnd >= 217): move
    beq.s   8f
    tst.w   d3
    beq     10f                         | half 0: attack
    bsr     rnd                         | d0 = r (0..255)
    cmpi.w  #217, d0
    bcs     10f                         | r < 217: attack
8:  | toward the cell in front of the player (or beside it)
    moveq   #0, d0
    move.b  S_FACING(a5), d0
    lea     DX, a0
    move.b  S_PX(a5), d1
    add.b   0(a0,d0.w), d1              | tx
    lea     DZ, a0
    move.b  S_PZ(a5), d2
    add.b   0(a0,d0.w), d2              | tz
    move.w  d3, d0
    mulu.w  d3, d0
    cmp.w   d0, d5
    bhi.s   82f                         | farther than half the reach
    tst.b   d4
    beq.s   82f                         | not aligned
    movem.l d1-d2, -(sp)
    bsr     rnd                         | d0 = r (0..255)
    move.w  d0, d6
    movem.l (sp)+, d1-d2
    cmpi.w  #38, d6
    bcc.s   82f                         | r >= 38: no shift
    lea     S_E_X(a5), a0
    move.b  0(a0,d7.w), d0
    cmp.b   S_PX(a5), d0
    bcc.s   80f                         | monster x >= player x
    subq.b  #1, d1                      | the monster is west: one cell west
    bra.s   81f
80: beq.s   81f                         | same x: no shift
    addq.b  #1, d1                      | the monster is east: one cell east
81: lea     S_E_Z(a5), a0
    move.b  0(a0,d7.w), d0
    cmp.b   S_PZ(a5), d0
    bcc.s   811f                        | monster z >= player z
    subq.b  #1, d2                      | the monster is north: one cell north
    bra.s   82f
811: beq.s  82f                         | same z: no shift
    addq.b  #1, d2                      | the monster is south: one cell south
82: lsl.w   #8, d2
    move.b  d1, d2
    move.w  d2, d1
    move.w  d7, d0
    bsr     ai_move                     | Z clear: it moved
    bne.s   83f
    tst.b   th_hit                      | could not move: attack if it can
    beq.s   9f
    bra.s   10f
83: lea     S_E_MOVE(a5), a0
    clr.b   0(a0,d7.w)                  | steps taken this turn: 0 (ai_after_step counts them)
    moveq   #1, d0
    bra.s   99f
10: move.w  d7, d0
    move.b  th_kind, d1
    move.w  th_tgt, d2
    bsr     queue_attack                | attack (or a barrel in the way) later this turn
9:  moveq   #0, d0
99: movem.l (sp)+, d2-d7
    tst.w   d0
    rts

| ai_think's decision, carried to the end of the routine
    .bss
    .even
th_hit:     .space  1                   | ai_think: can it hit, how, what
th_kind:    .space  1                   | T_PLAYER or T_ENT (a barrel / crate in the way)
th_tgt:     .space  2                   | the entity when T_ENT
    .text

| ai_after_step: entity d0.w has finished a step: on (lost souls go three
| steps), or lunge -> Z clear (bne) if it moved again
| Called by monster_turn for each monster that moved, until none moves.
| S.e_move counts the steps this turn; classes 4 (Phantom, lost souls,
| Nightmare) and 13 (Kronos) take up to 3 steps, the others 1. A monster
| that reaches a cell next to the player (same row or column) stops there.
| After its last step, classes 1 (dogs), 4, 5 (Pinky,
| Belphegor) and 13 lunge: next to the player with a clear shot, they
| queue an attack on the player.
|   in:  d0.w = entity
|   out: d0.l = 1 (Z clear) it moved again, 0 not
|   clobbers d0, d1, a0, a1 (d2-d7 kept)
ai_after_step:
    movem.l d2-d7, -(sp)
    move.w  d0, d7
    bsr     esub                        | d0 = its class
    move.w  d0, d6                      | es
    moveq   #1, d5                      | steps
    cmpi.w  #4, d6
    beq.s   1f
    cmpi.w  #13, d6
    bne.s   2f
1:  moveq   #3, d5
2:  moveq   #0, d4                      | adjacent and aligned
    lea     S_E_X(a5), a0
    move.b  0(a0,d7.w), d0
    lea     S_E_Z(a5), a0
    move.b  0(a0,d7.w), d1
    cmp.b   S_PX(a5), d0
    beq.s   3f                          | same column
    cmp.b   S_PZ(a5), d1
    bne.s   4f                          | not in a line with the player
3:  move.b  S_PX(a5), d2
    move.b  S_PZ(a5), d3
    bsr     dist2                       | d0 = squared distance
    cmpi.w  #1, d0
    bhi.s   4f                          | not next to the player
    moveq   #1, d4
4:  lea     S_E_MOVE(a5), a0
    addq.b  #1, 0(a0,d7.w)              | one more step done
    move.b  0(a0,d7.w), d0
    cmp.b   d5, d0
    bcc.s   6f                          | all its steps taken
    tst.b   d4
    beq.s   5f                          | not next to the player: another step
    move.b  d5, 0(a0,d7.w)              | next to the player: no more steps
    bra.s   6f
5:  move.b  S_PZ(a5), d1
    lsl.w   #8, d1
    move.b  S_PX(a5), d1
    move.w  d7, d0
    bsr     ai_move                     | toward the player's own cell
    beq.s   6f                          | could not move
    moveq   #1, d0                      | moved
    bra.s   9f
6:  lea     S_E_MOVE(a5), a0            | a lunge (pinkies, dogs, lost souls)
    cmp.b   0(a0,d7.w), d5
    bne.s   8f                          | not at the end of its steps
    tst.b   d4
    beq.s   8f                          | not next to the player
    cmpi.w  #5, d6
    beq.s   7f
    cmpi.w  #4, d6
    beq.s   7f
    cmpi.w  #1, d6
    beq.s   7f
    cmpi.w  #13, d6
    bne.s   8f                          | the other classes do not lunge
7:  lea     S_E_X(a5), a0
    move.b  0(a0,d7.w), d0
    lea     S_E_Z(a5), a0
    move.b  0(a0,d7.w), d1
    move.b  S_PX(a5), d2
    move.b  S_PZ(a5), d3
    move.w  #MASK_SHOT, d4
    move.w  d7, d5
    bsr     trace                       | Z set: nothing between it and the player
    bne.s   8f                          | something in the way
    move.w  d7, d0
    moveq   #T_PLAYER, d1
    moveq   #0, d2
    bsr     queue_attack                | attack the player later this turn
8:  moveq   #0, d0
9:  movem.l (sp)+, d2-d7
    tst.w   d0
    rts

