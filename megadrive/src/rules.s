| calc_path: the cost of going from (d0.b, d1.b) to (d2.b, d3.b): two
| greedy steps (0 / 1 when reached after the first / second), else 2 +
| the squared distance left
| The original's look-ahead: from the start, step in the direction that
| brings the squared distance down most (that the mover can take, ties:
| the first in OX order); do that twice. Uses cp_mask / cp_ent.
|   in:  d0.b, d1.b = start; d2.b, d3.b = target
|   out: d0.w = the cost (0 for the start itself)
|   clobbers d0, d1, a0, a1 (d2-d7 kept)
| Called by ai_move for each cell next to the monster.
calc_path:
    movem.l d2-d7, -(sp)
    move.b  d0, d4                      | sx
    move.b  d1, d5                      | sz
    cmp.b   d2, d4
    bne.s   1f
    cmp.b   d3, d5
    bne.s   1f
    moveq   #0, d0
    bra     9f                          | already there: 0
1:  clr.w   -(sp)                       | k
2:  move.w  #0xFFFF, d6                 | best
    clr.w   -(sp)                       | stx:stz (bytes)
    moveq   #0, d7                      | direction
3:  lea     OX, a0                      | ex = sx + ox - dx, ez = sz + oz - dz
    move.b  0(a0,d7.w), d0
    ext.w   d0
    moveq   #0, d1
    move.b  d4, d1
    add.w   d1, d0
    moveq   #0, d1
    move.b  d2, d1
    sub.w   d1, d0
    muls.w  d0, d0
    lea     OZ, a0
    move.b  0(a0,d7.w), d1
    ext.w   d1
    move.w  d1, a1
    moveq   #0, d1
    move.b  d5, d1
    add.w   a1, d1
    move.w  d1, a1
    moveq   #0, d1
    move.b  d3, d1
    sub.w   d1, a1
    move.w  a1, d1
    muls.w  d1, d1
    add.w   d1, d0                      | nd
    cmp.w   d6, d0
    bcc.s   4f                          | not nearer than the best so far
    movem.l d0/d2-d3, -(sp)             | (only then: can it step?)
    lea     OX, a0
    move.b  d4, d2
    add.b   0(a0,d7.w), d2
    lea     OZ, a0
    move.b  d5, d3
    add.b   0(a0,d7.w), d3
    move.b  d4, d0
    move.b  d5, d1
    bsr     can_step                    | Z set: the mover can take that step
    movem.l (sp)+, d0/d2-d3
    bne.s   4f                          | blocked
    move.w  d0, d6                      | the best so far
    lea     OX, a0
    move.b  0(a0,d7.w), (sp)
    lea     OZ, a0
    move.b  0(a0,d7.w), 1(sp)
4:  addq.w  #1, d7
    cmpi.w  #4, d7
    bne   3b                            | the next direction
    add.b   (sp), d4
    add.b   1(sp), d5                   | take the best step (none: stay)
    addq.l  #2, sp
    cmp.b   d2, d4
    bne.s   5f
    cmp.b   d3, d5                      | reached the target?
    bne.s   5f
    move.w  (sp)+, d0                   | reached: k
    bra.s   9f
