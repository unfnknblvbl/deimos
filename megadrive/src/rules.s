| rnd: d0.w = the next random byte (0..255): S.rng ^= rng << 7;
| ^= rng >> 9; ^= rng << 8 (xorshift, period 65535)
| A 16-bit xorshift generator: the same one the Python model uses, so both
| draw identical numbers in the same order (the lockstep test depends on it).
|   in:  S.rng (a5)
|   out: d0.l = 0..255, S.rng advanced
|   clobbers d1
    .global rnd
rnd:
    moveq   #0, d0                      | (d0.l = 0..255)
    move.w  S_RNG(a5), d0
    move.w  d0, d1
    lsl.w   #7, d1
    eor.w   d1, d0
    move.w  d0, d1
    lsr.w   #8, d1
| (lsr by 9 done as 8 + 1: an immediate shift count is at most 8)
    lsr.w   #1, d1
    eor.w   d1, d0
    move.w  d0, d1
    lsl.w   #8, d1
    eor.w   d1, d0
    move.w  d0, S_RNG(a5)
    andi.w  #0xFF, d0
    rts

| rnd32: d0.l = four random bytes, the first in the low byte
| Draws four bytes with rnd, in order; the first one ends in bits 0..7,
| the second in 8..15, the third in 16..23, the fourth in 24..31.
| clobbers d1 (d2 kept)
rnd32:
    move.l  d2, -(sp)
    bsr.s   rnd                         | byte 0
    move.l  d0, d2
    bsr.s   rnd                         | byte 1
    lsl.w   #8, d0
    or.w    d0, d2
    bsr.s   rnd                         | byte 2 (swap: into bits 16..23)
    swap    d0
    or.l    d0, d2
    bsr.s   rnd                         | byte 3 (swap and shift: bits 24..31)
    swap    d0
    lsl.l   #8, d0
    or.l    d0, d2
    move.l  d2, d0
    move.l  (sp)+, d2
    rts

| clamp8: d0.l (signed) -> 0..255
| (no other register touched)
clamp8:
    tst.l   d0
    bpl.s   1f
    moveq   #0, d0
    rts
1:  cmpi.l  #255, d0
    ble.s   2f
    move.l  #255, d0
2:  rts

| mask_has: Z clear (bne) if mask d1.w has bit d0.w (type; 16 and up: no)
| Used with the trace masks above. Only d0 and d1 are read; nothing is
| written but the flags.
mask_has:
    cmpi.w  #16, d0
    bcs.s   1f
    cmp.w   d0, d0                      | (Z set: no)
    rts
1:  btst    d0, d1
    rts

| fdiv: d0.w = floor(d0.w / d1.w), d1 > 0
| (floor, not truncation: C and divs round toward zero, Python floors.)
| d1.w is replaced by the remainder. out: d0.l = the quotient, sign-extended.
fdiv:
    ext.l   d0
    divs.w  d1, d0                      | d0 = remainder:quotient
    move.l  d0, d1
    swap    d1                          | remainder
    tst.w   d1                          | no remainder: exact
    beq.s   1f
    tst.w   d1                          | (a negative remainder: the numerator was negative)
    bpl.s   1f
    subq.w  #1, d0
1:  ext.l   d0
    rts

| etype / esub: d0.w = the type / subtype of entity d0.w
|   in:  d0.w = entity index
|   out: d0.l = def_etype / def_esub of its def (0..255)
|   clobbers d1, a0
etype:
    lea     S_E_DEF(a5), a0
    moveq   #0, d1                      | d1 = the entity's def
    move.b  0(a0,d0.w), d1
    movea.l def_etype, a0
    moveq   #0, d0
    move.b  0(a0,d1.w), d0
    rts
esub:
    lea     S_E_DEF(a5), a0
    moveq   #0, d1
    move.b  0(a0,d0.w), d1
    movea.l def_esub, a0
    moveq   #0, d0
    move.b  0(a0,d1.w), d0
    rts

| def_name: a0 = the name of def d0.w
| The names follow the offset table: offset i is counted from the table's
| start (def_name_off), and each name is upper case and 0-terminated.
|   out: a0 = the name; clobbers d0
def_name:
    movea.l def_name_off, a0
    add.w   d0, d0
    move.w  0(a0,d0.w), d0
    adda.w  d0, a0
    rts

| ent_name: a0 = the name of entity d0.w's def
| clobbers d0, d1
ent_name:
