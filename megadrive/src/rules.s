    .equ    ET_INV, 4                   | an inventory item (medkits, Berserker, collar...)
    .equ    ET_WEAPON, 5                | a weapon pick-up
    .equ    ET_AMMO, 6                  | an ammunition pick-up
    .equ    ET_FIRE, 10                 | fire hazards (hurt whoever stands in them)
    .equ    ET_FIRE2, 11
    .equ    ET_DESTRUCT, 12             | a destructible prop: barrels, crates, power couplings
    .equ    ET_AMMO2, 16                | ammunition dropped by a monster or crate

