"""
The portable game core's generated headers, from the Mega Drive game's
tools/gen_cdata.py (the same limits, tables and game-state layout):

  core/gen/state.h   struct state: the state S, field for field in the
                     layout the lockstep tests compare (gen_cdata's
                     state_layout()), every field as bytes - words and
                     longs big-endian - so the struct has no padding and
                     the same bytes on every CPU (S_GET16 / S_PUT16 ...)
  core/gen/sfx.h     the sound effects' ids (megadrive/tools/build_sfx.py)
  core/gen/data.h, data.c   weapon, monster and damage tables, limits,
                     level-blob table indices (gen_cdata's own output)

Usage: gen_core.py <deimos dir> <out dir = core/gen>

It also writes core/gen/layout.json (each field's offset and size, and the
state's size) for the tests. The Mega Drive game must have been built (its
build/gen/sfx.h). "Lockstep": the tests that play the game on a port and
in the Mega Drive game's Python model side by side, comparing S after every action;
only the fields before "end_compared" take part.
Licence: GPL-2.0-or-later.
"""
import json
import subprocess
import sys
from pathlib import Path


def main():
    """Write core/gen's files from the Mega Drive game checkout given."""
    md = Path(sys.argv[1]).resolve()
    out = Path(sys.argv[2] if len(sys.argv) > 2 else "core/gen")
    out.mkdir(parents=True, exist_ok=True)
    sys.path.insert(0, str(md / "tools"))
    import gen_cdata
    camp = md / "analysis" / "campaign.json"
    tmp = out / "_tmp"
    # gen_cdata's own output (data.h, data.c, the maps) into a scratch folder
    subprocess.run([sys.executable, str(md / "tools" / "gen_cdata.py"), str(camp), str(tmp), str(tmp / "maps")],
                   check=True, capture_output=True)
    # data.h without the Mega Drive game's blob pointers (the ports load levels through map_level)
    (out / "data.h").write_text((tmp / "data.h").read_text().replace(
        "extern const unsigned char *level_blob, *strings_blob;\n", ""))
    (out / "data.c").write_text((tmp / "data.c").read_text())
    (out / "sfx.h").write_text((md / "build" / "gen" / "sfx.h").read_text())   # (build_sfx.py's ids)
    lay = gen_cdata.state_layout()          # [(name, size)], in the model's byte order
    h = ["/* Generated by tools/gen_core.py - do not edit */",
         "#ifndef CORE_STATE_H", "#define CORE_STATE_H", '#include "data.h"',
         "/* the game state: bytes only (words, longs big-endian), no padding */",
         "struct state {"]
    off = 0
    offs = []
    for name, size in lay:
        if name == "end_compared":
            h.append("    /* ---- end of the part the lockstep tests compare ---- */")
            continue
        # every field bytes (an array when it is a word, a long or bigger)
        h.append(f"    u8 {name}" + (f"[{size}];" if size > 1 or name in gen_cdata.WORDS or name in gen_cdata.LONGS
                                     else ";"))
        offs.append((name, off))
        off += size
    h.append("};")
    h.append(f"#define STATE_SIZE {off}")
    for nm, v in (("MAX_SPAWNS", gen_cdata.MAX_SPAWNS),):
        h.append(f"#define {nm} {v}")
    h.append("#endif")
    (out / "state.h").write_text("\n".join(h) + "\n")
    (out / "layout.json").write_text(json.dumps({"fields": {n: [o, s] for (n, s), (_n, o) in
                                                             zip([x for x in lay if x[0] != "end_compared"], offs)},
                                                  "size": off}, indent=1))
    # the scratch folder removed
    for f in tmp.rglob("*"):
        if f.is_file():
            f.unlink()
    for d in sorted(tmp.rglob("*"), reverse=True):
        d.rmdir()
    tmp.rmdir()
    print(f"core/gen: state {off} bytes")


if __name__ == "__main__":
    main()
