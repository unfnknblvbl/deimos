"""
The ROM directory: 16 bytes in bank 1 at $7FC0 that say where the parts
made for the level are (docs/rom_format.md). The game itself doesn't read
it; it marks the ROM as this port's and is there for tools that look
inside a ROM. The Deimos Editor's builder (editor/src/sms_build.cpp)
writes the same bytes.

Usage: python3 rom_dir.py <gfx_dir>

Run by build.sh (step 3) after the sprite banks are built. Reads the bank
numbers of gfx_dir's live/data_N.bin (tools/live_data.py) and
sprite_bank_N.bin (tools/build_sprites.py) files; writes gfx_dir/rom_dir.inc
(the directory as one WLA-DX .db line).

Layout:
  "DEIMDIR1"  u8 version (4)
  u8 9, u8 n            the level's data banks 9 .. 9 + n - 1 (and bank 3)
  u8 first sprite bank, u8 number of sprite banks (both view sizes)
  3 zero bytes
Licence: GPL-2.0-or-later.
"""
import sys
from pathlib import Path

VERSION = 4                     # the directory's layout (4: no editable copy of the level)
FIRST_DATA_BANK = 9             # the level's big tables start here (tools/live_data.py)


def directory(gfx: Path) -> bytes:
    """The 16 directory bytes for the banks the build wrote into gfx (layout above)."""
    sprites = sorted(int(p.stem.split("_")[-1]) for p in gfx.glob("sprite_bank_*.bin"))
    data = sorted(int(p.stem.split("_")[-1]) for p in (gfx / "live").glob("data_*.bin"))
    return b"DEIMDIR1" + bytes([VERSION, FIRST_DATA_BANK, data[-1] - (FIRST_DATA_BANK - 1), sprites[0],
                                len(sprites), 0, 0, 0])


def main():
    """rom_dir.py <gfx_dir>: writes <gfx_dir>/rom_dir.inc and removes what an
    older build left for the level's editable copy (source_bank_*.bin,
    source_banks.inc), which the ROM no longer carries."""
    gfx = Path(sys.argv[1])
    d = directory(gfx)
    with open(gfx / "rom_dir.inc", "w") as fp:
        fp.write("; generated by tools/rom_dir.py\n.db " + ", ".join(f"${b:02X}" for b in d) + "\n")
    for old in list(gfx.glob("source_bank_*.bin")) + [gfx / "source_banks.inc"]:
        old.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
